//! A git-tag channel
//! (`{ git = "<url>", branch = "main", path = ".", tag = "v{version}", adopt = [..] }`):
//! each release is a commit on a distribution repository's branch, tagged.
//! It serves private crates, and Go, Swift and PHP natively (`path` and a
//! tag prefix such as `go/v{version}` put a module in a subdirectory).
//!
//! Publishing fetches the branch tip alone, removes the files the previous
//! release's `.crucible` lists, writes the package's paths, commits, tags,
//! and pushes branch and tag with `git push --atomic`, so a failed push
//! leaves neither. It never re-tags: an existing tag is compared, never
//! moved. Everything else in the repository (`NOTICE`, workflows) stays.
//! A tree with no `.crucible` predates Crucible and is adopted once: the
//! `adopt` paths, which the old publisher owned, are removed.
//!
//! Credentials are Git's own: an SSH agent or a credential helper. A URL
//! that carries a password or token is refused.

use std::collections::BTreeMap;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use semver::Version;
use tempfile::TempDir;

use crate::archive::{PackageFile, extract_tree_archive, is_relative_path, package_files};
use crate::channel::{Channel, ChannelError, PublishOutcome, PublishRequest, Published};
use crate::command::{CommandLine, CommandRunner, SystemRunner};
use crate::legacy::{LegacyRecord, SDK_RELEASE_FILE};
use crate::provenance::{MODEL_FILE, OWNERSHIP_FILE, PROVENANCE_FILE, Provenance};
use crate::release::{LastRelease, ReleaseRef, highest_stable};

/// The `.crucible` marker generators wrote before it listed paths. A tree
/// holding it is adopted like one with no marker.
const LEGACY_MARKER: &str =
    "Generated by crucible. This directory is emptied and rewritten on every run.\n";

/// How many paths one `git hash-object` names, to stay within Windows'
/// command-line limit.
const HASH_CHUNK: usize = 100;

/// A distribution repository, one branch, one directory and one tag line.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GitChannelConfig {
    /// The repository: an SSH or HTTPS URL, never with a password or token.
    pub url: String,
    pub branch: String,
    /// The package's directory in the repository, `.` for the root.
    pub path: String,
    /// The tag template, with `{version}` exactly once.
    pub tag: String,
    /// Paths under `path` the pre-Crucible publisher owned, removed once
    /// when the tree has no `.crucible`.
    pub adopt: Vec<String>,
}

impl GitChannelConfig {
    /// `branch = "main"`, `path = "."`, `tag = "v{version}"`, no `adopt`.
    pub fn new(url: impl Into<String>) -> Self {
        Self {
            url: url.into(),
            branch: "main".into(),
            path: ".".into(),
            tag: "v{version}".into(),
            adopt: Vec::new(),
        }
    }
}

/// A tag template such as `v{version}` or `go/v{version}`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TagTemplate {
    prefix: String,
    suffix: String,
}

impl TagTemplate {
    pub fn parse(template: &str) -> Result<Self, String> {
        let (prefix, suffix) = template
            .split_once("{version}")
            .ok_or_else(|| format!("{template:?} has no {{version}}"))?;
        if suffix.contains("{version}") {
            return Err(format!("{template:?} has {{version}} twice"));
        }
        if format!("{prefix}{suffix}").contains(['{', '}']) {
            return Err(format!("{template:?}: only {{version}} is substituted"));
        }
        Ok(Self {
            prefix: prefix.to_owned(),
            suffix: suffix.to_owned(),
        })
    }

    pub fn render(&self, version: &Version) -> String {
        format!("{}{version}{}", self.prefix, self.suffix)
    }

    /// The version a tag names, if it belongs to this line.
    pub fn version_of(&self, tag: &str) -> Option<Version> {
        let middle = tag.strip_prefix(&self.prefix)?.strip_suffix(&self.suffix)?;
        Version::parse(middle).ok()
    }
}

/// See the [module documentation](self).
pub struct GitTagChannel {
    config: GitChannelConfig,
    template: TagTemplate,
    runner: Box<dyn CommandRunner>,
    git: String,
}

impl GitTagChannel {
    /// The channel, run with the `git` on `PATH`.
    pub fn new(config: &GitChannelConfig) -> Result<Self, ChannelError> {
        Self::with_runner(config, Box::new(SystemRunner))
    }

    /// The channel, run through `runner`.
    pub fn with_runner(
        config: &GitChannelConfig,
        runner: Box<dyn CommandRunner>,
    ) -> Result<Self, ChannelError> {
        let invalid = |reason: String| ChannelError::Invalid {
            channel: format!("git {}", config.url),
            reason,
        };
        if config.url.is_empty() || config.url.starts_with('-') {
            return Err(invalid("not a repository URL".into()));
        }
        if carries_credential(&config.url) {
            return Err(invalid(
                "the URL carries a password or token; Git's SSH agent or credential helper supplies credentials".into(),
            ));
        }
        if config.branch.is_empty()
            || config.branch.starts_with('-')
            || config
                .branch
                .contains(|c: char| c.is_whitespace() || c.is_control())
        {
            return Err(invalid(format!("{:?} is not a branch name", config.branch)));
        }
        if config.path != "." && !is_relative_path(&config.path) {
            return Err(invalid(format!(
                "path {:?} is not a relative, /-separated path",
                config.path
            )));
        }
        if let Some(bad) = config.adopt.iter().find(|path| !is_relative_path(path)) {
            return Err(invalid(format!(
                "adopt {bad:?} is not a relative, /-separated path"
            )));
        }
        let template = TagTemplate::parse(&config.tag).map_err(invalid)?;
        Ok(Self {
            config: config.clone(),
            template,
            runner,
            git: "git".into(),
        })
    }

    /// Runs this program instead of `git`.
    pub fn with_git(mut self, program: impl Into<String>) -> Self {
        self.git = program.into();
        self
    }

    pub fn template(&self) -> &TagTemplate {
        &self.template
    }

    fn unreadable(&self, reason: impl Into<String>) -> ChannelError {
        ChannelError::Unreadable {
            channel: self.describe(),
            reason: reason.into(),
        }
    }

    fn failed(&self, reason: impl Into<String>) -> ChannelError {
        ChannelError::Publish {
            channel: self.describe(),
            reason: reason.into(),
        }
    }

    fn artifact_error(&self, path: &Path, reason: impl Into<String>) -> ChannelError {
        ChannelError::Artifact {
            channel: self.describe(),
            path: path.to_owned(),
            reason: reason.into(),
        }
    }

    /// `git`, with no prompt for credentials, no line-ending conversion
    /// (the bytes written are the bytes tested) and no `ext::` transport.
    fn git(&self) -> CommandLine {
        CommandLine::new(&self.git)
            .args([
                "-c",
                "protocol.ext.allow=never",
                "-c",
                "core.autocrlf=false",
                "-c",
                "core.safecrlf=false",
                "-c",
                "core.longpaths=true",
                "-c",
                "advice.detachedHead=false",
            ])
            .env("GIT_TERMINAL_PROMPT", "0")
    }

    fn git_in(&self, repo: &Path) -> CommandLine {
        self.git().arg("-C").arg(repo.to_string_lossy())
    }

    fn run(&self, command: CommandLine) -> Result<Vec<u8>, String> {
        let output = self
            .runner
            .run(&command)
            .map_err(|error| error.to_string())?;
        if output.success {
            Ok(output.stdout)
        } else {
            let shown: Vec<&str> = command
                .args
                .iter()
                .map(String::as_str)
                .skip_while(|arg| *arg == "-c" || arg.contains('='))
                .collect();
            Err(format!(
                "`git {}` failed: {}",
                shown.join(" "),
                output.stderr_text()
            ))
        }
    }

    fn run_text(&self, command: CommandLine) -> Result<String, String> {
        self.run(command)
            .map(|out| String::from_utf8_lossy(&out).trim().to_owned())
    }

    /// Every tag on the remote, with the commit it names (annotated tags
    /// peeled).
    fn remote_tags(&self) -> Result<BTreeMap<String, String>, ChannelError> {
        let text = self
            .run_text(
                self.git()
                    .args(["ls-remote", "--tags"])
                    .arg(&self.config.url),
            )
            .map_err(|reason| self.unreadable(reason))?;
        let mut direct = BTreeMap::new();
        let mut peeled = BTreeMap::new();
        for line in text.lines() {
            let Some((sha, name)) = line
                .split_once('\t')
                .and_then(|(sha, refname)| Some((sha, refname.strip_prefix("refs/tags/")?)))
            else {
                continue;
            };
            match name.strip_suffix("^{}") {
                Some(name) => peeled.insert(name.to_owned(), sha.to_owned()),
                None => direct.insert(name.to_owned(), sha.to_owned()),
            };
        }
        Ok(direct
            .into_iter()
            .map(|(name, sha)| {
                let commit = peeled.remove(&name).unwrap_or(sha);
                (name, commit)
            })
            .collect())
    }

    /// A bare scratch repository holding `tag` alone, fetched at depth 1.
    fn fetch_tag(&self, tag: &str) -> Result<TempDir, String> {
        let scratch = tempfile::tempdir().map_err(|error| error.to_string())?;
        self.run(
            self.git()
                .args(["init", "-q", "--bare"])
                .arg(scratch.path().to_string_lossy()),
        )?;
        self.run(
            self.git_in(scratch.path())
                .args(["fetch", "-q", "--depth", "1", "--no-tags"])
                .arg(&self.config.url)
                .arg(format!("+refs/tags/{tag}:refs/tags/{tag}")),
        )?;
        Ok(scratch)
    }

    /// The blobs under the channel's `path` at `rev`: path relative to
    /// `path` → (mode, object id).
    fn tree(&self, repo: &Path, rev: &str) -> Result<BTreeMap<String, (String, String)>, String> {
        let out = self.run(self.git_in(repo).args(["ls-tree", "-r", "-z", rev]))?;
        let prefix = if self.config.path == "." {
            String::new()
        } else {
            format!("{}/", self.config.path)
        };
        let mut entries = BTreeMap::new();
        for record in out.split(|byte| *byte == 0).filter(|r| !r.is_empty()) {
            let record = String::from_utf8_lossy(record);
            let Some((meta, path)) = record.split_once('\t') else {
                return Err(format!("unexpected ls-tree output {record:?}"));
            };
            let mut meta = meta.split(' ');
            let (Some(mode), Some(_kind), Some(sha)) = (meta.next(), meta.next(), meta.next())
            else {
                return Err(format!("unexpected ls-tree output {record:?}"));
            };
            if let Some(relative) = path.strip_prefix(&prefix) {
                entries.insert(relative.to_owned(), (mode.to_owned(), sha.to_owned()));
            }
        }
        Ok(entries)
    }

    fn blob(&self, repo: &Path, sha: &str) -> Result<Vec<u8>, String> {
        self.run(self.git_in(repo).args(["cat-file", "blob", sha]))
    }

    /// The package tree an artifact holds: the directory itself, or its
    /// tree archive unpacked into a scratch directory (kept alive by the
    /// returned guard).
    fn package(&self, artifact: &Path) -> Result<(Option<TempDir>, PathBuf), ChannelError> {
        if artifact.is_dir() {
            return Ok((None, artifact.to_owned()));
        }
        if !artifact.is_file() {
            return Err(self.artifact_error(artifact, "it does not exist"));
        }
        let scratch = tempfile::tempdir()
            .map_err(|error| self.artifact_error(artifact, error.to_string()))?;
        extract_tree_archive(artifact, scratch.path()).map_err(|error| {
            self.artifact_error(artifact, format!("not a tree archive: {error}"))
        })?;
        let root = scratch.path().to_owned();
        Ok((Some(scratch), root))
    }

    fn files(&self, artifact: &Path, root: &Path) -> Result<Vec<PackageFile>, ChannelError> {
        let files = package_files(root)
            .map_err(|error| self.artifact_error(artifact, error.to_string()))?;
        if files.is_empty() {
            return Err(self.artifact_error(artifact, "the package is empty"));
        }
        Ok(files)
    }

    /// Git's object ids for `files`' contents, as the files are (no
    /// filters), in order.
    fn hash(&self, repo: &Path, files: &[PackageFile]) -> Result<Vec<String>, String> {
        let mut ids = Vec::with_capacity(files.len());
        for chunk in files.chunks(HASH_CHUNK) {
            let text = self.run_text(
                self.git_in(repo)
                    .args(["hash-object", "--no-filters", "--"])
                    .args(chunk.iter().map(|file| file.absolute.to_string_lossy())),
            )?;
            ids.extend(text.lines().map(str::to_owned));
        }
        if ids.len() != files.len() {
            return Err("git hash-object returned the wrong number of ids".into());
        }
        Ok(ids)
    }

    /// Compares the package's paths with the tree at `rev`. Only the
    /// package's own paths count: the repository's other files are not
    /// the release's.
    fn compare(&self, repo: &Path, rev: &str, files: &[PackageFile]) -> Result<Published, String> {
        let tree = self.tree(repo, rev)?;
        let ids = self.hash(repo, files)?;
        let mut differences = Vec::new();
        for (file, id) in files.iter().zip(&ids) {
            match tree.get(&file.path) {
                None => differences.push(format!("{} is not in the tag", file.path)),
                Some((mode, _)) if !matches!(mode.as_str(), "100644" | "100755") => {
                    differences.push(format!("{} is not a file in the tag", file.path));
                }
                Some((_, sha)) if sha != id => {
                    differences.push(format!("{} differs", file.path));
                }
                Some(_) => {}
            }
        }
        Ok(if differences.is_empty() {
            Published::SameBytes
        } else {
            let more = differences.len().saturating_sub(5);
            differences.truncate(5);
            let mut detail = differences.join("; ");
            if more > 0 {
                detail.push_str(&format!("; and {more} more"));
            }
            Published::DifferentBytes { detail }
        })
    }

    fn pathspec(&self) -> &str {
        &self.config.path
    }

    /// Removes what the previous release owned under `target`: the paths
    /// its `.crucible` lists or, with none, the `adopt` paths. Returns what
    /// it did, for the log.
    fn clear_previous(&self, root: &Path, target: &Path) -> Result<String, String> {
        let marker = target.join(OWNERSHIP_FILE);
        let listed = match fs::read_to_string(&marker) {
            Ok(text) if text == LEGACY_MARKER => None,
            Ok(text) => Some(serde_json::from_str::<Vec<String>>(&text).map_err(|error| {
                format!("{OWNERSHIP_FILE} in the repository is not a path list: {error}")
            })?),
            Err(error) if error.kind() == io::ErrorKind::NotFound => None,
            Err(error) => return Err(error.to_string()),
        };
        match listed {
            Some(paths) => {
                for path in &paths {
                    if !is_relative_path(path) {
                        return Err(format!(
                            "{OWNERSHIP_FILE} in the repository lists {path:?}, which is not a relative path"
                        ));
                    }
                    let full = safe_join(root, target, path)?;
                    match fs::symlink_metadata(&full) {
                        Ok(metadata) if metadata.is_dir() => {
                            return Err(format!(
                                "{OWNERSHIP_FILE} lists {path}, which is a directory"
                            ));
                        }
                        Ok(_) => fs::remove_file(&full).map_err(|error| error.to_string())?,
                        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
                        Err(error) => return Err(error.to_string()),
                    }
                    prune_empty_parents(target, &full);
                }
                Ok(format!(
                    "removed the {} paths the previous {OWNERSHIP_FILE} lists",
                    paths.len()
                ))
            }
            None => {
                let mut removed = Vec::new();
                for path in &self.config.adopt {
                    let full = safe_join(root, target, path)?;
                    match fs::symlink_metadata(&full) {
                        Ok(metadata) if metadata.is_dir() => {
                            fs::remove_dir_all(&full).map_err(|error| error.to_string())?;
                        }
                        Ok(_) => fs::remove_file(&full).map_err(|error| error.to_string())?,
                        Err(error) if error.kind() == io::ErrorKind::NotFound => continue,
                        Err(error) => return Err(error.to_string()),
                    }
                    removed.push(path.as_str());
                }
                Ok(if removed.is_empty() {
                    format!("no previous {OWNERSHIP_FILE}; nothing to adopt")
                } else {
                    format!(
                        "no previous {OWNERSHIP_FILE}; adopted the tree, removing {}",
                        removed.join(", ")
                    )
                })
            }
        }
    }

    /// Whether commits need an identity supplied: none is configured.
    fn needs_identity(&self, repo: &Path) -> bool {
        let configured = self
            .run_text(self.git_in(repo).args(["config", "user.email"]))
            .is_ok_and(|email| !email.is_empty());
        !configured && std::env::var_os("GIT_AUTHOR_EMAIL").is_none()
    }
}

impl Channel for GitTagChannel {
    fn describe(&self) -> String {
        let mut shown = format!("git {} ({}", self.config.url, self.config.branch);
        if self.config.path != "." {
            shown.push_str(&format!(", {}", self.config.path));
        }
        shown.push_str(&format!(", {})", self.config.tag));
        shown
    }

    fn latest(&self) -> Result<Option<ReleaseRef>, ChannelError> {
        let tags = self.remote_tags()?;
        let releases: Vec<(Version, &String, &String)> = tags
            .iter()
            .filter_map(|(tag, commit)| Some((self.template.version_of(tag)?, tag, commit)))
            .collect();
        let Some(version) = highest_stable(releases.iter().map(|(version, _, _)| version)) else {
            return Ok(None);
        };
        let (version, tag, commit) = releases
            .iter()
            .find(|(candidate, _, _)| candidate == version)
            .expect("listed above");
        Ok(Some(ReleaseRef {
            version: version.clone(),
            artifact: format!("git:{commit}"),
            locator: (*tag).clone(),
        }))
    }

    fn read_release(&self, release: &ReleaseRef) -> Result<LastRelease, ChannelError> {
        let tag = &release.locator;
        let scratch = self
            .fetch_tag(tag)
            .map_err(|reason| self.unreadable(reason))?;
        let repo = scratch.path();
        let commit = self
            .run_text(
                self.git_in(repo)
                    .args(["rev-parse", "--verify", "-q"])
                    .arg(format!("refs/tags/{tag}^{{commit}}")),
            )
            .map_err(|reason| self.unreadable(reason))?;
        if format!("git:{commit}") != release.artifact {
            return Err(self.unreadable(format!("{tag} moved while it was read")));
        }
        let tree = self
            .tree(repo, &format!("refs/tags/{tag}"))
            .map_err(|reason| self.unreadable(reason))?;
        let read = |name: &str| -> Result<Option<Vec<u8>>, ChannelError> {
            tree.get(name)
                .map(|(_, sha)| self.blob(repo, sha))
                .transpose()
                .map_err(|reason| self.unreadable(reason))
        };
        let provenance = read(PROVENANCE_FILE)?
            .map(|bytes| Provenance::parse(&bytes))
            .transpose()
            .map_err(|reason| self.unreadable(format!("{tag}: {reason}")))?;
        let model = read(MODEL_FILE)?
            .map(String::from_utf8)
            .transpose()
            .map_err(|_| self.unreadable(format!("{tag}: {MODEL_FILE} is not UTF-8")))?;
        let legacy = read(SDK_RELEASE_FILE)?
            .map(|bytes| LegacyRecord::sdk_release(&bytes))
            .transpose()
            .map_err(|reason| self.unreadable(format!("{tag}: {reason}")))?;
        Ok(LastRelease {
            version: release.version.clone(),
            artifact: release.artifact.clone(),
            provenance,
            model,
            legacy,
        })
    }

    fn check_published(
        &self,
        version: &Version,
        artifact: &Path,
    ) -> Result<Published, ChannelError> {
        let tag = self.template.render(version);
        let (_scratch, root) = self.package(artifact)?;
        let files = self.files(artifact, &root)?;
        if !self.remote_tags()?.contains_key(&tag) {
            return Ok(Published::Absent);
        }
        let scratch = self
            .fetch_tag(&tag)
            .map_err(|reason| self.unreadable(reason))?;
        self.compare(scratch.path(), &format!("refs/tags/{tag}"), &files)
            .map_err(|reason| self.unreadable(reason))
    }

    fn describe_publish(&self, request: &PublishRequest<'_>) -> Result<Vec<String>, ChannelError> {
        let (_scratch, root) = self.package(request.artifact)?;
        let files = self.files(request.artifact, &root)?;
        let tag = self.template.render(request.version);
        let (url, branch) = (&self.config.url, &self.config.branch);
        let adopt = if self.config.adopt.is_empty() {
            String::new()
        } else {
            format!(
                " (or, with none, the adopted {})",
                self.config.adopt.join(", ")
            )
        };
        Ok(vec![
            format!("git fetch --depth 1 {url} refs/heads/{branch}"),
            format!(
                "remove what {}/{OWNERSHIP_FILE} lists{adopt}, then write the package's {} files there",
                self.config.path,
                files.len()
            ),
            format!(
                "git commit -m 'Release {} {}'",
                request.sdk, request.version
            ),
            format!("git tag {tag}"),
            format!("git push --atomic {url} HEAD:refs/heads/{branch} refs/tags/{tag}"),
        ])
    }

    fn publish(&self, request: &PublishRequest<'_>) -> Result<PublishOutcome, ChannelError> {
        let (_package_scratch, root) = self.package(request.artifact)?;
        let files = self.files(request.artifact, &root)?;
        let tag = self.template.render(request.version);
        let branch = &self.config.branch;
        self.run(
            self.git()
                .args(["check-ref-format"])
                .arg(format!("refs/tags/{tag}")),
        )
        .map_err(|_| self.failed(format!("{tag:?} is not a valid tag name")))?;
        let work = tempfile::tempdir().map_err(|error| self.failed(error.to_string()))?;
        let repo = work.path().join("checkout");
        let repo = repo.as_path();
        let step = |result: Result<Vec<u8>, String>| result.map_err(|reason| self.failed(reason));
        step(self.run(self.git().args(["init", "-q"]).arg(repo.to_string_lossy())))?;
        let heads = self
            .run_text(
                self.git()
                    .args(["ls-remote", "--heads"])
                    .arg(&self.config.url)
                    .arg(format!("refs/heads/{branch}")),
            )
            .map_err(|reason| self.unreadable(reason))?;
        if heads.is_empty() {
            // A new repository, or a new branch: the release starts it.
            step(
                self.run(
                    self.git_in(repo)
                        .args(["checkout", "-q", "--orphan", branch]),
                ),
            )?;
        } else {
            step(
                self.run(
                    self.git_in(repo)
                        .args(["fetch", "-q", "--depth", "1", "--no-tags"])
                        .arg(&self.config.url)
                        .arg(format!(
                            "+refs/heads/{branch}:refs/remotes/channel/{branch}"
                        )),
                ),
            )?;
            step(
                self.run(
                    self.git_in(repo)
                        .args(["checkout", "-q", "-B", branch])
                        .arg(format!("refs/remotes/channel/{branch}")),
                ),
            )?;
        }
        let target = if self.config.path == "." {
            repo.to_owned()
        } else {
            safe_join(repo, repo, &self.config.path).map_err(|reason| self.failed(reason))?
        };
        let cleared = self
            .clear_previous(repo, &target)
            .map_err(|reason| self.failed(reason))?;
        for file in &files {
            let destination =
                safe_join(repo, &target, &file.path).map_err(|reason| self.failed(reason))?;
            write_file(&file.absolute, &destination)
                .map_err(|error| self.failed(format!("writing {}: {error}", file.path)))?;
        }
        // `--force`: a package file the repository's .gitignore matches is
        // still the package's. The checkout holds nothing else new.
        step(
            self.run(
                self.git_in(repo)
                    .args(["add", "--all", "--force", "--"])
                    .arg(self.pathspec()),
            ),
        )?;
        let mut message = format!("Release {} {}", request.sdk, request.version);
        if let Some(commit) = request.source_commit {
            message.push_str(&format!("\n\nBuilt from {commit}."));
        }
        let mut commit = self.git_in(repo);
        if self.needs_identity(repo) {
            commit = commit.args([
                "-c",
                "user.name=Crucible",
                "-c",
                "user.email=crucible@noreply.invalid",
            ]);
        }
        step(
            self.run(
                commit
                    .args(["commit", "-q", "--allow-empty", "-m"])
                    .arg(message),
            ),
        )?;
        step(self.run(self.git_in(repo).args(["tag", "--"]).arg(&tag)))?;
        step(
            self.run(
                self.git_in(repo)
                    .args(["push", "-q", "--atomic"])
                    .arg(&self.config.url)
                    .arg(format!("HEAD:refs/heads/{branch}"))
                    .arg(format!("refs/tags/{tag}:refs/tags/{tag}")),
            ),
        )?;
        let head = self
            .run_text(self.git_in(repo).args(["rev-parse", "HEAD"]))
            .map_err(|reason| self.failed(reason))?;
        Ok(PublishOutcome {
            detail: format!(
                "pushed {tag} at {} to {branch}; {cleared}",
                &head[..head.len().min(12)]
            ),
        })
    }
}

/// `base/relative`, refusing a path whose existing components under `root`
/// include a symlink: a distribution repository could otherwise point a
/// package directory anywhere on disk.
fn safe_join(root: &Path, base: &Path, relative: &str) -> Result<PathBuf, String> {
    if !is_relative_path(relative) {
        return Err(format!("{relative:?} is not a relative path"));
    }
    let full = base.join(relative);
    let mut current = root.to_owned();
    let inside = full
        .strip_prefix(root)
        .map_err(|_| format!("{relative} is outside the checkout"))?;
    for component in inside.components() {
        current.push(component);
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(format!(
                    "{} is a symlink in the repository; refusing to write through it",
                    current.strip_prefix(root).unwrap_or(&current).display()
                ));
            }
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => break,
            Err(error) => return Err(error.to_string()),
        }
    }
    Ok(full)
}

fn write_file(source: &Path, destination: &Path) -> io::Result<()> {
    if let Some(parent) = destination.parent() {
        fs::create_dir_all(parent)?;
    }
    if destination.is_dir() {
        // An empty directory left by a removed file's parent.
        fs::remove_dir(destination)?;
    }
    fs::copy(source, destination).map(|_| ())
}

/// Removes `path`'s empty parent directories, up to `base`.
fn prune_empty_parents(base: &Path, path: &Path) {
    let mut current = path.parent();
    while let Some(dir) = current {
        if dir == base || !dir.starts_with(base) || fs::remove_dir(dir).is_err() {
            break;
        }
        current = dir.parent();
    }
}

/// Whether a repository URL carries a password or token. A user name such
/// as `git@` is fine over SSH; over HTTP(S) a user name can only be a
/// token, since credentials come from Git's helpers.
fn carries_credential(url: &str) -> bool {
    match url.split_once("://") {
        None => url
            .split_once('@')
            .is_some_and(|(user, _)| user.contains(':')),
        Some((scheme, rest)) => {
            let authority = rest.split(['/', '?', '#']).next().unwrap_or("");
            authority.rsplit_once('@').is_some_and(|(userinfo, _)| {
                userinfo.contains(':')
                    || matches!(scheme.to_ascii_lowercase().as_str(), "http" | "https")
            })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{GitChannelConfig, GitTagChannel, TagTemplate, carries_credential};
    use semver::Version;

    #[test]
    fn tag_templates() {
        let plain = TagTemplate::parse("v{version}").unwrap();
        let v = Version::new(0, 2, 1);
        assert_eq!(plain.render(&v), "v0.2.1");
        assert_eq!(plain.version_of("v0.2.1"), Some(v.clone()));
        assert_eq!(plain.version_of("go/v0.2.1"), None);
        assert_eq!(plain.version_of("v0.2"), None);
        assert_eq!(plain.version_of("v01.2.3"), None);
        assert_eq!(
            plain.version_of("v1.0.0-rc.1").unwrap().pre.as_str(),
            "rc.1"
        );
        let go = TagTemplate::parse("go/v{version}").unwrap();
        assert_eq!(go.render(&v), "go/v0.2.1");
        assert_eq!(go.version_of("go/v0.2.1"), Some(v.clone()));
        assert_eq!(go.version_of("v0.2.1"), None);
        let suffixed = TagTemplate::parse("sdk-{version}-rust").unwrap();
        assert_eq!(
            suffixed.version_of("sdk-1.2.3-rust"),
            Some(Version::new(1, 2, 3))
        );
        for bad in ["v", "{version}{version}", "{name}-{version}", "v{version"] {
            assert!(TagTemplate::parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn urls_with_credentials_are_refused() {
        for bad in [
            "https://token@github.com/o/r.git",
            "https://user:pw@github.com/o/r.git",
            "ssh://git:pw@github.com/o/r.git",
            "git:pw@github.com:o/r.git",
        ] {
            assert!(carries_credential(bad), "{bad}");
        }
        for good in [
            "git@github.com:Operation-Pigeon/mailpigeon-rs.git",
            "ssh://git@github.com/o/r.git",
            "https://github.com/o/r.git",
            "file:///C:/repos/r.git",
            "C:/repos/r.git",
        ] {
            assert!(!carries_credential(good), "{good}");
        }
    }

    #[test]
    fn configurations_are_checked() {
        let ok = GitChannelConfig::new("git@github.com:o/r.git");
        assert!(GitTagChannel::new(&ok).is_ok());
        let bad = |change: fn(&mut GitChannelConfig)| {
            let mut config = ok.clone();
            change(&mut config);
            GitTagChannel::new(&config).is_err()
        };
        assert!(bad(|c| c.url = "--upload-pack=evil".into()));
        assert!(bad(|c| c.url = "https://t@github.com/o/r".into()));
        assert!(bad(|c| c.branch = "-x".into()));
        assert!(bad(|c| c.branch = "a b".into()));
        assert!(bad(|c| c.path = "../x".into()));
        assert!(bad(|c| c.path = "/abs".into()));
        assert!(bad(|c| c.tag = "release".into()));
        assert!(bad(|c| c.adopt = vec!["../outside".into()]));
    }
}

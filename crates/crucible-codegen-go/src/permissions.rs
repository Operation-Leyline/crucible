//! `permissions/permissions.go` (docs/permissions.md §6.3): a sub-package of
//! the client module, so a model named `GraphPermission` or `Permissions`
//! keeps its name in the root package. Per resource an open string type,
//! `GraphPermission`, whose constants follow the convention of a model enum
//! (`GraphPermissionRead`) and which keeps any value a newer server (or an
//! audience this client is not) writes; deprecated aliases as deprecated
//! constants that `Canonical()` maps to their primaries; and `Permissions`,
//! the registry a console's grant picker reads. Internal permissions never
//! appear, whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{
    ClientResource, client_resources, code_span, constant_symbol, notes, primary,
};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use crate::{exported, go_doc, go_doc_for, literal};

/// Where the sub-package lives, relative to the module root.
pub(crate) const PATH: &str = "permissions/permissions.go";

/// The names the sub-package declares whatever the model.
const FIXED_NAMES: [&str; 3] = [
    "PermissionDescription",
    "ResourcePermissions",
    "Permissions",
];

/// The registry's record types. They are declared in the sub-package, so
/// they cannot take a model's name.
const RECORDS: &str = r#"// PermissionDescription is one permission in the registry.
type PermissionDescription struct {
	// Value is what grants store.
	Value string `json:"value"`
	// Description is the model's documentation for the permission, empty when it has none.
	Description string `json:"description"`
	// Tier is "public", "permissionOnly" or "notGrantable": a plain string, since a newer server may add tiers.
	Tier string `json:"tier"`
	// Grantable is false for a bundle the service confers whole: never offer it in a picker.
	Grantable bool `json:"grantable"`
	// Deprecated is true for a deprecated permission, every alias included.
	Deprecated bool `json:"deprecated"`
	// AliasOf is, for a deprecated alias, the value it stands for; empty otherwise.
	AliasOf string `json:"aliasOf,omitempty"`
}

// ResourcePermissions is one resource type's permissions, sorted by value.
type ResourcePermissions struct {
	// ResourceType is the authorization name grants use for the resource type.
	ResourceType string `json:"resourceType"`
	// Permissions are the type's permissions, deprecated aliases included.
	Permissions []PermissionDescription `json:"permissions"`
}

"#;

/// The resources a client sees, sorted by authorization name, each with its
/// Go type name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| {
            (
                format!("{}Permission", exported(service.name_of(client.id))),
                client,
            )
        })
        .collect()
}

/// Every name the sub-package declares must be distinct: two resources
/// whose names spell the same Go type, two permissions of one resource
/// that spell the same constant, or a constant that spells a type.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    let mut names: BTreeSet<String> = FIXED_NAMES.map(str::to_owned).into();
    for (name, client) in resources(service) {
        if !names.insert(name.clone()) {
            diagnostics.push(
                &service.id,
                format!("Go permission type `{name}` collides with another declaration of package permissions"),
            );
        }
        for permission in &client.permissions {
            let constant = format!("{name}{}", exported(&constant_symbol(&permission.symbol)));
            if !names.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{}` spells the Go constant `{constant}`, which another declaration of package permissions has",
                        permission.symbol,
                        service.name_of(client.id)
                    ),
                );
            }
        }
    }
}

/// The sub-package's one file, or `None` when no resource has a permission
/// a client may see.
pub(crate) fn emit(service: &Service) -> Option<String> {
    let resources = resources(service);
    if resources.is_empty() {
        return None;
    }
    let mut out = format!(
        "// Code generated by Crucible. DO NOT EDIT.\n\n// Package permissions holds the permissions the {} API's resources accept, as the values grants store, and Permissions, the registry a console's grant picker reads. A value this client does not know is kept as it is; internal permissions never appear.\npackage permissions\n\n",
        exported(service.id.name())
    );
    out.push_str(RECORDS);
    let mut registry = String::new();
    for (name, client) in &resources {
        let shape = service.name_of(client.id);
        let resource = client.resource;
        go_doc(
            &mut out,
            (service, crate::links::Package::Permissions),
            "",
            name,
            Some(&format!(
                "The permissions `{shape}` accepts (`{}`), by the values grants store.",
                resource.name
            )),
        );
        out.push_str(&format!(
            "// {name} preserves unrecognized string values.\ntype {name} string\n\nconst (\n"
        ));
        let mut constants: Vec<(String, String, String)> = Vec::new();
        for permission in &client.permissions {
            let constant = format!("{name}{}", exported(&constant_symbol(&permission.symbol)));
            let mut docs = permission.docs.clone().unwrap_or_default();
            if permission.alias_of.is_some() {
                if !docs.trim().is_empty() {
                    docs.push_str("\n\n");
                }
                docs.push_str(&format!(
                    "An alias of {}.",
                    code_span(&primary(resource, permission).value)
                ));
            }
            let mut comment = String::new();
            go_doc_for(
                &mut comment,
                (service, crate::links::Package::Permissions),
                "\t",
                &constant,
                Some(docs.as_str()).filter(|d| !d.trim().is_empty()),
                &notes(permission),
            );
            constants.push((comment, constant, literal(&permission.value)));
        }
        // gofmt aligns the specs of a run that no comment interrupts.
        let mut start = 0;
        while start < constants.len() {
            let end = (start + 1..constants.len())
                .find(|&next| !constants[next].0.is_empty())
                .unwrap_or(constants.len());
            let width = constants[start..end]
                .iter()
                .map(|(_, constant, _)| constant.len())
                .max()
                .unwrap_or_default();
            for (comment, constant, value) in &constants[start..end] {
                out.push_str(comment);
                out.push_str(&format!("\t{constant:<width$} {name} = {value}\n"));
            }
            start = end;
        }
        out.push_str(")\n\n");
        go_doc_for(
            &mut out,
            (service, crate::links::Package::Permissions),
            "",
            "Canonical",
            Some(
                "The permission a deprecated alias stands for; any other value, an unknown one included, is itself.",
            ),
            &DocNotes::default(),
        );
        let aliases = client.aliases();
        if aliases.is_empty() {
            out.push_str(&format!(
                "func (p {name}) Canonical() {name} {{\n\treturn p\n}}\n\n"
            ));
        } else {
            out.push_str(&format!(
                "func (p {name}) Canonical() {name} {{\n\tswitch p {{\n"
            ));
            for (alias, primary) in aliases {
                out.push_str(&format!(
                    "\tcase {name}{}:\n\t\treturn {name}{}\n",
                    exported(&constant_symbol(&alias.symbol)),
                    exported(&constant_symbol(&primary.symbol))
                ));
            }
            out.push_str("\tdefault:\n\t\treturn p\n\t}\n}\n\n");
        }
        registry.push_str(&format!(
            "\t{{\n\t\tResourceType: {},\n\t\tPermissions: []PermissionDescription{{\n",
            literal(&resource.name)
        ));
        for entry in client.entries() {
            let alias = entry
                .alias_of
                .map(|primary| format!(", AliasOf: {}", literal(primary)))
                .unwrap_or_default();
            registry.push_str(&format!(
                "\t\t\t{{Value: {}, Description: {}, Tier: {}, Grantable: {}, Deprecated: {}{alias}}},\n",
                literal(entry.value),
                literal(entry.description),
                literal(entry.tier),
                entry.grantable,
                entry.deprecated,
            ));
        }
        registry.push_str("\t\t},\n\t},\n");
    }
    go_doc(
        &mut out,
        (service, crate::links::Package::Permissions),
        "",
        "Permissions",
        Some(
            "Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the grantable ones that are not deprecated. Shared by every caller: read it, do not modify it.",
        ),
    );
    out.push_str(&format!(
        "var Permissions = []ResourcePermissions{{\n{registry}}}\n"
    ));
    Some(out)
}

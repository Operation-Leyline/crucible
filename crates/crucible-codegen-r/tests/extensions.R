args <- commandArgs(TRUE)
check <- function(value, label) if (!isTRUE(value)) stop(label, call. = FALSE)
rejects <- function(expression) { result <- tryCatch({ force(expression); NULL }, error = identity); if (is.null(result)) stop('Expected rejection'); result }
library(types.client, lib.loc = args[1L])
ns <- asNamespace('types.client'); codec <- get('.crucible_codec', ns)
parse <- types.client::json_parse
value <- codec(parse('{"mode":42,"names":["a","b"],"sparseNames":["a",null],"sparseMap":{"nil":null,"mode":42}}'), 'example.types#ReadOutput')
check(as.character(value$integer) == '12345678901234567890123456789012345678901234567890', 'Exact integer default')
check(as.character(value$decimal) == '12345678901234567890.12345678901234567890123456789', 'Exact decimal default')
check(inherits(value$mode, 'Mode') && value$mode == 42, 'Unknown intEnum')
check(length(value$sparse_names) == 2L && is.null(value$sparse_names[[2L]]) && 'nil' %in% names(value$sparse_map), 'Sparse native collections')
wire <- codec(value, 'example.types#ReadOutput', TRUE)
check(is.null(wire$sparseMap$nil) && wire$mode == 42, 'Sparse encode')
rejects(codec(parse('["a","a"]'), 'example.types#Names'))
rejects(codec(parse('[null]'), 'example.types#Names'))
rejects(codec(parse('[1,1.0]'), 'example.types#Decimals'))
rejects(codec(parse('[1,1e0]'), 'example.types#Integers'))
check(length(codec(parse('[18446744073709551617,36893488147419103233]'), 'example.types#Integers')) == 2L, 'Distinct exact integer set')
check(length(codec(parse('[1.000000000000000000001,1.000000000000000000002]'), 'example.types#Decimals')) == 2L, 'Distinct exact decimal set')
canonical <- get('.crucible_canonical_number', ns)
check(identical(canonical(types.client::big_decimal('10e999999999999999999999')), canonical(types.client::big_decimal('1e1000000000000000000000'))), 'Arbitrary exponent canonical equality')
rejects(types.client::big_integer('1.5'))
rejects(types.client::Mode(2147483648))
cat('R exact extended types passed\n')

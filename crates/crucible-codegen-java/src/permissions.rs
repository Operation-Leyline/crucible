//! The `<package>.permissions` package (docs/permissions.md §6.3): per
//! resource an open permission type in the open-enum convention
//! (`GraphPermission.READ`), which keeps a value this client does not know
//! and writes it back unchanged, with deprecated aliases as deprecated
//! constants `canonical()` maps to their primaries; and
//! `Permissions.PERMISSIONS`, the registry a console's grant picker reads.
//! A package of its own, so no model name can collide with these. Internal
//! permissions never appear, whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{
    ClientResource, client_resources, constant_symbol, notes, primary, upper_snake,
};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use super::{File, code, field, identifier, javadoc_for, literal};

/// A permission's constant: Java's upper snake case (`upper_snake`), so
/// `read` is `READ` and `mailSend` is `MAIL_SEND`, as TypeScript spells
/// them; `field` keeps `_`, a keyword, out.
fn constant(symbol: &str) -> String {
    field(&upper_snake(symbol))
}

/// The resources a client sees, each with its type's name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| (format!("{}Permission", service.name_of(client.id)), client))
        .collect()
}

/// Two permissions of one resource that Java would spell as one constant.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    for (name, client) in resources(service) {
        if !identifier(&name) {
            diagnostics.push(
                &service.id,
                format!("permission type `{name}` is not a Java identifier"),
            );
        }
        let mut seen = BTreeSet::new();
        for permission in &client.permissions {
            let constant = constant(&constant_symbol(&permission.symbol));
            if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{name}` shares the Java constant `{constant}` with another",
                        permission.symbol
                    ),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client, so they read
/// as runtime sources, bundled only with a client that has permissions.
const PERMISSION_DESCRIPTION: &str = r#"/**
 * One permission in the registry.
 *
 * @param value what grants store
 * @param description the model's documentation for it, empty when it has none
 * @param tier {@code "public"}, {@code "permissionOnly"} or {@code "notGrantable"}: a plain string, since a newer server may add a tier
 * @param grantable false for a bundle the service confers whole: never offer it in a picker
 * @param deprecated whether the model deprecates it; every alias is deprecated
 * @param aliasOf for a deprecated alias, the value it stands for; otherwise {@code null}
 */
public record PermissionDescription(
        java.lang.String value,
        java.lang.String description,
        java.lang.String tier,
        boolean grantable,
        boolean deprecated,
        java.lang.String aliasOf) {}
"#;

const RESOURCE_PERMISSIONS: &str = r#"/**
 * One resource type's permissions, sorted by value.
 *
 * @param resourceType the resource type's authorization name, as grants store it
 * @param permissions its permissions, deprecated aliases included, sorted by value
 */
public record ResourcePermissions(
        java.lang.String resourceType,
        java.util.List<PermissionDescription> permissions) {}
"#;

/// The package's files, none when the client sees no permission.
pub(crate) fn files(service: &Service, package: &str, source: &str) -> Vec<File> {
    let resources = resources(service);
    if resources.is_empty() {
        return Vec::new();
    }
    let header =
        format!("// Generated by Crucible. DO NOT EDIT.\npackage {package}.permissions;\n\n");
    let file = |name: &str, body: String| File {
        path: format!("{source}/permissions/{name}.java"),
        contents: format!("{header}{body}"),
    };
    let mut files = Vec::new();
    let mut registry = Vec::new();
    for (name, client) in &resources {
        files.push(file(name, enumeration(service, name, client)));
        registry.push(entry(client));
    }
    files.push(file(
        "PermissionDescription",
        PERMISSION_DESCRIPTION.to_owned(),
    ));
    files.push(file("ResourcePermissions", RESOURCE_PERMISSIONS.to_owned()));
    let mut body = javadoc_for(
        "",
        None,
        &[
            "The model's permissions as data: the registry a console's grant picker reads."
                .to_owned(),
        ],
        &[],
        &DocNotes::default(),
    );
    body.push_str("public final class Permissions {\n    private Permissions() {}\n\n");
    body.push_str(&javadoc_for(
        "    ",
        None,
        &["Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the {@code grantable} ones that are not {@code deprecated}.".to_owned()],
        &[],
        &DocNotes::default(),
    ));
    body.push_str(&format!(
        "    public static final java.util.List<ResourcePermissions> PERMISSIONS = java.util.List.of(\n{});\n}}\n",
        registry.join(",\n")
    ));
    files.push(file("Permissions", body));
    files
}

/// One resource's open permission type, `GraphPermission`.
fn enumeration(service: &Service, name: &str, client: &ClientResource<'_>) -> String {
    let shape = service.name_of(client.id);
    let resource = client.resource;
    let mut out = javadoc_for(
        "",
        None,
        &[
            format!(
                "The permissions {} accepts ({}), by the values grants store.",
                code(shape),
                code(&resource.name)
            ),
            "Open: a value this client does not know (a newer server's) is kept as it is and written back unchanged, so compare with the constants or {@link #value()}.".to_owned(),
        ],
        &["@param value the permission value, as grants store it".to_owned()],
        &DocNotes::default(),
    );
    out.push_str(&format!(
        "public record {name}(java.lang.String value) {{\n    /**\n     * Requires a non-null value.\n     *\n     * @param value the permission value\n     */\n    public {name} {{\n        java.util.Objects.requireNonNull(value);\n    }}\n\n    /** @return the permission value. */\n    @Override\n    public java.lang.String toString() {{\n        return value;\n    }}\n"
    ));
    for permission in &client.permissions {
        let mut notes = vec![format!("The {} permission.", code(&permission.value))];
        if permission.alias_of.is_some() {
            let primary = primary(resource, permission);
            notes.push(format!(
                "An alias of {}: {{@link #canonical()}} maps it to {{@link #{}}}.",
                code(&primary.value),
                constant(&constant_symbol(&primary.symbol))
            ));
        }
        out.push('\n');
        out.push_str(&javadoc_for(
            "    ",
            permission.docs.as_deref(),
            &notes,
            &[],
            &self::notes(permission),
        ));
        out.push_str(&format!(
            "    public static final {name} {} = new {name}({});\n",
            constant(&constant_symbol(&permission.symbol)),
            literal(&permission.value)
        ));
    }
    out.push('\n');
    out.push_str(&javadoc_for(
        "    ",
        None,
        &["The permission a deprecated alias stands for; any other value, one this client does not know included, is itself.".to_owned()],
        &["@return the primary permission".to_owned()],
        &DocNotes::default(),
    ));
    let aliases = client.aliases();
    if aliases.is_empty() {
        out.push_str(&format!(
            "    public {name} canonical() {{\n        return this;\n    }}\n"
        ));
    } else {
        // By value, not by constant: an unknown instance equal to an alias
        // maps too, and the deprecated constants are never referenced.
        out.push_str(&format!(
            "    public {name} canonical() {{\n        return switch (value) {{\n"
        ));
        for (alias, primary) in aliases {
            out.push_str(&format!(
                "            case {} -> {};\n",
                literal(&alias.value),
                constant(&constant_symbol(&primary.symbol))
            ));
        }
        out.push_str("            default -> this;\n        };\n    }\n");
    }
    out.push_str("}\n");
    out
}

/// The resource's `PERMISSIONS` entry, its permissions sorted by value.
fn entry(client: &ClientResource<'_>) -> String {
    let entries: Vec<String> = client
        .entries()
        .iter()
        .map(|e| {
            format!(
                "            new PermissionDescription({}, {}, {}, {}, {}, {})",
                literal(e.value),
                literal(e.description),
                literal(e.tier),
                e.grantable,
                e.deprecated,
                e.alias_of.map_or("null".to_owned(), literal),
            )
        })
        .collect();
    format!(
        "        new ResourcePermissions({}, java.util.List.of(\n{}))",
        literal(&client.resource.name),
        entries.join(",\n")
    )
}

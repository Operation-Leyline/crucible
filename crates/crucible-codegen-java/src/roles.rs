//! The `<package>.roles` package (docs/roles.md §7 "Clients"): the
//! service's role and scope values as open types in the open-enum
//! convention (`Role.OWNER`, `Scope.ALL_NOTES`), which keep a value this
//! client does not know (a newer server's, a custom role's) and write it
//! back unchanged; and `Roles.ROLES`, the registry a console's role picker
//! reads. A package of its own, as `permissions` is, so no model name can
//! collide with these. Generated from `crucible_codegen_common::roles`'
//! one rule, as every client's is: public roles and scopes only, in
//! catalogue order, and only public permissions in a role's `permissions`.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{constant_symbol, upper_snake};
use crucible_codegen_common::roles::{ClientRole, client_roles, client_scopes, custom};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use super::{File, Links, code, field, javadoc_for, javadoc_linked, literal};

/// A role's or scope's constant: Java's upper snake case, as permissions'.
fn constant(symbol: &str) -> String {
    field(&upper_snake(&constant_symbol(symbol)))
}

/// Two roles (or two scopes) that Java would spell as one constant.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    let roles = client_roles(service);
    if roles.is_empty() {
        return;
    }
    let scopes = client_scopes(service);
    for (what, symbols) in [
        (
            "role",
            roles
                .iter()
                .map(|r| r.role.symbol.as_str())
                .collect::<Vec<_>>(),
        ),
        (
            "scope",
            scopes.iter().map(|s| s.scope.symbol.as_str()).collect(),
        ),
    ] {
        let mut seen = BTreeSet::new();
        for symbol in symbols {
            let constant = constant(symbol);
            if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!("{what} `{symbol}` shares the Java constant `{constant}` with another"),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client.
const ROLE_DESCRIPTION: &str = r#"/**
 * One role in the registry.
 *
 * @param value what bindings store
 * @param description the model's documentation for it, empty when it has none
 * @param scopes the scope values it may be bound at, in catalogue order
 * @param holders the kinds of principal that may hold it; empty: any
 * @param assignedBy the roles whose holders alone may assign it; empty: whoever may write bindings
 * @param permissions what it grants: the permissions this client knows
 */
public record RoleDescription(
        java.lang.String value,
        java.lang.String description,
        java.util.List<java.lang.String> scopes,
        java.util.List<java.lang.String> holders,
        java.util.List<java.lang.String> assignedBy,
        java.util.List<RolePermission> permissions) {}
"#;

const ROLE_PERMISSION: &str = r#"/**
 * One permission a role grants.
 *
 * @param resourceType the resource type a grant names
 * @param permission what grants store
 */
public record RolePermission(java.lang.String resourceType, java.lang.String permission) {}
"#;

/// The package's files, none when the client sees no role.
pub(crate) fn files(service: &Service, package: &str, source: &str) -> Vec<File> {
    let roles = client_roles(service);
    if roles.is_empty() {
        return Vec::new();
    }
    let scopes = client_scopes(service);
    let links = Links { service, package };
    let header = format!("// Generated by Crucible. DO NOT EDIT.\npackage {package}.roles;\n\n");
    let file = |name: &str, body: String| File {
        path: format!("{source}/roles/{name}.java"),
        contents: format!("{header}{body}"),
    };
    let prefix = service.name_of(&service.id);
    vec![
        file(
            "Role",
            enumeration(
                &links,
                "Role",
                &format!(
                    "The roles of {}, by the values bindings store.",
                    code(prefix)
                ),
                roles
                    .iter()
                    .map(|r| {
                        (
                            r.role.symbol.as_str(),
                            r.value,
                            r.role.docs.as_deref(),
                            &r.role.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file(
            "Scope",
            enumeration(
                &links,
                "Scope",
                &format!(
                    "The scopes a role of {} is bound at, by the values bindings store.",
                    code(prefix)
                ),
                scopes
                    .iter()
                    .map(|s| {
                        (
                            s.scope.symbol.as_str(),
                            s.value,
                            s.scope.docs.as_deref(),
                            &s.scope.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file("RoleDescription", ROLE_DESCRIPTION.to_owned()),
        file("RolePermission", ROLE_PERMISSION.to_owned()),
        file("Roles", registry(service, &roles)),
    ]
}

/// One open value type, `Role` or `Scope`.
fn enumeration(
    links: &Links<'_>,
    name: &str,
    summary: &str,
    values: Vec<(&str, &str, Option<&str>, &DocNotes)>,
) -> String {
    let what = name.to_ascii_lowercase();
    let mut out = javadoc_for(
        "",
        None,
        &[
            summary.to_owned(),
            "Open: a value this client does not know (a newer server's, or a custom role's) is kept as it is and written back unchanged, so compare with the constants or {@link #value()}.".to_owned(),
        ],
        &[format!("@param value the {what} value, as bindings store it")],
        &DocNotes::default(),
    );
    out.push_str(&format!(
        "public record {name}(java.lang.String value) {{\n    /**\n     * Requires a non-null value.\n     *\n     * @param value the {what} value\n     */\n    public {name} {{\n        java.util.Objects.requireNonNull(value);\n    }}\n\n    /** @return the {what} value. */\n    @Override\n    public java.lang.String toString() {{\n        return value;\n    }}\n"
    ));
    for (symbol, value, docs, notes) in values {
        out.push('\n');
        out.push_str(&javadoc_linked(
            links,
            "    ",
            docs,
            &[format!("The {} {what}.", code(value))],
            &[],
            notes,
        ));
        out.push_str(&format!(
            "    public static final {name} {} = new {name}({});\n",
            constant(symbol),
            literal(value)
        ));
    }
    out.push_str("}\n");
    out
}

/// `java.util.List.of("a", "b")`.
fn strings<S: AsRef<str>>(items: &[S]) -> String {
    format!(
        "java.util.List.of({})",
        items
            .iter()
            .map(|s| literal(s.as_ref()))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// `Roles`, holding `ROLES`.
fn registry(service: &Service, roles: &[ClientRole<'_>]) -> String {
    let mut body = javadoc_for(
        "",
        None,
        &["The model's roles as data: the registry a console's role picker reads.".to_owned()],
        &[],
        &DocNotes::default(),
    );
    body.push_str("public final class Roles {\n    private Roles() {}\n\n");
    let summary = if custom(service) {
        "Every predefined role, in the service's catalogue order: what a role picker offers. The service also accepts custom roles, which are not listed."
    } else {
        "Every role, in the service's catalogue order: what a role picker offers."
    };
    body.push_str(&javadoc_for(
        "    ",
        None,
        &[summary.to_owned()],
        &[],
        &DocNotes::default(),
    ));
    let entries: Vec<String> = roles
        .iter()
        .map(|role| {
            let permissions: Vec<String> = role
                .permissions
                .iter()
                .map(|p| {
                    format!(
                        "new RolePermission({}, {})",
                        literal(p.resource_type),
                        literal(p.value)
                    )
                })
                .collect();
            format!(
                "        new RoleDescription(\n            {},\n            {},\n            {},\n            {},\n            {},\n            java.util.List.of({}))",
                literal(role.value),
                literal(role.description),
                strings(&role.scopes),
                strings(&role.holders),
                strings(&role.assigned_by),
                permissions.join(", ")
            )
        })
        .collect();
    body.push_str(&format!(
        "    public static final java.util.List<RoleDescription> ROLES = java.util.List.of(\n{});\n}}\n",
        entries.join(",\n")
    ));
    body
}

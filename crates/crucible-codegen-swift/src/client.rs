use super::{Options, literal, method, ty};
use crucible_codegen_common::docs;
use crucible_smithy::ir::{Operation, Service};

fn client_docs(service: &Service, client_name: &str) -> String {
    let mut text = format!(
        "Client for the {} service.\n\n",
        service
            .title
            .as_deref()
            .unwrap_or_else(|| service.id.name())
    );
    if let Some(service_docs) = &service.docs {
        text.push_str(&docs::escape(service_docs));
        text.push_str("\n\n");
    }
    text.push_str(&format!(
        "Create one ``{client_name}`` and share it: it is `Sendable`, holds no per-call state, and any number of calls may run at once. Call ``{client_name}/close()`` when finished. Every operation is `async` and reports failure as a ``ServiceException`` for a service response, a ``NetworkError`` when no response arrives, or a ``TimeoutError`` when the call outlasts ``ClientConfig/timeout``; cancelling the calling task cancels the call."
    ));
    docs::line_comment(
        "",
        "///",
        &text.replace(
            "ServiceException",
            &crucible_codegen_common::service_exception_name(service),
        ),
    )
}

fn operation_docs(
    service: &Service,
    op: &Operation,
    input: &str,
    output: &str,
    pages: bool,
) -> String {
    let (input, output) = (input.trim_matches('`'), output.trim_matches('`'));
    let token = op.idempotency_token.as_deref().map(super::field);
    let mut text = String::new();
    if let Some(summary) = &op.docs {
        text.push_str(&docs::escape(summary));
        text.push_str("\n\n");
    }
    text.push_str(&docs::operation_notes(op, token.as_deref()).join("\n\n"));
    if pages {
        text.push_str(
            "\n\nThis operation is paginated: use the `Pages` variant to read every page.",
        );
    }
    text.push_str(&format!("\n\n- Parameter input: The ``{input}`` to send."));
    text.push_str(&format!(
        "\n- Returns: The ``{output}`` the service returned."
    ));
    let errors = docs::operation_errors(service, op);
    if errors.is_empty() {
        text.push_str(
            "\n- Throws: A ``ServiceException`` when the service responds with an error.",
        );
    } else {
        let names: Vec<String> = errors.iter().map(|name| format!("``{name}``")).collect();
        text.push_str(&format!("\n- Throws: {}, or another ``ServiceException`` when the service responds with an error.", names.join(", ")));
    }
    docs::line_comment(
        "    ",
        "///",
        &text.replace(
            "ServiceException",
            &crucible_codegen_common::service_exception_name(service),
        ),
    )
}

pub fn emit(service: &Service, options: &Options) -> String {
    let client_name = format!("{}Client", service.id.name());
    let module = &options.module_name;
    let endpoint = literal(options.endpoint.as_deref().unwrap_or(""));
    let digest = options.content_sha256;
    let mut out = format!(
        "// Generated by Crucible. DO NOT EDIT.\nimport Foundation\n\n{}public final class {client_name}: Sendable {{\n    private let runtime: ClientRuntime\n{}    public init(_ config: ClientConfig = ClientConfig()) throws {{\n        runtime = try ClientRuntime(config, endpoint: {endpoint}, digest: {digest})\n    }}\n    /// Releases the HTTP session this client created. A transport passed in the\n    /// configuration is left open. Calls made after closing fail.\n    public func close() {{ runtime.close() }}\n",
        client_docs(service, &client_name),
        docs::line_comment(
            "    ",
            "///",
            "Creates a client. Without a `config`, the generated endpoint is used and no credentials are sent; see ``ClientConfig`` for credentials, retries, timeouts and the transport.\n\n- Throws: ``WireError`` when the endpoint or another setting is invalid."
        ),
    );
    for op in &service.operations {
        let input = op
            .input
            .as_ref()
            .map(|id| ty(service, id, module))
            .unwrap_or_else(|| "Unit".into());
        let output = op
            .output
            .as_ref()
            .map(|id| ty(service, id, module))
            .unwrap_or_else(|| "Unit".into());
        let default = if op.input.is_none() { " = .init()" } else { "" };
        let name = method(op.name());
        let wire = literal(op.name());
        out.push_str(&operation_docs(
            service,
            op,
            &input,
            &output,
            op.paginated.is_some(),
        ));
        out.push_str(&format!("    public func `{name}`(_ input: {input}{default}) async throws -> {output} {{\n        try await runtime.call({wire}, input: input, as: {output}.self)\n    }}\n"));
        if op.paginated.is_some() {
            out.push_str(&docs::line_comment("    ", "///", &format!("Every page of ``{name}(_:)``, following the pagination token until the service stops returning one. Each `next()` makes one call, so each can fail.\n\n- Parameter input: The ``{input}`` for the first page.", input = input.trim_matches('`'))));
            out.push_str(&format!("    public func `{name}Pages`(_ input: {input}) throws -> Pages<{output}> {{\n        try runtime.pages({wire}, input: input, as: {output}.self)\n    }}\n"));
        }
        for waiter in op.waiters.keys() {
            let waiter_name = literal(waiter);
            let waiter_docs = op
                .waiters
                .get(waiter)
                .and_then(|waiter| waiter.documentation.as_deref())
                .map(|text| {
                    format!(
                        "    /// {}\n    ///\n",
                        docs::escape(text).replace('\n', "\n    /// ")
                    )
                })
                .unwrap_or_default();
            out.push_str(&format!("{waiter_docs}    /// Polls `{name}` until the modeled `{waiter}` waiter succeeds, fails, or `timeout` seconds pass.\n    ///\n    /// - Parameter input: The ``{input}`` to send on every attempt.\n    /// - Parameter timeout: The most time to wait, in seconds.\n    /// - Parameter options: Overrides the modeled delays between attempts.\n    /// - Returns: The output of the successful attempt, or nil when an error acceptor succeeds.\n    /// - Throws: ``WaiterError`` when a failure acceptor matches and ``WaiterTimeoutError`` when `timeout` passes first.\n    public func `waitUntil{waiter}`(_ input: {input}{default}, timeout: Foundation.TimeInterval, options: WaiterOptions = WaiterOptions()) async throws -> {output}? {{\n        try await runtime.wait({wire}, waiter: {waiter_name}, input: input, timeout: timeout, options: options, as: {output}.self)\n    }}\n"));
        }
    }
    out.push_str("}\n");
    out
}

//! `Permissions.swift` (docs/permissions.md §6.3): a caseless `enum
//! Permissions` namespace, so a model named `GraphPermission` keeps its
//! name. Per resource an open `RawRepresentable` struct,
//! `Permissions.GraphPermission`, with a constant per permission like a
//! model enum's (`.read`), which keeps any value a newer server (or an
//! audience this client is not) writes; deprecated aliases as deprecated
//! constants that `canonical()` maps to their primaries; and
//! `Permissions.all`, the registry a console's grant picker reads.
//! Internal permissions never appear, whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{
    ClientResource, client_resources, code_span, constant_symbol, notes, primary,
};
use crucible_smithy::Diagnostics;
use crucible_smithy::ir::{Service, Shape};

use crate::models::doc;
use crate::{enum_constant, identifier, literal, model_name};

/// The namespace every permission declaration lives in.
pub(crate) const NAMESPACE: &str = "Permissions";

/// The names the namespace declares whatever the model.
const FIXED_NAMES: [&str; 3] = ["PermissionDescription", "ResourcePermissions", "all"];

/// The members a permission type declares besides its constants.
const MEMBERS: [&str; 9] = [
    "rawValue",
    "init",
    "self",
    "description",
    "debugDescription",
    "customMirror",
    "canonical",
    "encode",
    "hashValue",
];

/// The resources a client sees, sorted by authorization name, each with its
/// Swift type name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| {
            let name = format!("{}Permission", model_name(service.name_of(client.id)));
            (name, client)
        })
        .collect()
}

/// Whether the client gets a `Permissions.swift`.
pub(crate) fn present(service: &Service) -> bool {
    !client_resources(service).is_empty()
}

/// The namespace shares the module with the models: a model or module of
/// its name is diagnosed, never renamed. Inside it, two resources must spell
/// distinct types, and one resource's permissions distinct constants.
pub(crate) fn check(service: &Service, module: &str, diagnostics: &mut Diagnostics) {
    if !present(service) {
        return;
    }
    // Simple shapes and units declare no Swift type of their own.
    let models = service
        .shapes
        .iter()
        .filter(|(id, shape)| {
            !id.is_prelude() && !matches!(shape, Shape::Simple(_) | Shape::Unit { .. })
        })
        .any(|(id, _)| model_name(service.name_of(id)) == NAMESPACE);
    if models || module == NAMESPACE {
        diagnostics.push(
            &service.id,
            "`Permissions` names the Swift namespace of the model's permissions, so neither a model nor the module may take it",
        );
    }
    let mut types: BTreeSet<String> = FIXED_NAMES.map(str::to_owned).into();
    for (name, client) in resources(service) {
        if !types.insert(name.clone()) {
            diagnostics.push(
                &service.id,
                format!(
                    "Swift permission type `Permissions.{name}` collides with another declaration"
                ),
            );
        }
        let mut members: BTreeSet<String> = MEMBERS.map(str::to_owned).into();
        for permission in &client.permissions {
            let constant = enum_constant(&constant_symbol(&permission.symbol));
            let problem = if !identifier(&constant) {
                "which is not a Swift identifier".to_owned()
            } else if !members.insert(constant.clone()) {
                format!("which `Permissions.{name}` already declares")
            } else {
                continue;
            };
            diagnostics.push(
                &service.id,
                format!(
                    "permission `{}` of `{}` spells the Swift constant `{constant}`, {problem}",
                    permission.symbol,
                    service.name_of(client.id)
                ),
            );
        }
    }
}

/// `Permissions.swift`, or `None` when no resource has a permission a client
/// may see.
pub(crate) fn emit(service: &Service) -> Option<String> {
    let resources = resources(service);
    if resources.is_empty() {
        return None;
    }
    let mut out = String::from(
        "// Generated by Crucible. DO NOT EDIT.\n\n/// The permissions the service's resources accept, as the values grants store, and ``Permissions/all``, the registry a console's grant picker reads. A value this client does not know is kept as it is; internal permissions never appear.\npublic enum Permissions {\n    /// One permission in the registry.\n    public struct PermissionDescription: Swift.Sendable, Swift.Hashable {\n        /// What grants store.\n        public let value: Swift.String\n        /// The model's documentation for the permission, empty when it has none.\n        public let description: Swift.String\n        /// `\"public\"`, `\"permissionOnly\"` or `\"notGrantable\"`: a plain string, since a newer server may add tiers.\n        public let tier: Swift.String\n        /// False for a bundle the service confers whole: never offer it in a picker.\n        public let grantable: Swift.Bool\n        /// True for a deprecated permission, every alias included.\n        public let deprecated: Swift.Bool\n        /// For a deprecated alias, the value it stands for.\n        public let aliasOf: Swift.String?\n        public init(value: Swift.String, description: Swift.String, tier: Swift.String, grantable: Swift.Bool, deprecated: Swift.Bool, aliasOf: Swift.String? = nil) {\n            self.value = value\n            self.description = description\n            self.tier = tier\n            self.grantable = grantable\n            self.deprecated = deprecated\n            self.aliasOf = aliasOf\n        }\n    }\n\n    /// One resource type's permissions, sorted by value.\n    public struct ResourcePermissions: Swift.Sendable, Swift.Hashable {\n        /// The authorization name grants use for the resource type.\n        public let resourceType: Swift.String\n        /// The type's permissions, deprecated aliases included.\n        public let permissions: Swift.Array<PermissionDescription>\n        public init(resourceType: Swift.String, permissions: Swift.Array<PermissionDescription>) {\n            self.resourceType = resourceType\n            self.permissions = permissions\n        }\n    }\n",
    );
    let mut registry = Vec::new();
    for (name, client) in &resources {
        let shape = service.name_of(client.id);
        let resource = client.resource;
        out.push('\n');
        out.push_str(&doc(
            Some(&format!(
                "The permissions `{shape}` accepts (`{}`), by the values grants store.",
                resource.name
            )),
            &Default::default(),
            "    ",
        ));
        out.push_str(&format!("    public struct `{name}`: Swift.RawRepresentable, Swift.Hashable, Swift.Sendable, Swift.Codable, ModelDescription {{\n        /// The value grants store; a value this client does not list is kept as is.\n        public let rawValue: Swift.String\n        public init(rawValue: Swift.String) {{ self.rawValue = rawValue }}\n"));
        for permission in &client.permissions {
            // Model text: `doc` escapes it like a model enum value's, and
            // leaves the code span alone.
            let mut docs = permission.docs.clone().unwrap_or_default();
            if permission.alias_of.is_some() {
                if !docs.trim().is_empty() {
                    docs.push_str("\n\n");
                }
                docs.push_str(&format!(
                    "An alias of {}.",
                    code_span(&primary(resource, permission).value)
                ));
            }
            out.push_str(&doc(
                Some(docs.as_str()).filter(|d| !d.trim().is_empty()),
                &notes(permission),
                "        ",
            ));
            out.push_str(&format!(
                "        public static let `{}` = Self(rawValue: {})\n",
                enum_constant(&constant_symbol(&permission.symbol)),
                literal(&permission.value)
            ));
        }
        out.push_str(&format!(
            "        public var description: Swift.String {{ \"{name}(\\(rawValue))\" }}\n"
        ));
        // Raw values, not the constants: naming a deprecated alias would
        // warn inside the generated file.
        out.push_str("        /// The permission a deprecated alias stands for; any other value, an unknown one included, is itself.\n        public func canonical() -> Self {\n");
        let aliases = client.aliases();
        if aliases.is_empty() {
            out.push_str("            self\n");
        } else {
            out.push_str("            switch rawValue {\n");
            for (alias, primary) in aliases {
                out.push_str(&format!(
                    "            case {}: return Self(rawValue: {})\n",
                    literal(&alias.value),
                    literal(&primary.value)
                ));
            }
            out.push_str("            default: return self\n            }\n");
        }
        out.push_str("        }\n    }\n");
        let entries: Vec<String> = client
            .entries()
            .iter()
            .map(|e| {
                let alias = e
                    .alias_of
                    .map(|primary| format!(", aliasOf: {}", literal(primary)))
                    .unwrap_or_default();
                format!(
                    "            PermissionDescription(value: {}, description: {}, tier: {}, grantable: {}, deprecated: {}{alias}),\n",
                    literal(e.value),
                    literal(e.description),
                    literal(e.tier),
                    e.grantable,
                    e.deprecated,
                )
            })
            .collect();
        registry.push(format!(
            "        ResourcePermissions(resourceType: {}, permissions: [\n{}        ]),\n",
            literal(&resource.name),
            entries.concat()
        ));
    }
    out.push_str("\n    /// Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the `grantable` ones that are not `deprecated`.\n    public static let all: Swift.Array<ResourcePermissions> = [\n");
    out.push_str(&registry.concat());
    out.push_str("    ]\n}\n");
    Some(out)
}

use super::{enum_constant, field, literal, method, model_name, ty};
use crucible_codegen_common::docs;
use crucible_ir::ir::{DocNotes, Member, Service, Shape};

/// Doc comment with the model's notes, then the native deprecation attribute
/// so the compiler flags use sites.
pub(crate) fn doc(service: &Service, text: Option<&str>, notes: &DocNotes, indent: &str) -> String {
    let mut out = super::links::annotated(service, text, notes)
        .map(|text| docs::line_comment(indent, "///", &text))
        .unwrap_or_default();
    if let Some(deprecated) = &notes.deprecated {
        out.push_str(&format!(
            "{indent}@available(*, deprecated, message: {})\n",
            literal(&deprecated.note())
        ));
    }
    out
}

/// `description` for a generated model: thin, with formatting and the
/// redaction marker living in `runtime/Describe.swift`.
fn description(
    service: &Service,
    name: &str,
    members: &[Member],
    sensitive: bool,
    metadata: bool,
) -> String {
    let mut entries: Vec<String> = members
        .iter()
        .map(|member| {
            let field = field(&member.name);
            if docs::is_redacted(service, sensitive, member) {
                format!("({}, Describe.redact(`{field}`))", literal(&member.name))
            } else {
                format!("({}, `{field}`)", literal(&member.name))
            }
        })
        .collect();
    if metadata {
        entries.push("(\"metadata\", metadata)".into());
    }
    format!(
        "        public var description: Swift.String {{ Describe.format({}, [{}]) }}\n",
        literal(name),
        entries.join(", ")
    )
}

pub fn emit(service: &Service, module: &str) -> String {
    let exception = crucible_codegen_common::service_exception_name(service);
    let mut out = String::from(
        "// Generated by Crucible. DO NOT EDIT.\nimport Foundation\n\n/// The empty input or output of an operation that takes or returns nothing.\npublic struct Unit: Swift.Sendable, WireCodable, ModelDescription {\n        public var description: Swift.String { \"Unit()\" }\n        public init() {}\n        static func fromWire(_ value: JSONValue, _ context: WireContext) throws -> Self {\n            guard try value.object.isEmpty else { throw WireError(\"Unit requires an empty object\") }; return Self()\n        }\n        func toWire(_ context: WireContext) throws -> JSONValue { .object([:]) }\n    }\n",
    );
    let mut errors = String::from(
        "\ninternal enum ModeledErrors {\n    static func decode(_ target: Swift.String, value: JSONValue, codec: WireCodec, metadata: ErrorMetadata) throws -> any ServiceError {\n        switch target {\n",
    );
    for (id, shape) in &service.shapes {
        if id.is_prelude() || matches!(shape, Shape::Simple(_) | Shape::Unit { .. }) {
            continue;
        }
        let name = model_name(service.name_of(id));
        match shape {
            Shape::List(list) => out.push_str(&format!(
                "{}    public typealias `{name}` = Swift.Array<{}{}>\n",
                doc(service, list.docs.as_deref(), &list.notes, "    "),
                ty(service, &list.member.target, module),
                if list.sparse { "?" } else { "" }
            )),
            Shape::Map(map) => out.push_str(&format!(
                "{}    public typealias `{name}` = Swift.Dictionary<{}, {}{}>\n",
                doc(service, map.docs.as_deref(), &map.notes, "    "),
                ty(service, &map.key.target, module),
                ty(service, &map.value.target, module),
                if map.sparse { "?" } else { "" }
            )),
            Shape::IntEnum(enumeration) => {
                out.push_str(&doc(
                    service,
                    enumeration.docs.as_deref(),
                    &enumeration.notes,
                    "    ",
                ));
                out.push_str(&format!("    public struct `{name}`: Swift.RawRepresentable, Swift.Hashable, Swift.Sendable, WireCodable, ModelDescription {{\n        /// The integer sent on the wire.\n        public let rawValue: Swift.Int32\n        public init(rawValue: Swift.Int32) {{ self.rawValue = rawValue }}\n"));
                for value in &enumeration.values {
                    out.push_str(&doc(
                        service,
                        value.docs.as_deref(),
                        &value.notes,
                        "        ",
                    ));
                    out.push_str(&format!(
                        "        public static let `{}` = Self(rawValue: {})\n",
                        enum_constant(&value.name),
                        value.value
                    ));
                }
                out.push_str(&format!(
                    "        public var description: Swift.String {{ \"{name}(\\(rawValue))\" }}\n"
                ));
                out.push_str("        static func fromWire(_ value: JSONValue, _ context: WireContext) throws -> Self { Self(rawValue: try Swift.Int32.fromWire(value, context)) }\n        func toWire(_ context: WireContext) throws -> JSONValue { .number(Swift.String(rawValue)) }\n    }\n");
            }
            Shape::Enum(enumeration) => {
                out.push_str(&doc(
                    service,
                    enumeration.docs.as_deref(),
                    &enumeration.notes,
                    "    ",
                ));
                out.push_str(&format!("    public struct `{name}`: Swift.RawRepresentable, Swift.Hashable, Swift.Sendable, WireCodable, ModelDescription {{\n        /// The string sent on the wire; a value this client does not list is kept as is.\n        public let rawValue: Swift.String\n        public init(rawValue: Swift.String) {{ self.rawValue = rawValue }}\n"));
                for value in &enumeration.values {
                    out.push_str(&doc(
                        service,
                        value.docs.as_deref(),
                        &value.notes,
                        "        ",
                    ));
                    out.push_str(&format!(
                        "        public static let `{}` = Self(rawValue: {})\n",
                        enum_constant(&value.name),
                        literal(&value.value)
                    ));
                }
                out.push_str(&format!(
                    "        public var description: Swift.String {{ \"{name}(\\(rawValue))\" }}\n"
                ));
                out.push_str("        static func fromWire(_ value: JSONValue, _ context: WireContext) throws -> Self { Self(rawValue: try value.string) }\n        func toWire(_ context: WireContext) throws -> JSONValue { .string(rawValue) }\n    }\n");
            }
            Shape::Structure(structure) => {
                let error = if structure.error.is_some() {
                    format!(", {exception}")
                } else {
                    String::new()
                };
                out.push_str(&doc(
                    service,
                    structure.docs.as_deref(),
                    &structure.notes,
                    "    ",
                ));
                out.push_str(&format!(
                    "    public struct `{name}`: Swift.Sendable, WireCodable, ModelDescription{error} {{\n"
                ));
                let mut parameters = Vec::new();
                for member in &structure.members {
                    let field = field(&member.name);
                    let value_type = ty(service, &member.target, module);
                    let member_docs =
                        doc(service, member.docs.as_deref(), &member.notes, "        ");
                    if presence(member) {
                        out.push_str(&format!("        /// Whether `{field}` was omitted, set to null, or given a value.\n        public var `{field}Presence`: OptionalValue<{value_type}>\n{member_docs}        public var `{field}`: {value_type}? {{\n            get {{ `{field}Presence`.value }}\n            set {{ `{field}Presence` = newValue.map {{ .value($0) }} ?? .null }}\n        }}\n"));
                        parameters.push(format!("`{field}`: {value_type}? = nil"));
                        parameters.push(format!(
                            "`{field}Presence`: OptionalValue<{value_type}>? = nil"
                        ));
                    } else {
                        out.push_str(&format!(
                            "{member_docs}        public var `{field}`: {value_type}\n"
                        ));
                        parameters.push(format!("`{field}`: {value_type}"));
                    }
                }
                if structure.error.is_some() {
                    out.push_str("        /// Status, request ID and retry classification of the failed response.\n        public var metadata: ErrorMetadata\n");
                    parameters.push(String::from("metadata: ErrorMetadata = ErrorMetadata()"));
                }
                out.push_str(&description(
                    service,
                    &name,
                    &structure.members,
                    structure.sensitive(),
                    structure.error.is_some(),
                ));
                out.push_str(&format!(
                    "        public init({}) {{\n",
                    parameters.join(", ")
                ));
                for member in &structure.members {
                    let field = field(&member.name);
                    if presence(member) {
                        out.push_str(&format!("            self.`{field}Presence` = `{field}Presence` ?? (`{field}`.map {{ .value($0) }} ?? .unset)\n"));
                    } else {
                        out.push_str(&format!("            self.`{field}` = `{field}`\n"));
                    }
                }
                if structure.error.is_some() {
                    out.push_str("            self.metadata = metadata\n");
                }
                out.push_str("        }\n        static func fromWire(_ value: JSONValue, _ context: WireContext) throws -> Self {\n");
                if !structure.members.is_empty() {
                    out.push_str("            let object = try value.object\n");
                } else {
                    out.push_str("            _ = try value.object\n");
                }
                out.push_str(if structure.members.is_empty() {
                    "            return Self(\n"
                } else {
                    "            return try Self(\n"
                });
                for (index, member) in structure.members.iter().enumerate() {
                    let field = format!(
                        "{}{}",
                        field(&member.name),
                        if presence(member) { "Presence" } else { "" }
                    );
                    let read = if presence(member) { "optional" } else { "read" };
                    out.push_str(&format!("                {field}: context.codec.{read}(context.target, {}, object, as: {}.self){}\n", literal(&member.name), ty(service, &member.target, module), if index + 1 == structure.members.len() { "" } else { "," }));
                }
                out.push_str("            )\n        }\n        func toWire(_ context: WireContext) throws -> JSONValue {\n");
                if structure.members.is_empty() {
                    out.push_str("            return .object([:])\n");
                } else {
                    out.push_str("            var object: [Swift.String: JSONValue] = [:]\n");
                    for member in &structure.members {
                        out.push_str(&format!("            try context.codec.put(context.target, {}, self.`{}`, into: &object)\n", literal(&member.name), format_args!("{}{}", field(&member.name), if presence(member) { "Presence" } else { "" })));
                    }
                    out.push_str("            return .object(object)\n");
                }
                out.push_str("        }\n    }\n");
                if structure.error.is_some() {
                    errors.push_str(&format!("        case {}:\n            var error = try `{name}`.fromWire(value, codec.context(target))\n            error.metadata = metadata; return error\n", literal(&id.to_string())));
                }
            }
            Shape::Union(union) => {
                out.push_str(&doc(service, union.docs.as_deref(), &union.notes, "    "));
                out.push_str(&format!(
                    "    public indirect enum `{name}`: Swift.Sendable, WireCodable, ModelDescription {{\n"
                ));
                for member in &union.members {
                    out.push_str(&doc(
                        service,
                        member.docs.as_deref(),
                        &member.notes,
                        "        ",
                    ));
                    out.push_str(&format!(
                        "        case `{}`({}?)\n",
                        method(&member.name),
                        ty(service, &member.target, module)
                    ));
                }
                out.push_str("        /// A member this client does not know, kept so it can be sent back unchanged.\n");
                out.push_str("        case unknownVariant(name: Swift.String, value: JSONValue)\n        public var description: Swift.String {\n            switch self {\n");
                for member in &union.members {
                    let shown = if docs::is_redacted(service, union.sensitive(), member) {
                        "Describe.redact(value)"
                    } else {
                        "value"
                    };
                    out.push_str(&format!("            case .`{}`(let value): return Describe.format({}, [({}, {shown})])\n", method(&member.name), literal(&name), literal(&member.name)));
                }
                out.push_str(&format!("            case .unknownVariant(let name, _): return Describe.format({}, [(\"unknownVariant\", name)])\n            }}\n        }}\n", literal(&name)));
                out.push_str("        static func fromWire(_ value: JSONValue, _ context: WireContext) throws -> Self {\n            let object = try value.object\n            guard object.count == 1, let (name, item) = object.first else { throw WireError(\"Union requires one member\") }\n            switch name {\n");
                for member in &union.members {
                    out.push_str(&format!("            case {}: return .`{}`(item == .null ? nil : try {}.fromWire(item, context.child(context.codec.member(context.target, name))))\n", literal(&member.name), method(&member.name), ty(service, &member.target, module)));
                }
                out.push_str("            default: return .unknownVariant(name: name, value: item)\n            }\n        }\n        func toWire(_ context: WireContext) throws -> JSONValue {\n            switch self {\n");
                for member in &union.members {
                    let name = literal(&member.name);
                    out.push_str(&format!("            case .`{}`(let value): return .object([{name}: try value?.toWire(context.child(context.codec.member(context.target, {name}))) ?? .null])\n", method(&member.name)));
                }
                out.push_str("            case .unknownVariant(let name, let value):\n                guard try context.shape[\"members\"]?[name] == nil else { throw WireError(\"Unknown variant name is declared\") }\n                return .object([name: value])\n            }\n        }\n    }\n");
            }
            _ => unreachable!(),
        }
    }
    errors.push_str(
        "        default: return UnknownServiceError(metadata: metadata)\n        }\n    }\n}\n",
    );
    out.push_str(&errors);
    out
}

/// Whether a structure member has a `{name}Presence` and an optional
/// initializer parameter (`= nil`), so a caller may leave it out and a
/// value may lack it. A defaulted member is not one: Swift's initializer
/// takes every other member, and the decoder fills the default.
pub(crate) fn presence(member: &crucible_ir::ir::Member) -> bool {
    member.optional_on_client()
}

#[test]
fn streaming_blobs_are_byte_streams() {
    let service = Model::from_json(include_str!(
        "../../crucible-codegen-java/tests/streaming.json"
    ))
    .unwrap()
    .lower_with_capabilities(None, &crucible_codegen_csharp::capabilities())
    .unwrap();
    let files = emit(&service, &options()).unwrap();
    let file = |path: &str| {
        &files
            .iter()
            .find(|file| file.path == path)
            .unwrap_or_else(|| panic!("{path} emitted"))
            .contents
    };
    assert!(
        file("Models/UploadInput.cs")
            .contains("public global::Example.Weather.ByteStream @Body { get; set; } = default!;")
    );
    assert!(file("Models/DownloadOutput.cs").contains("global::Example.Weather.ByteStream @Body"));
    for runtime in [
        "ByteStream.cs",
        "ByteStreamContent.cs",
        "ResponseBodyStream.cs",
    ] {
        assert!(file(runtime).starts_with("// Generated by Crucible."));
    }
    let schema: serde_json::Value = serde_json::from_str(file("schema.json")).unwrap();
    assert_eq!(
        schema["operations"]["Sized"]["request"]["requiresLength"],
        true
    );
}

#[test]
fn streams_outside_the_http_payload_are_diagnosed() {
    let model = serde_json::json!({"smithy":"2.0","shapes":{
        "test#Service":{"type":"service","version":"1","traits":{"aws.protocols#awsJson1_0":{}},"operations":[{"target":"test#Put"}]},
        "test#Put":{"type":"operation","input":{"target":"test#Input"}},
        "test#Stream":{"type":"blob","traits":{"smithy.api#streaming":{}}},
        "test#Input":{"type":"structure","members":{"body":{"target":"test#Stream","traits":{"smithy.api#required":{}}}}}
    }});
    let service = Model::from_json(&model.to_string())
        .unwrap()
        .lower_with_capabilities(None, &crucible_codegen_csharp::capabilities())
        .unwrap();
    let error = emit(&service, &options()).err().unwrap();
    assert!(format!("{error:?}").contains("not the streaming payload"));
}

#[test]
fn service_exception_cannot_shadow_runtime_failures() {
    let mut service = Model::from_json(include_str!(
        "../../crucible-smithy/tests/fixtures/weather.json"
    ))
    .unwrap()
    .lower(None)
    .unwrap();
    service.id = crucible_smithy::ShapeId::new("example.weather", "Waiter");
    assert!(
        emit(&service, &options())
            .err()
            .unwrap()
            .to_string()
            .contains("C# runtime export")
    );
}

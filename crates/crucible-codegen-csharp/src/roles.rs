//! The `<Namespace>.Roles` namespace (docs/roles.md §7 "Clients"): the
//! service's role and scope values as open records in the open-enum
//! convention (`Role.Owner`, `Scope.AllNotes`), which keep a value this
//! client does not know (a newer server's, a custom role's) and write it
//! back unchanged; and `RoleRegistry.Roles`, the registry a console's role
//! picker reads. A namespace of its own, as `Permissions` is, so no model
//! name can collide with these. Generated from
//! `crucible_codegen_common::roles`' one rule, as every client's is: public
//! roles and scopes only, in catalogue order, and only public permissions
//! in a role's `Permissions`.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::constant_symbol;
use crucible_codegen_common::roles::{ClientRole, client_roles, client_scopes, custom};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use super::{File, Links, literal, param, pascal, xmldoc, xmldoc_with};

/// A role's or scope's member: the open-enum convention's (`pascal`), so
/// `allNotes` is `AllNotes`.
fn constant(symbol: &str) -> String {
    pascal(&constant_symbol(symbol))
}

/// Two roles (or two scopes) that C# would spell as one member, or one
/// spelled as a member the record already has.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    let roles = client_roles(service);
    if roles.is_empty() {
        return;
    }
    // The namespace `<Namespace>.Roles` and a model type `Roles` would be
    // one name.
    if service
        .shapes
        .keys()
        .any(|id| !id.is_prelude() && service.name_of(id) == "Roles")
    {
        diagnostics.push(
            &service.id,
            "a model type named `Roles` takes the namespace the C# client puts its roles in",
        );
    }
    let scopes = client_scopes(service);
    for (name, symbols) in [
        (
            "Role",
            roles
                .iter()
                .map(|r| r.role.symbol.as_str())
                .collect::<Vec<_>>(),
        ),
        (
            "Scope",
            scopes.iter().map(|s| s.scope.symbol.as_str()).collect(),
        ),
    ] {
        let mut seen: BTreeSet<String> = [
            name,
            "Value",
            "ToString",
            "Equals",
            "GetHashCode",
            "Deconstruct",
            "Clone",
            "PrintMembers",
            "EqualityContract",
        ]
        .into_iter()
        .map(str::to_owned)
        .collect();
        let what = name.to_ascii_lowercase();
        for symbol in symbols {
            let constant = constant(symbol);
            if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "{what} `{symbol}` is the C# member `{constant}`, which another {what} or the record already has"
                    ),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client.
const ROLE_DESCRIPTION: &str = r#"/// <summary>
/// One role in the registry.
/// </summary>
/// <param name="Value">What bindings store.</param>
/// <param name="Description">The model's documentation for it, empty when it has none.</param>
/// <param name="Scopes">The scope values it may be bound at, in catalogue order.</param>
/// <param name="Holders">The kinds of principal that may hold it; empty: any.</param>
/// <param name="AssignedBy">The roles whose holders alone may assign it; empty: whoever may write bindings.</param>
/// <param name="Permissions">What it grants: the permissions this client knows.</param>
public sealed record RoleDescription(string Value, string Description, global::System.Collections.Generic.IReadOnlyList<string> Scopes, global::System.Collections.Generic.IReadOnlyList<string> Holders, global::System.Collections.Generic.IReadOnlyList<string> AssignedBy, global::System.Collections.Generic.IReadOnlyList<RolePermission> Permissions);
"#;

const ROLE_PERMISSION: &str = r#"/// <summary>
/// One permission a role grants.
/// </summary>
/// <param name="ResourceType">The resource type a grant names.</param>
/// <param name="Permission">What grants store.</param>
public sealed record RolePermission(string ResourceType, string Permission);
"#;

/// The namespace's files, none when the client sees no role.
pub(crate) fn files(service: &Service, ns: &str) -> Vec<File> {
    let roles = client_roles(service);
    if roles.is_empty() {
        return Vec::new();
    }
    let scopes = client_scopes(service);
    let links = Links { service, ns };
    let header = format!(
        "// Generated by Crucible. DO NOT EDIT.\n#nullable enable\n#pragma warning disable CS0618\nnamespace {ns}.Roles;\n\n"
    );
    let file = |name: &str, body: String| File {
        path: format!("Roles/{name}.cs"),
        contents: format!("{header}{body}"),
    };
    let prefix = service.name_of(&service.id);
    vec![
        file(
            "Role",
            record(
                &links,
                "Role",
                &format!("The roles of {prefix}, by the values bindings store."),
                roles
                    .iter()
                    .map(|r| {
                        (
                            r.role.symbol.as_str(),
                            r.value,
                            r.role.docs.as_deref(),
                            &r.role.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file(
            "Scope",
            record(
                &links,
                "Scope",
                &format!(
                    "The scopes a role of {prefix} is bound at, by the values bindings store."
                ),
                scopes
                    .iter()
                    .map(|s| {
                        (
                            s.scope.symbol.as_str(),
                            s.value,
                            s.scope.docs.as_deref(),
                            &s.scope.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file("RoleDescription", ROLE_DESCRIPTION.to_owned()),
        file("RolePermission", ROLE_PERMISSION.to_owned()),
        file("RoleRegistry", registry(service, &roles)),
    ]
}

/// One open value record, `Role` or `Scope`.
fn record(
    links: &Links<'_>,
    name: &str,
    summary: &str,
    values: Vec<(&str, &str, Option<&str>, &DocNotes)>,
) -> String {
    let what = name.to_ascii_lowercase();
    let mut out = xmldoc(
        "",
        None,
        &[
            summary.to_owned(),
            "Open: a value this client does not know (a newer server's, or a custom role's) is kept as it is and written back unchanged, so compare with the constants or Value.".to_owned(),
        ],
        &[param("Value", &format!("The {what} value, as bindings store it."))],
    );
    out.push_str(&format!(
        "public sealed record {name}(string Value) {{\n    /// <inheritdoc/>\n    public override string ToString() => Value;\n"
    ));
    for (symbol, value, docs, notes) in values {
        out.push('\n');
        out.push_str(&xmldoc_with(
            Some(links),
            "    ",
            docs,
            &[],
            &[format!("The {value} {what}.")],
            &[],
            notes,
        ));
        out.push_str(&format!(
            "    public static readonly {name} @{} = new({});\n",
            constant(symbol),
            literal(value)
        ));
    }
    out.push_str("}\n");
    out
}

/// `global::System.Array.AsReadOnly(new string[] { "a", "b" })`.
fn strings<S: AsRef<str>>(items: &[S]) -> String {
    array(
        "string",
        items.iter().map(|s| literal(s.as_ref())).collect(),
    )
}

/// `global::System.Array.AsReadOnly(new T[] { a, b })`, `{ }` when empty.
fn array(element: &str, items: Vec<String>) -> String {
    let items = if items.is_empty() {
        " ".to_owned()
    } else {
        format!(" {} ", items.join(", "))
    };
    format!("global::System.Array.AsReadOnly(new {element}[] {{{items}}})")
}

/// `RoleRegistry`, holding `Roles`.
fn registry(service: &Service, roles: &[ClientRole<'_>]) -> String {
    let mut body = xmldoc(
        "",
        None,
        &["The model's roles as data: the registry a console's role picker reads.".to_owned()],
        &[],
    );
    body.push_str("public static class RoleRegistry {\n");
    let summary = if custom(service) {
        "Every predefined role, in the service's catalogue order: what a role picker offers. The service also accepts custom roles, which are not listed."
    } else {
        "Every role, in the service's catalogue order: what a role picker offers."
    };
    body.push_str(&xmldoc("    ", None, &[summary.to_owned()], &[]));
    let entries: Vec<String> = roles
        .iter()
        .map(|role| {
            let permissions: Vec<String> = role
                .permissions
                .iter()
                .map(|p| format!("new({}, {})", literal(p.resource_type), literal(p.value)))
                .collect();
            format!(
                "        new(\n            {},\n            {},\n            {},\n            {},\n            {},\n            {}),",
                literal(role.value),
                literal(role.description),
                strings(&role.scopes),
                strings(&role.holders),
                strings(&role.assigned_by),
                array("RolePermission", permissions)
            )
        })
        .collect();
    body.push_str(&format!(
        "    public static readonly global::System.Collections.Generic.IReadOnlyList<RoleDescription> Roles = global::System.Array.AsReadOnly(new RoleDescription[] {{\n{}\n    }});\n}}\n",
        entries.join("\n")
    ));
    body
}

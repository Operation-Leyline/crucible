//! The `<Namespace>.Permissions` namespace (docs/permissions.md §6.3): per
//! resource an open permission record in the open-enum convention
//! (`GraphPermission.Read`), which keeps a value this client does not know
//! and writes it back unchanged, with deprecated aliases as `[Obsolete]`
//! members `Canonical()` maps to their primaries; and
//! `PermissionRegistry.Permissions`, the registry a console's grant picker
//! reads. A namespace of its own, so no model name can collide with these.
//! Internal permissions never appear, whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::documentation as docs;
use crucible_codegen_common::permissions::{ClientResource, client_resources, notes, primary};
use crucible_smithy::Diagnostics;
use crucible_smithy::ir::{DocNotes, Service};

use super::{File, identifier, literal, param, pascal, returns, xmldoc, xmldoc_with};

/// A permission's member: the open-enum convention's (`pascal`), so `read`
/// is `Read`.
fn constant(symbol: &str) -> String {
    pascal(symbol)
}

/// The resources a client sees, each with its type's name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| (format!("{}Permission", service.name_of(client.id)), client))
        .collect()
}

/// Two permissions of one resource that C# would spell as one member, or
/// one spelled as a member the record already has.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    for (name, client) in resources(service) {
        if !identifier(&name) {
            diagnostics.push(
                &service.id,
                format!("permission type `{name}` is not a C# identifier"),
            );
        }
        let mut seen: BTreeSet<String> = [
            name.as_str(),
            "Value",
            "ToString",
            "Equals",
            "GetHashCode",
            "Deconstruct",
            "Clone",
            "PrintMembers",
            "EqualityContract",
            "Canonical",
        ]
        .into_iter()
        .map(str::to_owned)
        .collect();
        for permission in &client.permissions {
            let constant = constant(&permission.symbol);
            if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{name}` is the C# member `{constant}`, which another permission or the record already has",
                        permission.symbol
                    ),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client, so they read
/// as runtime sources, bundled only with a client that has permissions.
const PERMISSION_DESCRIPTION: &str = r#"/// <summary>
/// One permission in the registry.
/// </summary>
/// <param name="Value">What grants store.</param>
/// <param name="Description">The model's documentation for it, empty when it has none.</param>
/// <param name="Tier">"public", "permissionOnly" or "notGrantable": a plain string, since a newer server may add a tier.</param>
/// <param name="Grantable">False for a bundle the service confers whole: never offer it in a picker.</param>
/// <param name="Deprecated">Whether the model deprecates it; every alias is deprecated.</param>
/// <param name="AliasOf">For a deprecated alias, the value it stands for; otherwise null.</param>
public sealed record PermissionDescription(string Value, string Description, string Tier, bool Grantable, bool Deprecated, string? AliasOf = null);
"#;

const RESOURCE_PERMISSIONS: &str = r#"/// <summary>
/// One resource type's permissions, sorted by value.
/// </summary>
/// <param name="ResourceType">The resource type's authorization name, as grants store it.</param>
/// <param name="Permissions">Its permissions, deprecated aliases included, sorted by value.</param>
public sealed record ResourcePermissions(string ResourceType, global::System.Collections.Generic.IReadOnlyList<PermissionDescription> Permissions);
"#;

/// The namespace's files, none when the client sees no permission.
pub(crate) fn files(service: &Service, ns: &str) -> Vec<File> {
    let resources = resources(service);
    if resources.is_empty() {
        return Vec::new();
    }
    let header = format!(
        "// Generated by Crucible. DO NOT EDIT.\n#nullable enable\n#pragma warning disable CS0618\nnamespace {ns}.Permissions;\n\n"
    );
    let file = |name: &str, body: String| File {
        path: format!("Permissions/{name}.cs"),
        contents: format!("{header}{body}"),
    };
    let mut files = Vec::new();
    let mut registry = Vec::new();
    for (name, client) in &resources {
        files.push(file(name, record(service, name, client)));
        registry.push(entry(client));
    }
    files.push(file(
        "PermissionDescription",
        PERMISSION_DESCRIPTION.to_owned(),
    ));
    files.push(file("ResourcePermissions", RESOURCE_PERMISSIONS.to_owned()));
    let mut body = xmldoc(
        "",
        None,
        &[
            "The model's permissions as data: the registry a console's grant picker reads."
                .to_owned(),
        ],
        &[],
    );
    body.push_str("public static class PermissionRegistry {\n");
    body.push_str(&xmldoc(
        "    ",
        None,
        &["Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the Grantable ones that are not Deprecated.".to_owned()],
        &[],
    ));
    body.push_str(&format!(
        "    public static readonly global::System.Collections.Generic.IReadOnlyList<ResourcePermissions> Permissions = global::System.Array.AsReadOnly(new ResourcePermissions[] {{\n{}\n    }});\n}}\n",
        registry.join("\n")
    ));
    files.push(file("PermissionRegistry", body));
    files
}

/// One resource's open permission record, `GraphPermission`.
fn record(service: &Service, name: &str, client: &ClientResource<'_>) -> String {
    let shape = service.name_of(client.id);
    let resource = client.resource;
    let mut out = xmldoc(
        "",
        None,
        &[
            format!(
                "The permissions {shape} accepts ({}), by the values grants store.",
                resource.name
            ),
            "Open: a value this client does not know (a newer server's) is kept as it is and written back unchanged, so compare with the constants or Value.".to_owned(),
        ],
        &[param("Value", "The permission value, as grants store it.")],
    );
    out.push_str(&format!(
        "public sealed record {name}(string Value) {{\n    /// <inheritdoc/>\n    public override string ToString() => Value;\n"
    ));
    for permission in &client.permissions {
        let mut rendered = Vec::new();
        if permission.alias_of.is_some() {
            let primary = primary(resource, permission);
            // Already XML: the value is escaped, the references are ours.
            rendered.push(format!(
                "<para>An alias of <c>{}</c>: <see cref=\"Canonical\"/> maps it to <see cref=\"{}\"/>.</para>",
                docs::xmldoc_text(&primary.value),
                constant(&primary.symbol)
            ));
        }
        out.push('\n');
        out.push_str(&xmldoc_with(
            "    ",
            permission.docs.as_deref(),
            &rendered,
            &[format!("The {} permission.", permission.value)],
            &[],
            &notes(permission),
        ));
        out.push_str(&format!(
            "    public static readonly {name} @{} = new({});\n",
            constant(&permission.symbol),
            literal(&permission.value)
        ));
    }
    out.push('\n');
    out.push_str(&xmldoc_with(
        "    ",
        None,
        &[],
        &["The permission a deprecated alias stands for; any other value, one this client does not know included, is itself.".to_owned()],
        &[returns("The primary permission.")],
        &DocNotes::default(),
    ));
    let aliases = client.aliases();
    if aliases.is_empty() {
        out.push_str(&format!("    public {name} Canonical() => this;\n"));
    } else {
        // By value, not by member: an unknown instance equal to an alias
        // maps too, and the obsolete members are never referenced.
        out.push_str(&format!(
            "    public {name} Canonical() => Value switch {{\n"
        ));
        for (alias, primary) in aliases {
            out.push_str(&format!(
                "        {} => @{},\n",
                literal(&alias.value),
                constant(&primary.symbol)
            ));
        }
        out.push_str("        _ => this,\n    };\n");
    }
    out.push_str("}\n");
    out
}

/// The resource's registry entry, its permissions sorted by value.
fn entry(client: &ClientResource<'_>) -> String {
    let entries: Vec<String> = client
        .entries()
        .iter()
        .map(|e| {
            let alias = e
                .alias_of
                .map(|primary| format!(", AliasOf: {}", literal(primary)))
                .unwrap_or_default();
            format!(
                "            new({}, {}, {}, Grantable: {}, Deprecated: {}{alias}),",
                literal(e.value),
                literal(e.description),
                literal(e.tier),
                e.grantable,
                e.deprecated,
            )
        })
        .collect();
    format!(
        "        new({}, global::System.Array.AsReadOnly(new PermissionDescription[] {{\n{}\n        }})),",
        literal(&client.resource.name),
        entries.join("\n")
    )
}

use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn compile(source: &str) -> std::process::Output {
    let dependencies = std::env::current_exe()
        .unwrap()
        .parent()
        .unwrap()
        .to_owned();
    let runtime = fs::read_dir(&dependencies)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.file_name()
                .unwrap()
                .to_string_lossy()
                .starts_with("libcrucible_server_runtime_rust-")
                && path
                    .extension()
                    .is_some_and(|extension| extension == "rlib")
        })
        .max_by_key(|path| path.metadata().unwrap().modified().unwrap())
        .expect("Cargo built the runtime library");
    let directory =
        std::env::temp_dir().join(format!("crucible-server-abi-{}", std::process::id()));
    fs::create_dir_all(&directory).unwrap();
    let input = directory.join("consumer.rs");
    fs::write(&input, source).unwrap();
    let output = Command::new(std::env::var_os("RUSTC").unwrap_or_else(|| "rustc".into()))
        .arg("--edition=2024")
        .arg("--crate-type=lib")
        .arg("--emit=metadata")
        .arg("--extern")
        .arg(format!(
            "crucible_server_runtime_rust={}",
            runtime.display()
        ))
        .arg("-L")
        .arg(format!("dependency={}", dependencies.display()))
        .arg("-o")
        .arg(PathBuf::from(&directory).join("consumer.rmeta"))
        .arg(input)
        .output()
        .unwrap();
    fs::remove_dir_all(directory).unwrap();
    output
}

#[test]
fn abi_versions_and_consumer_boundary() {
    let matching = compile(&format!(
        "crucible_server_runtime_rust::__generated::check_abi!({:?});",
        env!("CARGO_PKG_VERSION")
    ));
    assert!(
        matching.status.success(),
        "{}",
        String::from_utf8_lossy(&matching.stderr)
    );
    let mismatching =
        compile("crucible_server_runtime_rust::__generated::check_abi!(\"0.0.0-mismatch\");");
    assert!(!mismatching.status.success());
    let message = format!(
        "this code was generated by crucible-build 0.0.0-mismatch but crucible-server-runtime-rust is {}; use the same Crucible version for both",
        env!("CARGO_PKG_VERSION")
    );
    assert!(String::from_utf8_lossy(&mismatching.stderr).contains(&message));

    let read_only = compile(
        r#"
        use crucible_server_runtime_rust::{OperationInfo, ServiceInfo};
        pub fn read(op: &OperationInfo, service: &ServiceInfo) -> (&'static str, &'static str) {
            (op.name, service.id)
        }
    "#,
    );
    assert!(
        read_only.status.success(),
        "{}",
        String::from_utf8_lossy(&read_only.stderr)
    );
    let exhaustive = compile(
        r#"
        use crucible_server_runtime_rust::operation::Fault;
        pub fn classify(fault: Fault) -> bool {
            match fault { Fault::Client => true, Fault::Server => false }
        }
    "#,
    );
    assert!(!exhaustive.status.success());
    assert!(String::from_utf8_lossy(&exhaustive.stderr).contains("non-exhaustive"));

    let construction = compile(
        r#"
        use crucible_server_runtime_rust::operation::{MemberInfo, Location, Scalar, Redaction};
        pub const MEMBER: MemberInfo = MemberInfo {
            name: "test", location: Location::Body, scalar: Scalar::Json,
            redaction: &Redaction::Public, traits: &[],
        };
    "#,
    );
    assert!(!construction.status.success());
    assert!(String::from_utf8_lossy(&construction.stderr).contains("non-exhaustive"));
    let old_helpers = compile("use crucible_server_runtime_rust::{codec, error::write_error};");
    assert!(!old_helpers.status.success());
    assert!(String::from_utf8_lossy(&old_helpers.stderr).contains("unresolved imports"));
}

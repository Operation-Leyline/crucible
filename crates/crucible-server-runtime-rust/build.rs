use std::{env, fs, path::PathBuf};

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    let version = env!("CARGO_PKG_VERSION");
    // Embed the runtime version here: env! inside the expansion would read the consumer's version.
    let source = format!(
        r#"
#[doc(hidden)]
#[macro_export]
macro_rules! __crucible_check_abi {{
    ({version:?}) => {{}};
    ($version:literal) => {{
        compile_error!(concat!("this code was generated by crucible-build ", $version,
            " but crucible-server-runtime-rust is {version}; use the same Crucible version for both"));
    }};
}}
"#
    );
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").expect("Cargo OUT_DIR")).join("check_abi.rs"),
        source,
    )
    .expect("write ABI check");
}

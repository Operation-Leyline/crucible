//! `lib/permissions.dart` (docs/permissions.md §6.3): a library of its own,
//! which the package's main library does not export, so a model named
//! `GraphPermission` keeps its name. Per resource an open class,
//! `GraphPermission`, with a constant per permission like a model enum's
//! (`GraphPermission.read`), which keeps any value a newer server (or an
//! audience this client is not) writes; deprecated aliases as deprecated
//! constants that `canonical()` maps to their primaries; and `permissions`,
//! the registry a console's grant picker reads, whose record types are the
//! bundled `runtime/permissions.dart`. Internal permissions never appear,
//! whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{
    ClientResource, client_resources, code_span, constant_symbol, notes, primary,
};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use crate::models::doc_in;
use crate::{enum_constant, identifier, literal};

/// The library a console imports: `package:<name>/permissions.dart`.
pub(crate) const LIBRARY: &str = "lib/permissions.dart";

/// The registry's record types, bundled like the rest of the runtime.
pub(crate) const RUNTIME: &str = include_str!("../runtime/permissions.dart");

/// The names the library declares or exports whatever the model.
const FIXED_NAMES: [&str; 4] = [
    "core",
    "PermissionDescription",
    "ResourcePermissions",
    "permissions",
];

/// The members a permission class declares besides its constants.
const MEMBERS: [&str; 8] = [
    "value",
    "canonical",
    "toJson",
    "hashCode",
    "runtimeType",
    "toString",
    "noSuchMethod",
    "core",
];

/// The resources a client sees, sorted by authorization name, each with its
/// Dart class name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| (format!("{}Permission", service.name_of(client.id)), client))
        .collect()
}

/// The library is `lib/permissions.dart`, so a package of that name, whose
/// main library has the same path, is diagnosed. Inside it, two resources
/// must name distinct classes, and one resource's permissions distinct
/// constants.
pub(crate) fn check(service: &Service, package: &str, diagnostics: &mut Diagnostics) {
    let resources = resources(service);
    if resources.is_empty() {
        return;
    }
    if package == "permissions" {
        diagnostics.push(
            &service.id,
            "a Dart package named `permissions` has its main library where the permissions library goes",
        );
    }
    let mut names: BTreeSet<String> = FIXED_NAMES.map(str::to_owned).into();
    for (name, client) in &resources {
        if !names.insert(name.clone()) {
            diagnostics.push(
                &service.id,
                format!("Dart permission class `{name}` collides with another declaration"),
            );
        }
        let mut members: BTreeSet<String> = MEMBERS.map(str::to_owned).into();
        members.insert(name.clone());
        for permission in &client.permissions {
            let constant = enum_constant(&constant_symbol(&permission.symbol));
            let problem = if !identifier(&constant) {
                "which is not a Dart identifier".to_owned()
            } else if !members.insert(constant.clone()) {
                format!("which `{name}` already declares")
            } else {
                continue;
            };
            diagnostics.push(
                &service.id,
                format!(
                    "permission `{}` of `{}` spells the Dart constant `{constant}`, {problem}",
                    permission.symbol,
                    service.name_of(client.id)
                ),
            );
        }
    }
}

/// `lib/permissions.dart`, or `None` when no resource has a permission a
/// client may see.
pub(crate) fn emit(service: &Service) -> Option<String> {
    let resources = resources(service);
    if resources.is_empty() {
        return None;
    }
    let mut out = String::from(
        "// Generated by Crucible. DO NOT EDIT.\n\n/// The permissions the service's resources accept, as the values grants store, and [permissions], the registry a console's grant picker reads. A value this client does not know is kept as it is; internal permissions never appear.\nlibrary;\n\nimport 'dart:core' as core;\nimport 'src/runtime/permissions.dart';\nexport 'src/runtime/permissions.dart';\n",
    );
    let mut registry = Vec::new();
    for (name, client) in &resources {
        let shape = service.name_of(client.id);
        let resource = client.resource;
        out.push('\n');
        out.push_str(&doc_in(
            service,
            crate::links::Library::Permissions,
            Some(&format!(
                "The permissions `{shape}` accepts (`{}`), by the values grants store.",
                resource.name
            )),
            &DocNotes::default(),
            "",
        ));
        out.push_str(&format!("final class {name} {{\n  /// The value grants store; a value this client does not list is kept as is.\n  final core.String value;\n  const {name}(this.value);\n"));
        for permission in &client.permissions {
            // Model text: `doc` escapes it like a model enum value's, and
            // leaves the code span alone.
            let mut docs = permission.docs.clone().unwrap_or_default();
            if permission.alias_of.is_some() {
                if !docs.trim().is_empty() {
                    docs.push_str("\n\n");
                }
                docs.push_str(&format!(
                    "An alias of {}.",
                    code_span(&primary(resource, permission).value)
                ));
            }
            out.push_str(&doc_in(
                service,
                crate::links::Library::Permissions,
                Some(docs.as_str()).filter(|d| !d.trim().is_empty()),
                &notes(permission),
                "  ",
            ));
            out.push_str(&format!(
                "  static const {} = {name}({});\n",
                enum_constant(&constant_symbol(&permission.symbol)),
                literal(&permission.value)
            ));
        }
        // Raw values, not the constants: naming a deprecated alias would
        // trip `deprecated_member_use_from_same_package`.
        out.push_str("  /// The permission a deprecated alias stands for; any other value, an unknown one included, is itself.\n");
        let aliases = client.aliases();
        if aliases.is_empty() {
            out.push_str(&format!("  {name} canonical() => this;\n"));
        } else {
            out.push_str(&format!("  {name} canonical() => switch (value) {{\n"));
            for (alias, primary) in aliases {
                out.push_str(&format!(
                    "        {} => const {name}({}),\n",
                    literal(&alias.value),
                    literal(&primary.value)
                ));
            }
            out.push_str("        _ => this,\n      };\n");
        }
        out.push_str(&format!("  /// The value, so `jsonEncode` writes the permission as grants store it.\n  core.String toJson() => value;\n  @core.override\n  core.bool operator ==(core.Object other) => other is {name} && value == other.value;\n  @core.override\n  core.int get hashCode => value.hashCode;\n  @core.override\n  core.String toString() => '{name}($value)';\n}}\n"));
        let entries: Vec<String> = client
            .entries()
            .iter()
            .map(|e| {
                let alias = e
                    .alias_of
                    .map(|primary| format!(", aliasOf: {}", literal(primary)))
                    .unwrap_or_default();
                format!(
                    "    PermissionDescription(value: {}, description: {}, tier: {}, grantable: {}, deprecated: {}{alias}),\n",
                    literal(e.value),
                    literal(e.description),
                    literal(e.tier),
                    e.grantable,
                    e.deprecated,
                )
            })
            .collect();
        registry.push(format!(
            "  ResourcePermissions(resourceType: {}, permissions: <PermissionDescription>[\n{}  ]),\n",
            literal(&resource.name),
            entries.concat()
        ));
    }
    out.push_str("\n/// Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the `grantable` ones that are not `deprecated`.\nconst permissions = <ResourcePermissions>[\n");
    out.push_str(&registry.concat());
    out.push_str("];\n");
    Some(out)
}

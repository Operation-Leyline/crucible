use super::{Options, field, literal, method};
use crucible_codegen_common::docs;
use crucible_smithy::ir::{Operation, Service};

fn operation_docs(service: &Service, op: &Operation, pages: bool) -> String {
    let token = op.idempotency_token.as_deref().map(field);
    let mut text = String::new();
    if let Some(summary) = &op.docs {
        text.push_str(&docs::escape(summary));
        text.push_str("\n\n");
    }
    text.push_str(&docs::operation_notes(op, token.as_deref()).join("\n\n"));
    if pages {
        text.push_str(
            "\n\nThis operation is paginated: see the `Pages` variant to read every page.",
        );
    }
    let errors = docs::operation_errors(service, op);
    if !errors.is_empty() {
        text.push_str("\n\nThrows:\n");
        for name in errors {
            text.push_str(&format!("\n- [models.{name}]"));
        }
    }
    docs::line_comment("  ", "///", &text)
}

pub fn emit(service: &Service, options: &Options) -> String {
    let client_name = format!("{}Client", service.id.name());
    let async_import = if service.operations.is_empty() {
        ""
    } else {
        "import 'dart:async';\n"
    };
    let cancel_import = if service.operations.is_empty() {
        ""
    } else {
        "import 'runtime/cancellation.dart';\n"
    };
    let mut out = format!(
        "// Generated by Crucible. DO NOT EDIT.\n{async_import}import 'models.dart' as models;\nimport 'schema.dart';\nimport 'runtime/config.dart';\nimport 'runtime/codec.dart';\nimport 'runtime/json.dart';\n{cancel_import}import 'runtime/client_runtime.dart';\n\n{}final class {client_name} {{\n  final ClientRuntime _runtime;\n{}  {client_name}([ClientConfig? config]) : _runtime = ClientRuntime(config ?? ClientConfig(),\n    WireCodec(wireObject(exactJsonDecode(schemaSource)), models.decodeModel), models.decodeError, () => const models.Unit(),\n    endpoint: {}, digest: {});\n  /// Releases the HTTP client this client created. A transport passed in the\n  /// configuration is left open. Calls made after closing throw a `StateError`.\n  void close() => _runtime.close();\n",
        docs::line_comment("", "///", &client_docs(service, &client_name)),
        docs::line_comment(
            "  ",
            "///",
            "Creates a client. Without a [config], the generated endpoint is used and no credentials are sent; see [ClientConfig] for credentials, retries, timeouts and the transport. Throws an `ArgumentError` for an invalid endpoint."
        ),
        literal(options.endpoint.as_deref().unwrap_or("")),
        options.content_sha256
    );
    for op in &service.operations {
        let input = op
            .input
            .as_ref()
            .map(|id| service.name_of(id))
            .unwrap_or("Unit");
        let output = op
            .output
            .as_ref()
            .map(|id| service.name_of(id))
            .unwrap_or("Unit");
        let name = field(&method(op.name()));
        let params = if op.input.is_none() {
            "{CancellationToken? cancellation}".to_string()
        } else {
            format!("models.{input} input, {{CancellationToken? cancellation}}")
        };
        let input_expr = if op.input.is_none() {
            "const models.Unit()"
        } else {
            "input"
        };
        out.push_str(&operation_docs(service, op, op.paginated.is_some()));
        out.push_str(&format!("  Future<models.{output}> {name}({params}) => _runtime.call({}, {input_expr}, cancellation: cancellation);\n", literal(op.name())));
        for waiter in op.waiters.keys() {
            let params = if op.input.is_none() {
                "{required Duration timeout, Duration? minDelay, Duration? maxDelay, CancellationToken? cancellation}".to_string()
            } else {
                format!(
                    "models.{input} input, {{required Duration timeout, Duration? minDelay, Duration? maxDelay, CancellationToken? cancellation}}"
                )
            };
            out.push_str(&waiter_docs(op, waiter));
            out.push_str(&format!("  Future<models.{output}?> waitUntil{}({params}) => _runtime.wait({}, {}, {input_expr}, timeout: timeout, minDelay: minDelay, maxDelay: maxDelay, cancellation: cancellation);\n", super::models::variant(waiter), literal(op.name()), literal(waiter)));
        }
        if op.paginated.is_some() {
            out.push_str(&docs::line_comment("  ", "///", &format!("Streams every page of [{name}], following the pagination token until the service stops returning one. Each page is a separate call, so each can fail; cancel through [cancellation].")));
            out.push_str(&format!("  Stream<models.{output}> {name}Pages(models.{input} input, {{CancellationToken? cancellation}}) => _runtime.pages({}, input, cancellation: cancellation);\n", literal(op.name())));
        }
    }
    out.push_str("}\n");
    out
}

fn client_docs(service: &Service, client_name: &str) -> String {
    let mut text = format!(
        "Client for the {} service.\n\n",
        service
            .title
            .as_deref()
            .unwrap_or_else(|| service.id.name())
    );
    if let Some(service_docs) = &service.docs {
        text.push_str(&docs::escape(service_docs));
        text.push_str("\n\n");
    }
    text.push_str(&format!(
        "Create one `{client_name}`, share it, and call [close] when finished. It holds no per-call state, so many calls may be in flight at once within an isolate; do not send it to another isolate. Each operation returns a `Future` and reports failure as a [ServiceException] for service responses, a [NetworkException] when no response arrives, or a [CancelledException]. A call that outlasts `ClientConfig.timeout` fails with a `TimeoutException`."
    ));
    // The runtime's `ServiceException` is renamed per service.
    text.replace(
        "ServiceException",
        &crucible_codegen_common::service_exception_name(service),
    )
}

fn waiter_docs(op: &Operation, waiter: &str) -> String {
    let text = op
        .waiters
        .get(waiter)
        .and_then(|waiter| waiter.documentation.as_deref())
        .map(|text| format!("{}\n\n", docs::escape(text)))
        .unwrap_or_default();
    docs::line_comment(
        "  ",
        "///",
        &format!(
            "{text}Calls [{}] repeatedly until the modeled `{waiter}` waiter succeeds, with jittered backoff between `minDelay` and `maxDelay`. Completes with null when an error acceptor succeeds. Throws a [WaiterException] when a failure acceptor matches and a [WaiterTimeoutException] after `timeout`.",
            super::field(&super::method(op.name()))
        ),
    )
}

//! `crucible sdk plan|build|verify|publish` end to end, on a git channel:
//! a real service repository and a local bare distribution repository,
//! with Git isolated from the user's configuration. (The npm channel is
//! tested in crucible-sdk-release against a fake registry: it is HTTPS
//! only, so it has no local stand-in here.)

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const WEATHER: &str = include_str!("../../crucible-smithy/tests/fixtures/weather.json");
const RUNTIME: &str = r#"runtime = { git = "https://github.com/Operation-Leyline/crucible", rev = "0123456789abcdef0123456789abcdef01234567", version = "0.6" }"#;

struct Service {
    root: tempfile::TempDir,
}

impl Service {
    /// A service repository whose SDK file declares `sdks` (appended to a
    /// header naming the model and README), committed.
    fn new(sdks: &str) -> Self {
        let root = tempfile::tempdir_in(env!("CARGO_TARGET_TMPDIR")).unwrap();
        let service = Self { root };
        fs::write(service.root.path().join("gitconfig"), "").unwrap();
        service.git(&["init", "-q", "--bare", "-b", "main", "remote.git"]);
        let repo = service.repo();
        fs::create_dir_all(repo.join("sdk")).unwrap();
        fs::create_dir_all(repo.join("consumer")).unwrap();
        fs::write(repo.join("model.json"), WEATHER).unwrap();
        fs::write(repo.join("sdk/README.md"), "# Weather\n\nThe SDK.\n").unwrap();
        fs::write(repo.join("consumer/Cargo.lock"), lock("0.6.1")).unwrap();
        let file = format!(
            "schema_version = 1\nmodel = \"model.json\"\n\n[defaults]\ndescription = \"Client for the Weather API.\"\nreadme = \"sdk/README.md\"\n\n{}",
            sdks.replace("{remote}", &service.remote_url())
                .replace("{runtime}", RUNTIME)
        );
        fs::write(repo.join("crucible-sdk.toml"), file).unwrap();
        service.git_in(&repo, &["init", "-q", "-b", "main"]);
        service.commit("service");
        service
    }

    fn repo(&self) -> PathBuf {
        self.root.path().join("service")
    }

    fn remote(&self) -> PathBuf {
        self.root.path().join("remote.git")
    }

    fn remote_url(&self) -> String {
        let path = self.remote().to_string_lossy().replace('\\', "/");
        format!("file:///{}", path.trim_start_matches('/'))
    }

    fn release(&self) -> PathBuf {
        self.root.path().join("release")
    }

    fn isolate<'a>(&self, command: &'a mut Command) -> &'a mut Command {
        command
            .env("GIT_CONFIG_GLOBAL", self.root.path().join("gitconfig"))
            .env("GIT_CONFIG_NOSYSTEM", "1")
    }

    fn git_in(&self, directory: &Path, args: &[&str]) -> String {
        fs::create_dir_all(directory).unwrap();
        let output = self
            .isolate(
                Command::new("git")
                    .current_dir(directory)
                    .args([
                        "-c",
                        "user.name=Test",
                        "-c",
                        "user.email=test@example.invalid",
                    ])
                    .args(args),
            )
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8_lossy(&output.stdout).trim().to_owned()
    }

    fn git(&self, args: &[&str]) -> String {
        self.git_in(self.root.path(), args)
    }

    fn commit(&self, message: &str) {
        let repo = self.repo();
        self.git_in(&repo, &["add", "-A"]);
        self.git_in(&repo, &["commit", "-q", "-m", message]);
    }

    fn crucible(&self, args: &[&str]) -> Output {
        self.isolate(
            Command::new(env!("CARGO_BIN_EXE_crucible"))
                .current_dir(self.repo())
                .args(args),
        )
        .output()
        .unwrap()
    }

    fn remote_tags(&self) -> String {
        self.git_in(&self.remote(), &["tag", "--list"])
    }
}

/// A consumer's lockfile, with the SDK as a path package at `version`.
fn lock(version: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"consumer\"\nversion = \"0.1.0\"\ndependencies = [\n \"weather-sdk\",\n]\n\n[[package]]\nname = \"weather-sdk\"\nversion = \"{version}\"\n"
    )
}

fn success(output: Output) -> String {
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap()
}

fn failure(output: Output) -> String {
    assert!(
        !output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stdout)
    );
    String::from_utf8(output.stderr).unwrap()
}

fn json(text: &str) -> serde_json::Value {
    serde_json::from_str(text).unwrap()
}

const RUST: &str = r#"[sdk.rust]
package = "weather-sdk"
version = "0.2.0"
out = "generated/rust"
private = true
{runtime}
# The consumer's lock names the release version while the tests run, and
# {artifact} is the archived tree.
test = [
  ["git", "diff", "--no-index", "--exit-code", "consumer/Cargo.lock", "consumer/expected.lock"],
  ["git", "hash-object", "{artifact}"],
]
lockfiles = ["consumer/Cargo.lock"]
channel = { git = "{remote}" }

[sdk.rust-dev]
language = "rust"
package = "weather-dev"
out = "generated/rust-dev"
{runtime}
"#;

#[test]
fn plans_builds_verifies_and_publishes_a_git_channel_release() {
    let service = Service::new(RUST);
    let repo = service.repo();
    fs::write(repo.join("consumer/expected.lock"), lock("0.2.0")).unwrap();

    // An empty channel is not a first release until someone says so.
    let error = failure(service.crucible(&["sdk", "plan"]));
    assert!(error.contains("--first-release rust"), "{error}");

    let plan = json(&success(service.crucible(&[
        "sdk",
        "plan",
        "--first-release",
        "rust",
        "--json",
    ])));
    assert_eq!(plan["sdks"]["rust"]["version"], "0.2.0");
    assert_eq!(
        plan["sdks"]["rust"]["decision"]["reasons"][0]["reason"],
        "first-release"
    );
    assert!(plan["sdks"]["rust-dev"].get("channel").is_none());
    assert!(plan["sdks"]["rust-dev"]["version"].is_string());
    assert!(service.remote_tags().is_empty());

    let release = service.release();
    let release_arg = release.to_str().unwrap();
    let built = success(service.crucible(&[
        "sdk",
        "build",
        "--out",
        release_arg,
        "--first-release",
        "rust",
    ]));
    assert!(built.contains("locks 0.2.0 for the tests"), "{built}");
    let plan = json(&fs::read_to_string(release.join("plan.json")).unwrap());
    let record = json(&fs::read_to_string(release.join("release.json")).unwrap());
    assert_eq!(record["sdks"]["rust"]["version"], "0.2.0");
    assert_eq!(
        record["sdks"]["rust"]["artifact"]["path"],
        "rust/package.tar"
    );
    assert_eq!(record["sdks"]["rust-dev"]["channel"], false);
    let head = service.git_in(&repo, &["rev-parse", "HEAD"]);
    assert_eq!(plan["sdks"]["rust"]["sourceCommit"], head.as_str());
    assert_eq!(plan["generator"]["changes"], 0);
    // The package carries its provenance, with the source commit.
    let provenance = json(&fs::read_to_string(release.join("rust/package/crucible.json")).unwrap());
    assert_eq!(provenance["packageVersion"], "0.2.0");
    assert_eq!(provenance["source"]["commit"], head.as_str());
    assert_eq!(
        provenance["contentDigest"],
        plan["sdks"]["rust"]["contentDigest"]
    );
    // `out` now holds the release; the consumer's lock is as it was.
    let manifest = fs::read_to_string(repo.join("generated/rust/Cargo.toml")).unwrap();
    assert!(manifest.contains("version = \"0.2.0\""), "{manifest}");
    assert_eq!(
        fs::read_to_string(repo.join("consumer/Cargo.lock")).unwrap(),
        lock("0.6.1")
    );
    // A release builds in a fresh directory.
    let error = failure(service.crucible(&[
        "sdk",
        "build",
        "--out",
        release_arg,
        "--first-release",
        "rust",
    ]));
    assert!(error.contains("not empty"), "{error}");

    assert!(success(service.crucible(&["sdk", "verify", release_arg])).contains("verified 2"));

    // Without --execute, nothing is pushed.
    let dry = success(service.crucible(&["sdk", "publish", release_arg]));
    assert!(
        dry.contains("git push --atomic") && dry.contains("dry run"),
        "{dry}"
    );
    assert!(service.remote_tags().is_empty());

    let published = success(service.crucible(&["sdk", "publish", release_arg, "--execute"]));
    assert!(published.contains("pushed v0.2.0"), "{published}");
    assert!(published.contains("rust-dev: no channel"), "{published}");
    assert_eq!(service.remote_tags(), "v0.2.0");
    let tree = service.git_in(
        &service.remote(),
        &["ls-tree", "-r", "--name-only", "v0.2.0"],
    );
    for path in [
        ".crucible",
        "Cargo.toml",
        "README.md",
        "crucible.json",
        "crucible-model.json",
    ] {
        assert!(tree.lines().any(|line| line == path), "{path} in\n{tree}");
    }
    // A rerun is journalled.
    let again = success(service.crucible(&["sdk", "publish", release_arg, "--execute"]));
    assert!(again.contains("already done"), "{again}");
    // A rerun that lost the journal finds the same bytes.
    fs::remove_file(release.join("publication.json")).unwrap();
    let again = success(service.crucible(&["sdk", "publish", release_arg, "--execute"]));
    assert!(again.contains("already on"), "{again}");

    // Nothing changed: no release.
    let plan = json(&success(service.crucible(&["sdk", "plan", "--json"])));
    assert!(plan["sdks"]["rust"].get("version").is_none(), "{plan}");
    assert_eq!(plan["sdks"]["rust"]["last"]["version"], "0.2.0");
    let text = success(service.crucible(&["sdk", "plan", "--sdk", "rust"]));
    assert!(text.contains("unchanged since 0.2.0"), "{text}");

    // A README change is content: the next patch.
    fs::write(
        repo.join("sdk/README.md"),
        "# Weather\n\nThe SDK, improved.\n",
    )
    .unwrap();
    service.commit("readme");
    let plan = json(&success(
        service.crucible(&["sdk", "plan", "--json", "--sdk", "rust"]),
    ));
    assert_eq!(plan["sdks"]["rust"]["version"], "0.2.1");
    assert_eq!(
        plan["sdks"]["rust"]["decision"]["reasons"][0]["reason"],
        "content-changed"
    );
    let plan = json(&success(service.crucible(&[
        "sdk",
        "plan",
        "--json",
        "--sdk",
        "rust",
        "--bump",
        "rust=major",
    ])));
    assert_eq!(plan["sdks"]["rust"]["version"], "0.3.0");
    let error = failure(service.crucible(&["sdk", "plan", "--first-release", "rust"]));
    assert!(error.contains("already has 0.2.0"), "{error}");
    let error = failure(service.crucible(&["sdk", "plan", "--bump", "rust-dev=minor"]));
    assert!(error.contains("no channel"), "{error}");

    // A tampered artifact fails verify and publish.
    fs::write(release.join("rust/package.tar"), b"tampered").unwrap();
    let error = failure(service.crucible(&["sdk", "verify", release_arg]));
    assert!(
        error.contains("not the artifact that was tested"),
        "{error}"
    );
}

#[test]
fn a_failed_test_leaves_no_release_and_restores_the_lockfiles() {
    let service = Service::new(RUST);
    let repo = service.repo();
    // expected.lock is missing, so the first test command fails.
    let release = service.release();
    let error = failure(service.crucible(&[
        "sdk",
        "build",
        "--out",
        release.to_str().unwrap(),
        "--first-release",
        "rust",
    ]));
    assert!(error.contains("test `git diff"), "{error}");
    assert!(release.join("plan.json").is_file());
    assert!(!release.join("release.json").exists());
    assert_eq!(
        fs::read_to_string(repo.join("consumer/Cargo.lock")).unwrap(),
        lock("0.6.1")
    );
    let error = failure(service.crucible(&["sdk", "publish", release.to_str().unwrap()]));
    assert!(error.contains("no release.json"), "{error}");
}

#[test]
fn a_release_needs_committed_inputs_and_a_published_runtime() {
    let service = Service::new(RUST);
    let repo = service.repo();
    fs::write(repo.join("consumer/expected.lock"), lock("0.2.0")).unwrap();
    fs::write(repo.join("sdk/README.md"), "uncommitted\n").unwrap();
    let release = service.release();
    let error = failure(service.crucible(&[
        "sdk",
        "build",
        "--out",
        release.to_str().unwrap(),
        "--first-release",
        "rust",
    ]));
    assert!(error.contains("--allow-dirty"), "{error}");
    let built = success(service.crucible(&[
        "sdk",
        "build",
        "--out",
        service.root.path().join("dirty").to_str().unwrap(),
        "--first-release",
        "rust",
        "--allow-dirty",
    ]));
    assert!(built.contains("built and tested"), "{built}");
    let provenance = json(
        &fs::read_to_string(service.root.path().join("dirty/rust/package/crucible.json")).unwrap(),
    );
    assert_eq!(provenance["source"]["dirty"], true);

    let local = Service::new(
        "[sdk.rust]\npackage = \"weather-sdk\"\nout = \"generated/rust\"\nruntime_path = \"runtime\"\nchannel = { git = \"{remote}\" }\n",
    );
    fs::create_dir_all(local.repo().join("runtime")).unwrap();
    let error = failure(local.crucible(&[
        "sdk",
        "build",
        "--out",
        local.release().to_str().unwrap(),
        "--first-release",
        "rust",
    ]));
    assert!(error.contains("runtime_path"), "{error}");
}

//! The `<package>.permissions` package (docs/permissions.md §6.3): per
//! resource an open permission type in the open-enum convention
//! (`GraphPermission.READ`), which keeps a value this client does not know
//! and writes it back unchanged, with deprecated aliases as deprecated
//! constants `canonical()` maps to their primaries; and `PERMISSIONS`, the
//! registry a console's grant picker reads. A package of its own, so no
//! model name can collide with these. Common code only, so every target
//! the package builds for compiles it. Internal permissions never appear,
//! whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{
    ClientResource, client_resources, constant_symbol, notes, primary,
};
use crucible_smithy::Diagnostics;
use crucible_smithy::ir::Service;

use super::{File, code, identifier, kdoc, kdoc_for, literal};

/// A permission's constant: the open-enum convention's
/// (`name.to_uppercase()`), so `read` is `READ`.
fn constant(symbol: &str) -> String {
    symbol.to_uppercase()
}

/// The resources a client sees, each with its type's name.
fn resources(service: &Service) -> Vec<(String, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| (format!("{}Permission", service.name_of(client.id)), client))
        .collect()
}

/// Two permissions of one resource that Kotlin would spell as one constant.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    for (name, client) in resources(service) {
        if !identifier(&name) {
            diagnostics.push(
                &service.id,
                format!("permission type `{name}` is not a Kotlin identifier"),
            );
        }
        let mut seen = BTreeSet::new();
        for permission in &client.permissions {
            let constant = constant(&constant_symbol(&permission.symbol));
            // Kotlin reserves names made only of underscores, backticked
            // or not, so `_` cannot name a constant.
            if constant.chars().all(|c| c == '_') {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{name}` spells the Kotlin constant `{constant}`, which Kotlin reserves",
                        permission.symbol
                    ),
                );
            } else if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{name}` shares the Kotlin constant `{constant}` with another",
                        permission.symbol
                    ),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client, so they read
/// as runtime sources, bundled only with a client that has permissions.
const PERMISSION_DESCRIPTION: &str = r#"/**
 * One permission in the registry.
 *
 * @property value what grants store
 * @property description the model's documentation for it, empty when it has none
 * @property tier `"public"`, `"permissionOnly"` or `"notGrantable"`: a plain string, since a newer server may add a tier
 * @property grantable false for a bundle the service confers whole: never offer it in a picker
 * @property deprecated whether the model deprecates it; every alias is deprecated
 * @property aliasOf for a deprecated alias, the value it stands for; otherwise null
 */
data class PermissionDescription(
    val value: kotlin.String,
    val description: kotlin.String,
    val tier: kotlin.String,
    val grantable: kotlin.Boolean,
    val deprecated: kotlin.Boolean,
    val aliasOf: kotlin.String? = null,
)
"#;

const RESOURCE_PERMISSIONS: &str = r#"/**
 * One resource type's permissions, sorted by value.
 *
 * @property resourceType the resource type's authorization name, as grants store it
 * @property permissions its permissions, deprecated aliases included, sorted by value
 */
data class ResourcePermissions(
    val resourceType: kotlin.String,
    val permissions: kotlin.collections.List<PermissionDescription>,
)
"#;

/// The package's files, none when the client sees no permission.
pub(crate) fn files(service: &Service, package: &str, source: &str) -> Vec<File> {
    let resources = resources(service);
    if resources.is_empty() {
        return Vec::new();
    }
    let header = format!(
        "// Generated by Crucible. DO NOT EDIT.\n@file:Suppress(\"DEPRECATION\")\npackage {package}.permissions\n\n"
    );
    let file = |name: &str, body: String| File {
        path: format!("{source}/permissions/{name}.kt"),
        contents: format!("{header}{body}"),
    };
    let mut files = Vec::new();
    let mut registry = Vec::new();
    for (name, client) in &resources {
        files.push(file(name, enumeration(service, name, client)));
        registry.push(entry(client));
    }
    files.push(file(
        "PermissionDescription",
        PERMISSION_DESCRIPTION.to_owned(),
    ));
    files.push(file("ResourcePermissions", RESOURCE_PERMISSIONS.to_owned()));
    // `Permissions.PERMISSIONS` from Java, as the constants are static
    // fields: both annotations are optional expectations in common code.
    let mut body = kdoc(
        "",
        None,
        &["Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the `grantable` ones that are not `deprecated`.".to_owned()],
        &[],
    );
    body.push_str(&format!(
        "@kotlin.jvm.JvmField\nval PERMISSIONS: kotlin.collections.List<ResourcePermissions> = listOf(\n{}\n)\n",
        registry.join("\n")
    ));
    files.push(File {
        path: format!("{source}/permissions/Permissions.kt"),
        contents: format!(
            "// Generated by Crucible. DO NOT EDIT.\n@file:Suppress(\"DEPRECATION\")\n@file:kotlin.jvm.JvmName(\"Permissions\")\npackage {package}.permissions\n\n{body}"
        ),
    });
    files
}

/// One resource's open permission type, `GraphPermission`.
fn enumeration(service: &Service, name: &str, client: &ClientResource<'_>) -> String {
    let shape = service.name_of(client.id);
    let resource = client.resource;
    let mut out = kdoc(
        "",
        None,
        &[
            format!(
                "The permissions {} accepts ({}), by the values grants store.",
                code(shape),
                code(&resource.name)
            ),
            "Open: a value this client does not know (a newer server's) is kept as it is and written back unchanged, so compare with the constants or `value`.".to_owned(),
        ],
        &["@property value the permission value, as grants store it".to_owned()],
    );
    out.push_str(&format!(
        "data class {name}(val value: kotlin.String) {{\n    override fun toString(): kotlin.String = value\n\n"
    ));
    out.push_str(&kdoc(
        "    ",
        None,
        &["The permission a deprecated alias stands for; any other value, one this client does not know included, is itself.".to_owned()],
        &[],
    ));
    let aliases = client.aliases();
    if aliases.is_empty() {
        out.push_str(&format!("    fun canonical(): {name} = this\n"));
    } else {
        // By value, not by constant: an unknown instance equal to an alias
        // maps too, and the deprecated constants are never referenced.
        out.push_str(&format!("    fun canonical(): {name} = when (value) {{\n"));
        for (alias, primary) in aliases {
            out.push_str(&format!(
                "        {} -> `{}`\n",
                literal(&alias.value),
                constant(&constant_symbol(&primary.symbol))
            ));
        }
        out.push_str("        else -> this\n    }\n");
    }
    out.push_str("\n    companion object {\n");
    for (index, permission) in client.permissions.iter().enumerate() {
        let mut notes = vec![format!("The {} permission.", code(&permission.value))];
        if permission.alias_of.is_some() {
            let primary = primary(resource, permission);
            notes.push(format!(
                "An alias of {}: [canonical] maps it to [{}].",
                code(&primary.value),
                constant(&constant_symbol(&primary.symbol))
            ));
        }
        if index > 0 {
            out.push('\n');
        }
        out.push_str(&kdoc_for(
            "        ",
            permission.docs.as_deref(),
            &notes,
            &[],
            &self::notes(permission),
            "",
        ));
        out.push_str(&format!(
            "        @kotlin.jvm.JvmField val `{}` = {name}({})\n",
            constant(&constant_symbol(&permission.symbol)),
            literal(&permission.value)
        ));
    }
    out.push_str("    }\n}\n");
    out
}

/// The resource's `PERMISSIONS` entry, its permissions sorted by value.
fn entry(client: &ClientResource<'_>) -> String {
    let entries: Vec<String> = client
        .entries()
        .iter()
        .map(|e| {
            let alias = e
                .alias_of
                .map(|primary| format!(", aliasOf = {}", literal(primary)))
                .unwrap_or_default();
            format!(
                "        PermissionDescription(value = {}, description = {}, tier = {}, grantable = {}, deprecated = {}{alias}),",
                literal(e.value),
                literal(e.description),
                literal(e.tier),
                e.grantable,
                e.deprecated,
            )
        })
        .collect();
    format!(
        "    ResourcePermissions(\n        resourceType = {},\n        permissions = listOf(\n{}\n        ),\n    ),",
        literal(&client.resource.name),
        entries
            .iter()
            .map(|entry| format!("    {entry}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}

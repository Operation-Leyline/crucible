//! The `<package>.roles` package (docs/roles.md §7 "Clients"): the
//! service's role and scope values as open types in the open-enum
//! convention (`Role.OWNER`, `Scope.ALL_NOTES`), which keep a value this
//! client does not know (a newer server's, a custom role's) and write it
//! back unchanged; and `ROLES`, the registry a console's role picker reads.
//! A package of its own, as `permissions` is, so no model name can collide
//! with these; common code only. Generated from
//! `crucible_codegen_common::roles`' one rule, as every client's is: public
//! roles and scopes only, in catalogue order, and only public permissions
//! in a role's `permissions`.

use std::collections::BTreeSet;

use crucible_codegen_common::permissions::{constant_symbol, upper_snake};
use crucible_codegen_common::roles::{ClientRole, client_roles, client_scopes, custom};
use crucible_ir::Diagnostics;
use crucible_ir::ir::{DocNotes, Service};

use super::{File, Links, code, kdoc, kdoc_linked, literal};

/// A role's or scope's constant: Kotlin's upper snake case, as permissions'.
fn constant(symbol: &str) -> String {
    upper_snake(&constant_symbol(symbol))
}

/// Two roles (or two scopes) that Kotlin would spell as one constant, or
/// one Kotlin reserves.
pub(crate) fn check(service: &Service, diagnostics: &mut Diagnostics) {
    let roles = client_roles(service);
    if roles.is_empty() {
        return;
    }
    let scopes = client_scopes(service);
    for (what, symbols) in [
        (
            "role",
            roles
                .iter()
                .map(|r| r.role.symbol.as_str())
                .collect::<Vec<_>>(),
        ),
        (
            "scope",
            scopes.iter().map(|s| s.scope.symbol.as_str()).collect(),
        ),
    ] {
        let mut seen = BTreeSet::new();
        for symbol in symbols {
            let constant = constant(symbol);
            // Kotlin reserves names made only of underscores.
            if constant.chars().all(|c| c == '_') {
                diagnostics.push(
                    &service.id,
                    format!(
                        "{what} `{symbol}` spells the Kotlin constant `{constant}`, which Kotlin reserves"
                    ),
                );
            } else if !seen.insert(constant.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "{what} `{symbol}` shares the Kotlin constant `{constant}` with another"
                    ),
                );
            }
        }
    }
}

/// The generic registry records: the same for every client.
const ROLE_DESCRIPTION: &str = r#"/**
 * One role in the registry.
 *
 * @property value what bindings store
 * @property description the model's documentation for it, empty when it has none
 * @property scopes the scope values it may be bound at, in catalogue order
 * @property holders the kinds of principal that may hold it; empty: any
 * @property assignedBy the roles whose holders alone may assign it; empty: whoever may write bindings
 * @property permissions what it grants: the permissions this client knows
 */
data class RoleDescription(
    val value: kotlin.String,
    val description: kotlin.String,
    val scopes: kotlin.collections.List<kotlin.String>,
    val holders: kotlin.collections.List<kotlin.String>,
    val assignedBy: kotlin.collections.List<kotlin.String>,
    val permissions: kotlin.collections.List<RolePermission>,
)
"#;

const ROLE_PERMISSION: &str = r#"/**
 * One permission a role grants.
 *
 * @property resourceType the resource type a grant names
 * @property permission what grants store
 */
data class RolePermission(
    val resourceType: kotlin.String,
    val permission: kotlin.String,
)
"#;

/// The package's files, none when the client sees no role.
pub(crate) fn files(service: &Service, package: &str, source: &str) -> Vec<File> {
    let roles = client_roles(service);
    if roles.is_empty() {
        return Vec::new();
    }
    let scopes = client_scopes(service);
    let links = Links { service, package };
    let header = format!(
        "// Generated by Crucible. DO NOT EDIT.\n@file:Suppress(\"DEPRECATION\")\npackage {package}.roles\n\n"
    );
    let file = |name: &str, body: String| File {
        path: format!("{source}/roles/{name}.kt"),
        contents: format!("{header}{body}"),
    };
    let prefix = service.name_of(&service.id);
    let mut files = vec![
        file(
            "Role",
            enumeration(
                &links,
                "Role",
                &format!(
                    "The roles of {}, by the values bindings store.",
                    code(prefix)
                ),
                roles
                    .iter()
                    .map(|r| {
                        (
                            r.role.symbol.as_str(),
                            r.value,
                            r.role.docs.as_deref(),
                            &r.role.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file(
            "Scope",
            enumeration(
                &links,
                "Scope",
                &format!(
                    "The scopes a role of {} is bound at, by the values bindings store.",
                    code(prefix)
                ),
                scopes
                    .iter()
                    .map(|s| {
                        (
                            s.scope.symbol.as_str(),
                            s.value,
                            s.scope.docs.as_deref(),
                            &s.scope.notes,
                        )
                    })
                    .collect(),
            ),
        ),
        file("RoleDescription", ROLE_DESCRIPTION.to_owned()),
        file("RolePermission", ROLE_PERMISSION.to_owned()),
    ];
    // `Roles.ROLES` from Java, as `Permissions.PERMISSIONS` is.
    files.push(File {
        path: format!("{source}/roles/Roles.kt"),
        contents: format!(
            "// Generated by Crucible. DO NOT EDIT.\n@file:Suppress(\"DEPRECATION\")\n@file:kotlin.jvm.JvmName(\"Roles\")\npackage {package}.roles\n\n{}",
            registry(service, &roles)
        ),
    });
    files
}

/// One open value type, `Role` or `Scope`.
fn enumeration(
    links: &Links<'_>,
    name: &str,
    summary: &str,
    values: Vec<(&str, &str, Option<&str>, &DocNotes)>,
) -> String {
    let what = name.to_ascii_lowercase();
    let mut out = kdoc(
        "",
        None,
        &[
            summary.to_owned(),
            "Open: a value this client does not know (a newer server's, or a custom role's) is kept as it is and written back unchanged, so compare with the constants or `value`.".to_owned(),
        ],
        &[format!("@property value the {what} value, as bindings store it")],
    );
    out.push_str(&format!(
        "data class {name}(val value: kotlin.String) {{\n    override fun toString(): kotlin.String = value\n\n    companion object {{\n"
    ));
    for (index, (symbol, value, docs, notes)) in values.into_iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        out.push_str(&kdoc_linked(
            links,
            "        ",
            docs,
            &[format!("The {} {what}.", code(value))],
            &[],
            notes,
            "",
        ));
        out.push_str(&format!(
            "        @kotlin.jvm.JvmField val `{}` = {name}({})\n",
            constant(symbol),
            literal(value)
        ));
    }
    out.push_str("    }\n}\n");
    out
}

/// `listOf("a", "b")`.
fn strings<S: AsRef<str>>(items: &[S]) -> String {
    format!(
        "listOf({})",
        items
            .iter()
            .map(|s| literal(s.as_ref()))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// `ROLES`.
fn registry(service: &Service, roles: &[ClientRole<'_>]) -> String {
    let summary = if custom(service) {
        "Every predefined role, in the service's catalogue order: what a role picker offers. The service also accepts custom roles, which are not listed."
    } else {
        "Every role, in the service's catalogue order: what a role picker offers."
    };
    let mut body = kdoc("", None, &[summary.to_owned()], &[]);
    let entries: Vec<String> = roles
        .iter()
        .map(|role| {
            let permissions: Vec<String> = role
                .permissions
                .iter()
                .map(|p| {
                    format!(
                        "RolePermission(resourceType = {}, permission = {})",
                        literal(p.resource_type),
                        literal(p.value)
                    )
                })
                .collect();
            format!(
                "    RoleDescription(\n        value = {},\n        description = {},\n        scopes = {},\n        holders = {},\n        assignedBy = {},\n        permissions = listOf({}),\n    ),",
                literal(role.value),
                literal(role.description),
                strings(&role.scopes),
                strings(&role.holders),
                strings(&role.assigned_by),
                permissions.join(", ")
            )
        })
        .collect();
    body.push_str(&format!(
        "@kotlin.jvm.JvmField\nval ROLES: kotlin.collections.List<RoleDescription> = listOf(\n{}\n)\n",
        entries.join("\n")
    ));
    body
}

//! The `[docs]` package: the API reference as `crucible generate docs
//! --sdks` writes it, with a `package.json`, a README and provenance, so
//! `crucible sdk` versions and publishes it like an SDK.

use crucible_ir::ir::Service;
use serde_json::{Value, json};

use super::{Channel, Docs, DocsSchemas, SdkFile};
use crate::File;
use crate::provenance::{Package, Stamp};
use crate::sdks::Versions;

/// The reference package's files at `version` (a development export
/// without one), describing each SDK at its version in `sdks`
/// ([`crate::sdks::file_at`]): the reference at the package's root, where
/// its relative links resolve, `sdks.json` beside `describe.json`, then
/// `package.json`, `README.md`, `crucible.json` and `crucible-model.json`.
/// `service` is the full lowered model; the package projects its audience.
pub fn package(
    file: &SdkFile,
    docs: &Docs,
    service: &Service,
    version: Option<&str>,
    sdks: &Versions,
    stamp: &Stamp,
) -> Result<Vec<File>, String> {
    let version = version.unwrap_or(Docs::DEVELOPMENT_VERSION);
    let mut options = crate::DocsOptions::default();
    options.schemas = match docs.schemas {
        DocsSchemas::Inline => crate::Schemas::Inline,
        DocsSchemas::Shared => crate::Schemas::Shared,
        DocsSchemas::Omit => crate::Schemas::Omit,
    };
    let mut files = crate::docs(service, docs.audience, &options)
        .map_err(|diagnostics| format!("cannot generate docs:\n{diagnostics}"))?;
    files.push(crate::sdks::file_at(file, service, docs.audience, sdks)?);
    if docs.openapi {
        files.push(openapi(docs, service)?);
    }
    for owned in ["package.json", "README.md"] {
        if files.iter().any(|file| file.path == owned) {
            return Err(format!(
                "docs: the reference emitted {owned}, which its package owns"
            ));
        }
    }
    let projected = crucible_ir::project(service, docs.audience)
        .map_err(|diagnostics| format!("docs:\n{diagnostics}"))?;
    files.push(File {
        path: "package.json".into(),
        contents: manifest(docs, &projected, version),
    });
    files.push(File {
        path: "README.md".into(),
        contents: readme(docs, &projected, version, sdks),
    });
    crate::provenance::stamp(
        &mut files,
        &projected,
        docs.audience,
        &Package {
            language: Docs::LANGUAGE,
            name: &docs.package,
            version,
        },
        stamp,
    )
    .map_err(|error| format!("docs: {error}"))?;
    Ok(files)
}

/// The OpenAPI document's name beside `describe.json`.
pub const OPENAPI_FILE: &str = "openapi.json";

/// `openapi.json`: the service as the package's audience sees it, for
/// tools that read OpenAPI. The reference stays the fuller description. A
/// service the OpenAPI generator refuses fails the package, with its
/// diagnostics, since the file was asked for.
#[cfg(feature = "openapi")]
fn openapi(docs: &Docs, service: &Service) -> Result<File, String> {
    let options = crate::OpenApiOptions {
        endpoint: docs.endpoint.clone(),
    };
    crate::Generator::OpenApi(options)
        .emit_for_audience(service, docs.audience)
        .map_err(|diagnostics| format!("docs.openapi:\n{diagnostics}"))?
        .into_iter()
        .find(|file| file.path == OPENAPI_FILE)
        .ok_or_else(|| format!("docs.openapi: the generator wrote no {OPENAPI_FILE}"))
}

#[cfg(not(feature = "openapi"))]
fn openapi(_docs: &Docs, _service: &Service) -> Result<File, String> {
    Err("docs.openapi: this crucible was built without the OpenAPI generator".into())
}

/// `package.json`: identity, where it is published, and nothing to run.
/// It never says `"private": true`, which npm refuses to publish: a
/// private reference is kept private by its registry and `access`.
fn manifest(docs: &Docs, service: &Service, version: &str) -> String {
    let mut package = serde_json::Map::new();
    package.insert("name".into(), json!(docs.package));
    package.insert("version".into(), json!(version));
    let title = service.title.as_deref().unwrap_or(service.id.name());
    package.insert(
        "description".into(),
        json!(
            docs.description
                .clone()
                .unwrap_or_else(|| format!("The {title} API reference, generated by Crucible."))
        ),
    );
    if let Some(license) = &docs.license {
        package.insert("license".into(), json!(license));
    }
    if let Some(repository) = &docs.repository {
        package.insert(
            "repository".into(),
            json!({"type": "git", "url": repository}),
        );
    }
    if let Some(homepage) = &docs.homepage {
        package.insert("homepage".into(), json!(homepage));
    }
    if let Some(Channel::Npm { url, access, .. }) = &docs.channel {
        let mut config = serde_json::Map::new();
        config.insert("registry".into(), json!(url));
        if let Some(access) = access {
            config.insert("access".into(), json!(access));
        }
        package.insert("publishConfig".into(), Value::Object(config));
    }
    package.insert(
        "crucible".into(),
        json!({"version": env!("CARGO_PKG_VERSION"), "service": service.id.to_string(),
            "serviceVersion": service.version}),
    );
    let mut text =
        serde_json::to_string_pretty(&Value::Object(package)).expect("a JSON value serializes");
    text.push('\n');
    text
}

/// What the package holds and which SDK releases it describes. Model text
/// reaches it only as escaped Markdown, as in an SDK's README.
fn readme(docs: &Docs, service: &Service, version: &str, sdks: &Versions) -> String {
    use crucible_codegen_common::guide::{code_span, markdown_text};
    let title = markdown_text(service.title.as_deref().unwrap_or(service.id.name()));
    let mut out = format!(
        "# {}\n\n<!-- Generated by crucible. Change the model or the SDK configuration and regenerate. -->\n\n\
         The {title} API reference ({}, version {}), generated by Crucible from the service's model. \
         This is package version {}.\n\n\
         | File | Holds |\n|---|---|\n\
         | `describe.json` | The reference as data (`crucible.describe/1`) |\n\
         | `sdks.json` | Each SDK's names, snippets and guide (`crucible.sdks/1`) |\n\
         | `changes.json` | The release chain (`crucible.changes/1`) |\n\
         | `llms.txt`, `llms-full.txt`, `src/` | The same reference as Markdown |\n\
         | `index.html` | A static page that renders `describe.json` |\n{openapi}",
        markdown_text(&docs.package),
        code_span(&service.id.to_string()),
        code_span(&service.version),
        code_span(version),
        openapi = if docs.openapi {
            "| `openapi.json` | The same API as an OpenAPI 3.1 document |\n"
        } else {
            ""
        },
    );
    if !sdks.is_empty() {
        out.push_str("\nIt describes these SDK releases:\n\n");
        for (name, version) in sdks {
            out.push_str(&format!("- {} {}\n", code_span(name), code_span(version)));
        }
    }
    out
}

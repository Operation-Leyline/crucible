use std::fs;

use crucible_codegen::{File, write};

fn file(path: &str, contents: &str) -> File {
    File {
        path: path.into(),
        contents: contents.into(),
    }
}

#[test]
fn regeneration_retains_unchanged_files_and_removes_only_owned_files() {
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    let files = vec![
        file("src/Current.java", "current"),
        file("src/Removed.java", "old"),
    ];
    write(&out, &files).unwrap();
    fs::write(out.join("src/Handwritten.java"), "mine").unwrap();
    for directory in ["target", "node_modules", "dist", ".build"] {
        fs::create_dir(out.join(directory)).unwrap();
        fs::write(out.join(directory).join("keep"), "build").unwrap();
    }
    let metadata = fs::metadata(out.join("src/Current.java")).unwrap();
    let marker_metadata = fs::metadata(out.join(".crucible")).unwrap();
    write(&out, &files).unwrap();
    assert_eq!(
        metadata.modified().unwrap(),
        fs::metadata(out.join("src/Current.java"))
            .unwrap()
            .modified()
            .unwrap()
    );
    assert_eq!(
        marker_metadata.modified().unwrap(),
        fs::metadata(out.join(".crucible"))
            .unwrap()
            .modified()
            .unwrap()
    );
    write(
        &out,
        &[
            file("src/Current.java", "current"),
            file("src/Added.java", "new"),
        ],
    )
    .unwrap();
    assert!(!out.join("src/Removed.java").exists());
    assert_eq!(
        fs::read_to_string(out.join("src/Handwritten.java")).unwrap(),
        "mine"
    );
    for directory in ["target", "node_modules", "dist", ".build"] {
        assert!(out.join(directory).join("keep").is_file());
    }
}

#[test]
fn invalid_paths_and_collisions_preserve_prior_output() {
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    write(&out, &[file("current", "original")]).unwrap();
    for path in [
        "../escape",
        "/absolute",
        "a/../escape",
        "a\\escape",
        "C:/escape",
        ".crucible",
        "target/owned",
        "a//b",
        "./file",
        ".CRUCIBLE",
        ".crucible ",
        "src/File.java.",
    ] {
        assert!(
            write(&out, &[file("current", "changed"), file(path, "bad")]).is_err(),
            "{path}"
        );
        assert_eq!(fs::read_to_string(out.join("current")).unwrap(), "original");
    }
    fs::write(out.join("consumer"), "mine").unwrap();
    assert!(write(&out, &[file("current", "changed"), file("consumer", "bad")]).is_err());
    assert_eq!(fs::read_to_string(out.join("current")).unwrap(), "original");
    assert_eq!(fs::read_to_string(out.join("consumer")).unwrap(), "mine");
    assert!(write(&out, &[file("duplicate", "a"), file("duplicate", "b")]).is_err());
    assert!(write(&out, &[file("File", "a"), file("file", "b")]).is_err());
    assert!(write(&out, &[file("parent", "a"), file("parent/child", "b")]).is_err());
    assert!(write(&out, &[file("Parent", "a"), file("parent/child", "b")]).is_err());
}

#[test]
fn preserves_unrelated_files_on_initial_generation_and_legacy_migration() {
    let root = tempfile::tempdir().unwrap();
    fs::write(root.path().join("consumer"), "mine").unwrap();
    write(root.path(), &[file("generated", "source")]).unwrap();
    assert!(root.path().join("consumer").is_file());
    fs::write(
        root.path().join(".crucible"),
        "Generated by crucible. This directory is emptied and rewritten on every run.\n",
    )
    .unwrap();
    write(root.path(), &[file("generated", "updated")]).unwrap();
    assert!(root.path().join("consumer").is_file());
    assert_eq!(
        fs::read_to_string(root.path().join("generated")).unwrap(),
        "updated"
    );
}

#[test]
fn corrupt_manifest_is_rejected_before_any_writes() {
    let root = tempfile::tempdir().unwrap();
    fs::write(root.path().join(".crucible"), "not json").unwrap();
    assert!(write(root.path(), &[file("generated", "source")]).is_err());
    assert!(!root.path().join("generated").exists());
    fs::write(root.path().join(".crucible"), "[\"../escape\"]").unwrap();
    assert!(write(root.path(), &[file("generated", "source")]).is_err());
    assert!(!root.path().join("generated").exists());
}

#[cfg(unix)]
#[test]
fn rejects_symlink_outputs_and_stale_file_parents() {
    use std::os::unix::fs::symlink;
    let root = tempfile::tempdir().unwrap();
    let external = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    write(&out, &[file("src/file", "source")]).unwrap();
    fs::remove_file(out.join("src/file")).unwrap();
    fs::remove_dir(out.join("src")).unwrap();
    symlink(external.path(), out.join("src")).unwrap();
    fs::write(external.path().join("file"), "keep").unwrap();
    assert!(write(&out, &[]).is_err());
    assert_eq!(
        fs::read_to_string(external.path().join("file")).unwrap(),
        "keep"
    );
    let linked = root.path().join("linked");
    symlink(external.path(), &linked).unwrap();
    assert!(write(&linked, &[file("new", "bad")]).is_err());
    assert!(!external.path().join("new").exists());
}

#[test]
fn failed_write_leaves_the_directory_regenerable() {
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    write(&out, &[file("z.txt", "old")]).unwrap();
    let locked = out.join("z.txt");
    let mut permissions = fs::metadata(&locked).unwrap().permissions();
    permissions.set_readonly(true);
    fs::set_permissions(&locked, permissions.clone()).unwrap();
    // A superuser writes through read-only files, so no failure to provoke.
    if fs::OpenOptions::new().append(true).open(&locked).is_ok() {
        return;
    }
    let files = [file("new.txt", "new"), file("z.txt", "changed")];
    assert!(write(&out, &files).is_err());
    #[allow(clippy::permissions_set_readonly_false)]
    permissions.set_readonly(false);
    fs::set_permissions(&locked, permissions).unwrap();
    write(&out, &files).unwrap();
    assert_eq!(fs::read_to_string(out.join("new.txt")).unwrap(), "new");
    assert_eq!(fs::read_to_string(out.join("z.txt")).unwrap(), "changed");
}

#[test]
fn case_only_rename_regenerates() {
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    write(&out, &[file("src/Foo.txt", "old"), file("Dir/a.txt", "a")]).unwrap();
    write(&out, &[file("src/foo.txt", "new"), file("dir/a.txt", "a")]).unwrap();
    let names: Vec<_> = fs::read_dir(out.join("src"))
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect();
    assert_eq!(names, ["foo.txt"]);
    assert_eq!(fs::read_to_string(out.join("src/foo.txt")).unwrap(), "new");
    assert_eq!(fs::read_to_string(out.join("dir/a.txt")).unwrap(), "a");
}

#[test]
fn case_variant_of_a_consumer_file_is_not_adopted() {
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("sdk");
    write(&out, &[file("generated", "source")]).unwrap();
    fs::write(out.join("Bar.txt"), "mine").unwrap();
    // Either the filesystem keeps the two names apart or it refuses; the
    // consumer's file survives in both cases.
    let _ = write(&out, &[file("generated", "source"), file("bar.txt", "gen")]);
    assert_eq!(fs::read_to_string(out.join("Bar.txt")).unwrap(), "mine");
}

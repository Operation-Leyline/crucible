#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Middleware {
    /// `x-amz-content-sha256` on every request with a body.
    ContentSha256,
}

#[derive(Debug, Clone)]
pub struct Options {
    pub package_name: String,
    pub package_version: String,
    /// Defaults to the service name plus `Client`.
    pub client_name: Option<String>,
    /// The endpoint a client uses when its config names none.
    pub endpoint: Option<String>,
    /// Middleware every client runs by default, ahead of the caller's.
    pub middleware: Vec<Middleware>,
    /// Merged over the generated `package.json`: publishing, repository, scope.
    pub package_json: Option<Value>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    /// Relative to the output directory, with `/` separators.
    pub path: String,
    pub contents: String,
}


pub fn emit(service: &Service, options: &Options) -> Result<Vec<File>, Diagnostics> {
    service.require_capabilities(&capabilities())?;
    let mut diagnostics = Diagnostics::default();
    let client = options
        .client_name
        .clone()
        .unwrap_or_else(|| format!("{}Client", service.id.name()));
    for id in service.shapes.keys().filter(|id| !id.is_prelude()) {
        let name = service.name_of(id);
        if RUNTIME_EXPORTS.contains(&name) || name == client {
            diagnostics.push(
                id,
                format!("`{name}` collides with a name the TypeScript client exports"),
            );
        } else if RESERVED.contains(&name) {
            diagnostics.push(
                id,
                format!("`{name}` is reserved in the generated TypeScript client"),
            );
        }
    }
    for operation in &service.operations {
        if RESERVED.contains(&operation.name()) {
            diagnostics.push(
                &operation.id,
                format!(
                    "`{}` is reserved in the generated TypeScript client",
                    operation.name()
                ),
            );
        }
    }
    for operation in &service.operations {
        let Some(stream) = &operation.request.event_stream else {
            continue;
        };
        if let Some(crucible_smithy::ir::Shape::Union(union)) = service.shape(&stream.target) {
            for arm in &union.members {
                if matches!(service.shape(&arm.target), Some(crucible_smithy::ir::Shape::Structure(s)) if s.error.is_some())
                {
                    diagnostics.push(
                        &stream.target.with_member(&arm.name),
                        "a client cannot send a modeled error in an input event stream",
                    );
                }
            }
        }
    }
    let errors = errors::emit(service, &mut diagnostics);
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    let file = |path: &str, contents: String| File {
        path: path.to_owned(),
        contents,
    };
    Ok(vec![
        file("src/runtime.ts", RUNTIME.replace("\r\n", "\n")),
        file(
            "src/query.ts",
            include_str!("../runtime/query.ts").replace("\r\n", "\n"),
        ),
        file(
            "src/endpoints.ts",
            include_str!("../runtime/endpoints.ts").replace("\r\n", "\n"),
        ),
        file(
            "src/waiters.ts",
            include_str!("../runtime/waiters.ts").replace("\r\n", "\n"),
        ),
        file(
            "src/credentials.ts",
            include_str!("../runtime/credentials.ts").replace("\r\n", "\n"),
        ),
        file(
            "src/checksums.ts",
            include_str!("../runtime/checksums.ts").replace("\r\n", "\n"),
        ),
        file(
            "src/events.ts",
            include_str!("../runtime/events.ts").replace("\r\n", "\n"),
        ),
        file("src/models.ts", models::emit(service)),
        file("src/errors.ts", errors),
        file("src/schemas.ts", schemas::emit(service)),
        file("src/client.ts", client::emit(service, options, &client)),
        file("src/index.ts", index(&client)),
        file("package.json", package_json(service, options)),
        file("tsconfig.json", TSCONFIG.to_owned()),
        file("crucible.json", provenance(service)),
    ])
}

fn index(client: &str) -> String {
    format!(
        "{HEADER}export {{ credentialsFromEnvironment, credentialsFromProfile, chainCredentials, cacheCredentials }} from \"./credentials.js\";\nexport type {{ AwsCredentials }} from \"./credentials.js\";\nexport {{ WaiterError, WaiterTimeout }} from \"./waiters.js\";\nexport {{ ChecksumError }} from \"./checksums.js\";\nexport type {{ ChecksumPolicy }} from \"./checksums.js\";\nexport type {{ WaiterOptions, WaiterResult }} from \"./waiters.js\";\nexport * from \"./models.js\";\n\
         export * from \"./errors.js\";\n\
         export {{ {client} }} from \"./client.js\";\n\
         export {{ AuthenticationError, ByteStream, Decimal, EventStream, EventStreamError, NetworkError, ServiceError, TimeoutError, contentSha256, stringifyJson }} from \"./runtime.js\";\n\
         export type {{\n  ClientConfig,\n  Document,\n  Fetch,\n  Middleware,\n  Next,\n  RequestOptions,\n  \
         ResponseMetadata,\n  AuthScheme,\n  BasicCredentials,\n  IdentityProvider,\n  RetryConfig,\n  TokenProvider,\n  Unit,\n  UnknownUnion,\n}} from \"./runtime.js\";\n"
    )
}

fn provenance(service: &Service) -> String {
    let schema = serde_json::to_string(&crucible_codegen_common::schema(service, str::to_owned))
        .expect("schema serializes");
    serde_json::to_string_pretty(&json!({
        "generatorVersion": env!("CARGO_PKG_VERSION"), "service": service.id.to_string(),
        "serviceVersion": service.version, "schemaSha256": format!("{:x}", Sha256::digest(schema.as_bytes())),
    })).expect("provenance serializes") + "\n"
}

fn package_json(service: &Service, options: &Options) -> String {
    let mut package = json!({
        "name": options.package_name,
        "version": options.package_version,
        "description": format!("Client for {} {}, generated by crucible. Do not edit.", service.id, service.version),
        "type": "module",
        "main": "./dist/index.js",
        "types": "./dist/index.d.ts",
        "exports": { ".": { "types": "./dist/index.d.ts", "default": "./dist/index.js" } },
        "files": ["dist", "crucible.json"],
        "sideEffects": false,
        "scripts": { "build": "tsc -p ." },
        "devDependencies": { "typescript": ">=5.7 <7" },
        "crucible": { "version": env!("CARGO_PKG_VERSION"), "service": service.id.to_string(), "serviceVersion": service.version },
    });
    if let Some(overrides) = &options.package_json {
        merge(&mut package, overrides);
    }
    let mut text = serde_json::to_string_pretty(&package).expect("a JSON value always serializes");
    text.push('\n');
    text
}

/// Objects merge key by key; anything else replaces.
fn merge(base: &mut Value, overrides: &Value) {
    match (base, overrides) {
        (Value::Object(base), Value::Object(overrides)) => {
            for (key, value) in overrides {
                merge(base.entry(key.clone()).or_insert(Value::Null), value);
            }
        }
        (base, value) => *base = value.clone(),
    }
}


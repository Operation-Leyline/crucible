#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Middleware {
    /// `x-amz-content-sha256` on every request with a body.
    ContentSha256,
}

#[derive(Debug, Clone)]
pub struct Options {
    pub package_name: String,
    pub package_version: String,
    /// Defaults to the service name plus `Client`.
    pub client_name: Option<String>,
    /// The endpoint a client uses when its config names none.
    pub endpoint: Option<String>,
    /// Middleware every client runs by default, ahead of the caller's.
    pub middleware: Vec<Middleware>,
    /// Merged over the generated `package.json`, last. It cannot set what
    /// Crucible owns: the name, version, `crucible`, `files`, `private` or
    /// `publishConfig`.
    pub package_json: Option<Value>,
    /// Description, URLs, license, authors, README, keywords, `private` and
    /// the npm registry.
    pub metadata: crucible_codegen_common::PackageMetadata,
}

/// `package.json` keys the generated package owns, which `package_json`
/// may not override: identity, provenance and the publish guard.
const OWNED_KEYS: &[&str] = &[
    "name",
    "version",
    "crucible",
    "files",
    "private",
    "publishConfig",
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    /// Relative to the output directory, with `/` separators.
    pub path: String,
    pub contents: String,
}

pub fn capabilities() -> crucible_smithy::Capabilities {
    use crucible_smithy::Feature;
    crucible_smithy::Capabilities::new([
        Feature::GreedyLabels,
        Feature::Sparse,
        Feature::IntEnum,
        Feature::BigInteger,
        Feature::BigDecimal,
        Feature::NonBlobPayload,
        Feature::ErrorPayload,
        Feature::MediaTypeHeaders,
    ])
}

pub fn emit(service: &Service, options: &Options) -> Result<Vec<File>, Diagnostics> {
    service.require_capabilities(&capabilities())?;
    crucible_codegen_common::check_service_exception_name(service)?;
    let mut diagnostics = Diagnostics::default();
    let client = options
        .client_name
        .clone()
        .unwrap_or_else(|| format!("{}Client", service.id.name()));
    let exception = crucible_codegen_common::service_exception_name(service);
    if client == exception {
        diagnostics.push(
            &service.id,
            format!("client name collides with generated service exception `{exception}`"),
        );
    }
    for id in service.shapes.keys().filter(|id| !id.is_prelude()) {
        let name = service.name_of(id);
        if RUNTIME_EXPORTS.contains(&name) || name == client {
            diagnostics.push(
                id,
                format!("`{name}` collides with a name the TypeScript client exports"),
            );
        } else if RESERVED.contains(&name) {
            diagnostics.push(
                id,
                format!("`{name}` is reserved in the generated TypeScript client"),
            );
        }
    }
    for operation in &service.operations {
        if RESERVED.contains(&operation.name()) {
            diagnostics.push(
                &operation.id,
                format!(
                    "`{}` is reserved in the generated TypeScript client",
                    operation.name()
                ),
            );
        }
    }
    if let Some(overrides) = &options.package_json {
        match overrides.as_object() {
            Some(overrides) => {
                for key in OWNED_KEYS
                    .iter()
                    .filter(|key| overrides.contains_key(**key))
                {
                    diagnostics.push(
                        &service.id,
                        format!(
                            "package_json cannot set `{key}`: the generated package.json owns it"
                        ),
                    );
                }
            }
            None => diagnostics.push(&service.id, "package_json must be a JSON object"),
        }
    }
    for problem in options.metadata.problems() {
        diagnostics.push(&service.id, format!("npm package metadata: {problem}"));
    }
    permissions::check_names(service, &mut diagnostics);
    let errors = errors::emit(service, &mut diagnostics);
    let permissions =
        permissions::present(service).then(|| permissions::emit(service, &mut diagnostics));
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    let file = |path: &str, contents: String| File {
        path: path.to_owned(),
        contents,
    };
    Ok(vec![
        file(
            "src/runtime.ts",
            crucible_codegen_common::service_exception_runtime(service, RUNTIME)
                .replace("\r\n", "\n"),
        ),
        file("src/models.ts", models::emit(service)),
        file("src/errors.ts", errors),
        file("src/schemas.ts", schemas::emit(service)),
        file("src/client.ts", client::emit(service, options, &client)),
        file(
            "src/index.ts",
            index(&client, &permissions::index_exports(service)),
        ),
        file("package.json", package_json(service, options)),
        file("tsconfig.json", TSCONFIG.to_owned()),
    ]
    .into_iter()
    .chain(permissions.map(|contents| file("src/permissions.ts", contents)))
    .chain(
        options
            .metadata
            .readme
            .clone()
            .map(|text| file("README.md", text)),
    )
    .chain(
        options
            .metadata
            .license_file
            .clone()
            .map(|text| file("LICENSE", text)),
    )
    .collect())
}

/// `permissions`: `index_exports`' re-exports of `permissions.ts`, empty
/// when there is none.
fn index(client: &str, permissions: &str) -> String {
    format!(
        "{HEADER}export * from \"./models.js\";\n\
         export * from \"./errors.js\";\n\
         {permissions}\
         export {{ {client} }} from \"./client.js\";\n\
         export {{ Decimal, NetworkError, ServiceError, TimeoutError, contentSha256, stringifyJson }} from \"./runtime.js\";\n\
         export type {{\n  ClientConfig,\n  Document,\n  Fetch,\n  Middleware,\n  Next,\n  RequestOptions,\n  \
         ResponseMetadata,\n  RetryConfig,\n  TokenProvider,\n  Unit,\n  UnknownUnion,\n}} from \"./runtime.js\";\n"
    )
}

fn package_json(service: &Service, options: &Options) -> String {
    let metadata = &options.metadata;
    let mut package = serde_json::Map::new();
    let mut set = |key: &str, value: Value| {
        package.insert(key.to_owned(), value);
    };
    set("name", json!(options.package_name));
    set("version", json!(options.package_version));
    set(
        "description",
        json!(metadata.description.clone().unwrap_or_else(|| format!(
            "Client for {} {}, generated by crucible. Do not edit.",
            service.id, service.version
        ))),
    );
    if !metadata.keywords.is_empty() {
        set("keywords", json!(metadata.keywords));
    }
    if let Some(homepage) = &metadata.homepage {
        set("homepage", json!(homepage));
    }
    if let Some(repository) = &metadata.repository {
        set("repository", json!({ "type": "git", "url": repository }));
    }
    if let Some(license) = &metadata.license {
        set("license", json!(license));
    } else if metadata.license_file.is_some() {
        set("license", json!("SEE LICENSE IN LICENSE"));
    }
    if let Some((author, contributors)) = metadata.authors.split_first() {
        set("author", json!(author));
        if !contributors.is_empty() {
            set("contributors", json!(contributors));
        }
    }
    // Unpublishable to npm: private with no npm registry, or released
    // through Git tags. `npm publish` refuses it.
    let registry = match &metadata.registry {
        Some(crucible_codegen_common::Registry::Npm { url, access, .. }) => Some((url, access)),
        _ => None,
    };
    let git = metadata.registry == Some(crucible_codegen_common::Registry::Git);
    if (metadata.private && registry.is_none()) || git {
        set("private", json!(true));
    }
    set("type", json!("module"));
    set("main", json!("./dist/index.js"));
    set("types", json!("./dist/index.d.ts"));
    set(
        "exports",
        json!({ ".": { "types": "./dist/index.d.ts", "default": "./dist/index.js" } }),
    );
    let mut files = vec!["dist", "crucible.json", "crucible-model.json"];
    if metadata.readme.is_some() {
        files.push("README.md");
    }
    set("files", json!(files));
    set("sideEffects", json!(false));
    set("scripts", json!({ "build": "tsc -p ." }));
    set("devDependencies", json!({ "typescript": ">=5.7 <7" }));
    if let Some((url, access)) = registry {
        let mut config = serde_json::Map::new();
        config.insert("registry".into(), json!(url));
        if let Some(access) = access {
            config.insert("access".into(), json!(access));
        }
        set("publishConfig", Value::Object(config));
    }
    set(
        "crucible",
        json!({ "version": env!("CARGO_PKG_VERSION"), "service": service.id.to_string(), "serviceVersion": service.version }),
    );
    let mut package = Value::Object(package);
    if let Some(overrides) = &options.package_json {
        merge(&mut package, overrides);
    }
    let mut text = serde_json::to_string_pretty(&package).expect("a JSON value always serializes");
    text.push('\n');
    text
}

/// Objects merge key by key; anything else replaces.
fn merge(base: &mut Value, overrides: &Value) {
    match (base, overrides) {
        (Value::Object(base), Value::Object(overrides)) => {
            for (key, value) in overrides {
                merge(base.entry(key.clone()).or_insert(Value::Null), value);
            }
        }
        (base, value) => *base = value.clone(),
    }
}


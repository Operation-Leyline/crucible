//! `permissions.py` (docs/permissions.md §6.3): per resource an open
//! enumeration of the values grants store, `GraphPermission.READ`, built on
//! the same `OpenEnum` as the model's string enums, so a value this client
//! does not know is kept verbatim; deprecated aliases with `canonical()`;
//! and `PERMISSIONS`, the registry a console's grant picker reads.
//! Internal permissions never appear, whatever the audience.

use std::collections::BTreeSet;

use crucible_codegen_common::documentation::with_notes;
use crucible_codegen_common::permissions::{
    ClientResource, client_resources, code_span, constant_symbol, notes, primary,
};
use crucible_ir::Diagnostics;
use crucible_ir::ir::Service;

use crate::names::{enum_member, literal};
use crate::python_doc;

/// The resources a client sees, sorted by authorization name, each with
/// its shape's name.
fn resources(service: &Service) -> Vec<(&str, ClientResource<'_>)> {
    client_resources(service)
        .into_iter()
        .map(|client| (service.name_of(client.id), client))
        .collect()
}

/// Whether the client gets a `permissions.py`.
pub(crate) fn present(service: &Service) -> bool {
    !client_resources(service).is_empty()
}

/// Two permissions of one resource that Python names alike would be one
/// enumeration member, and a model named `permissions` would shadow the
/// module as an attribute of the package.
pub(crate) fn check_names(service: &Service, diagnostics: &mut Diagnostics) {
    if !present(service) {
        return;
    }
    if service
        .shapes
        .keys()
        .any(|id| !id.is_prelude() && service.name_of(id) == "permissions")
    {
        diagnostics.push(
            &service.id,
            "a model named `permissions` takes the name of the Python module the client's permissions are generated in",
        );
    }
    for (shape, client) in resources(service) {
        let mut seen = BTreeSet::new();
        for permission in &client.permissions {
            let member = enum_member(&constant_symbol(&permission.symbol));
            if !seen.insert(member.clone()) {
                diagnostics.push(
                    &service.id,
                    format!(
                        "permission `{}` of `{shape}` shares the Python member `{member}` with another",
                        permission.symbol
                    ),
                );
            }
        }
    }
}

pub(crate) fn emit(service: &Service) -> String {
    let mut out = String::from(
        "# Generated by Crucible. Edit the .cru model, then regenerate.\n\"\"\"The permissions grants store, by resource type, and PERMISSIONS, the registry a grant picker reads.\"\"\"\nfrom __future__ import annotations\n\nfrom .runtime import OpenEnum, PermissionDescription, ResourcePermissions\n\n",
    );
    let resources = resources(service);
    let mut exports: Vec<String> = resources
        .iter()
        .map(|(shape, _)| format!("{shape}Permission"))
        .collect();
    exports.extend(
        [
            "PERMISSIONS",
            "PermissionDescription",
            "ResourcePermissions",
        ]
        .map(str::to_owned),
    );
    out.push_str(&format!(
        "__all__ = [{}]\n\n\n",
        exports
            .iter()
            .map(|name| literal(name))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    let mut registry = String::new();
    for (shape, client) in &resources {
        let resource = client.resource;
        let name = format!("{shape}Permission");
        out.push_str(&format!("class {name}(OpenEnum):\n"));
        python_doc(
            service,
            &mut out,
            "    ",
            &format!(
                "The permissions `{shape}` accepts (`{}`), by the values grants store. A value this client does not know is kept as it is, as an UNKNOWN member.",
                resource.name
            ),
        );
        for permission in &client.permissions {
            out.push_str(&format!(
                "    {} = {}\n",
                enum_member(&constant_symbol(&permission.symbol)),
                literal(&permission.value)
            ));
            let mut docs = permission.docs.clone().unwrap_or_default();
            if permission.alias_of.is_some() {
                if !docs.trim().is_empty() {
                    docs.push_str("\n\n");
                }
                docs.push_str(&format!(
                    "An alias of {}.",
                    code_span(&primary(resource, permission).value)
                ));
            }
            // An enumeration value's docstring, deprecation included, as the
            // model's enum values have theirs.
            if let Some(docs) = with_notes(
                Some(docs.as_str()).filter(|d| !d.trim().is_empty()),
                &notes(permission),
            ) {
                python_doc(service, &mut out, "    ", &docs);
            }
        }
        out.push_str(&format!("\n    def canonical(self) -> {name}:\n"));
        python_doc(
            service,
            &mut out,
            "        ",
            "The permission this one stands for: a deprecated alias's primary, or this one, unknown values included.",
        );
        for (alias, primary) in client.aliases() {
            out.push_str(&format!(
                "        if self is {name}.{}:\n            return {name}.{}\n",
                enum_member(&constant_symbol(&alias.symbol)),
                enum_member(&constant_symbol(&primary.symbol))
            ));
        }
        out.push_str("        return self\n\n\n");
        let entries: String = client
            .entries()
            .iter()
            .map(|e| {
                let alias = e
                    .alias_of
                    .map(|primary| format!(", alias_of={}", literal(primary)))
                    .unwrap_or_default();
                format!(
                    "        PermissionDescription(value={}, description={}, tier={}, grantable={}, deprecated={}{alias}),\n",
                    literal(e.value),
                    literal(e.description),
                    literal(e.tier),
                    python_bool(e.grantable),
                    python_bool(e.deprecated),
                )
            })
            .collect();
        registry.push_str(&format!(
            "    ResourcePermissions(resource_type={}, permissions=(\n{entries}    )),\n",
            literal(&resource.name)
        ));
    }
    out.push_str(&format!(
        "PERMISSIONS: tuple[ResourcePermissions, ...] = (\n{registry})\n"
    ));
    python_doc(
        service,
        &mut out,
        "",
        "Every permission this client knows, by resource type, deprecated aliases included. A grant picker offers only the grantable ones that are not deprecated.",
    );
    out
}

fn python_bool(value: bool) -> &'static str {
    if value { "True" } else { "False" }
}

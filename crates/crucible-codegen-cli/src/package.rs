use crucible_smithy::Diagnostics;
use crucible_smithy::ir::Service;

use crate::{Options, names};

pub(crate) fn validate(service: &Service, options: &Options, diagnostics: &mut Diagnostics) {
    let name = &options.bin_name;
    if !name.starts_with(|c: char| c.is_ascii_lowercase())
        || !name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '-' | '_'))
        || reserved_name(name)
    {
        diagnostics.push(&service.id, "CLI binary name must start with a lowercase letter and contain only lowercase letters, digits, hyphens or underscores; Cargo directory and Windows device names are reserved");
    }
    if semver::Version::parse(&options.package_version).is_err() {
        diagnostics.push(
            &service.id,
            "CLI package version must be a semantic version such as 0.1.0",
        );
    }
    if options.runtime_path.as_os_str().is_empty() || options.runtime_path.to_str().is_none() {
        diagnostics.push(
            &service.id,
            "CLI runtime path must be a nonempty UTF-8 path to the Crucible repository",
        );
    }
}

fn reserved_name(name: &str) -> bool {
    matches!(
        name,
        "build" | "deps" | "examples" | "incremental" | "con" | "prn" | "aux" | "nul"
    ) || name
        .strip_prefix("com")
        .or_else(|| name.strip_prefix("lpt"))
        .is_some_and(|suffix| suffix.len() == 1 && matches!(suffix.as_bytes()[0], b'1'..=b'9'))
}

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("strings serialize")
}

fn cargo_path(path: &str) -> String {
    let path = path.replace('\\', "/");
    // canonicalize() returns Windows verbatim paths, but Cargo represents path
    // dependencies as file URLs, which cannot encode the verbatim device prefix.
    if let Some(unc) = path.strip_prefix("//?/UNC/") {
        return format!("//{unc}");
    }
    if let Some(drive) = path.strip_prefix("//?/") {
        let bytes = drive.as_bytes();
        if bytes.len() >= 3 && bytes[0].is_ascii_alphabetic() && &bytes[1..3] == b":/" {
            return drive.to_owned();
        }
    }
    path
}

pub(crate) fn manifest(options: &Options) -> String {
    let dependency = |name: &str| {
        let path = options.runtime_path.join("crates").join(name);
        quoted(&cargo_path(&path.to_string_lossy()))
    };
    format!(
        "# Generated by crucible.\n[package]\nname = {}\nversion = {}\nedition = \"2024\"\npublish = false\n\n[workspace]\n\n[lib]\nname = \"generated_cli\"\n\n[[bin]]\nname = {}\npath = \"src/main.rs\"\n\n[dependencies]\ncrucible-client-runtime-rust = {{ path = {} }}\ncrucible-cli-runtime = {{ path = {} }}\nserde_json = \"1\"\ntokio = {{ version = \"1\", features = [\"macros\", \"rt-multi-thread\"] }}\n\n[lints.rust]\nunsafe_code = \"forbid\"\n",
        quoted(&options.bin_name),
        quoted(&options.package_version),
        quoted(&options.bin_name),
        dependency("crucible-client-runtime-rust"),
        dependency("crucible-cli-runtime"),
    )
}

pub(crate) const MAIN: &str = "// Generated by crucible.\n#[tokio::main]\nasync fn main() -> std::process::ExitCode {\n    match generated_cli::run(std::env::args_os()).await {\n        Ok(()) => std::process::ExitCode::SUCCESS,\n        Err(error) => crucible_cli_runtime::report(error),\n    }\n}\n";

pub(crate) fn library(service: &Service) -> String {
    let mut code = String::from(
        "// Generated by crucible.\npub mod client;\n\nuse crucible_cli_runtime::{Error, Invocation, Output, write_json};\n\npub const SCHEMA: &str = include_str!(\"../schema.json\");\n\n/// Parse process arguments and execute a service command.\npub async fn run(args: impl IntoIterator<Item = std::ffi::OsString>) -> Result<(), Error> {\n    if let Some(invocation) = crucible_cli_runtime::parse(SCHEMA, args)? {\n        dispatch(invocation).await?;\n    }\n    Ok(())\n}\n\n/// Execute a parsed invocation. Customize its Config before dispatch for\n/// token providers, interceptors and other service-specific integrations.\npub async fn dispatch(invocation: Invocation) -> Result<(), Error> {\n",
    );
    if service.operations.is_empty() {
        code = code.replace("Error, Invocation, Output, write_json", "Error, Invocation");
        // With no methods the SDK's connection field is intentionally unread.
        code = code.replace("pub mod client;", "#[allow(dead_code)]\npub mod client;");
        code.push_str(
            "    let _ = invocation;\n    Err(Error::input(\"service has no operations\"))\n}\n",
        );
        return code;
    }
    code.push_str(&format!("    let client = client::{}::new(invocation.config);\n    match invocation.operation.as_str() {{\n", names::client(service.id.name())));
    let mut operations = service.operations.iter().collect::<Vec<_>>();
    operations.sort_by_key(|operation| operation.name());
    for operation in operations {
        let name = names::function(operation.name());
        code.push_str(&format!("        {:?} => {{\n", operation.name()));
        let argument = if let Some(input) = &operation.input {
            code.push_str(&format!("            let input: client::{} = serde_json::from_value(invocation.input).map_err(|_| Error::input(\"input does not match the operation's modeled types\"))?;\n", service.name_of(input)));
            "input"
        } else {
            ""
        };
        if operation.paginated.is_some() {
            code.push_str(&format!("            if invocation.paginate {{\n                let mut pages = client.{}_pages(input);\n                let mut collected = Vec::new();\n                while let Some(page) = pages.next_page().await {{\n                    let page = page.map_err(Error::request)?;\n                    if invocation.output == Output::Jsonl {{\n                        write_json(&page)?;\n                    }} else {{\n                        collected.push(page);\n                    }}\n                }}\n                if invocation.output == Output::Json {{\n                    write_json(&collected)?;\n                }}\n                return Ok(());\n            }}\n", name.trim_start_matches("r#")));
        }
        if operation.output.is_some() {
            code.push_str(&format!("            let output = client.{name}({argument}).await.map_err(Error::request)?;\n            write_json(&output)\n        }}\n"));
        } else {
            code.push_str(&format!("            client.{name}({argument}).await.map_err(Error::request)?;\n            write_json(&())\n        }}\n"));
        }
    }
    code.push_str("        _ => Err(Error::input(\"unknown operation\")),\n    }\n}\n");
    // Services without pagination have no references to Output.
    if !service
        .operations
        .iter()
        .any(|operation| operation.paginated.is_some())
    {
        code = code.replace(
            "Error, Invocation, Output, write_json",
            "Error, Invocation, write_json",
        );
    }
    code
}

#[cfg(test)]
mod tests {
    use super::cargo_path;

    #[test]
    fn cargo_paths_remove_windows_verbatim_prefixes() {
        for path in [r"\\?\C:\Users\name\crucible", "//?/C:/Users/name/crucible"] {
            assert_eq!(cargo_path(path), "C:/Users/name/crucible");
        }
        for path in [
            r"\\?\UNC\server\share\crucible",
            "//?/UNC/server/share/crucible",
        ] {
            assert_eq!(cargo_path(path), "//server/share/crucible");
        }
    }

    #[test]
    fn cargo_paths_preserve_ordinary_paths() {
        for path in [
            "/home/name/crucible",
            "../crucible",
            "C:/Users/name/crucible",
            "//server/share/crucible",
        ] {
            assert_eq!(cargo_path(path), path);
        }
        assert_eq!(
            cargo_path(r"C:\Users\name\crucible"),
            "C:/Users/name/crucible"
        );
        assert_eq!(
            cargo_path(r"\\server\share\crucible"),
            "//server/share/crucible"
        );
    }
}

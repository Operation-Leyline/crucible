//! The Rust server emitter: an axum crate for one service.
//!
//! Output, under `src/`:
//! - `runtime.rs`: the vendored runtime (request parts, text and timestamp
//!   codecs, validation, responses)
//! - `models.rs`: a type per shape, with `Validate` for input shapes
//! - `errors.rs`: a struct per error, an enum per operation, `rejection`
//! - `api.rs`: a trait per resource for the service to implement
//! - `router.rs`: `router(service)`, an `axum::Router` serving every operation

mod api;
mod errors;
mod models;
mod names;
mod router;
mod types;

use crucible_smithy::ir::{Service, Shape};
use crucible_smithy::{Diagnostics, ShapeId};

pub(crate) const HEADER: &str =
    "// Generated by crucible. Do not edit: change the Smithy model and regenerate.\n\n";

const RUNTIME: &str = include_str!("../runtime/server.rs");

#[derive(Debug, Clone)]
pub struct Options {
    pub crate_name: String,
    pub crate_version: String,
    /// The error a rejected request becomes. Defaults to the service's one
    /// error whose name contains `Validation`.
    pub validation_error: Option<ShapeId>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    /// Relative to the output directory, with `/` separators.
    pub path: String,
    pub contents: String,
}

pub fn emit_server(service: &Service, options: &Options) -> Result<Vec<File>, Diagnostics> {
    let mut diagnostics = Diagnostics::default();
    let validation = match &options.validation_error {
        Some(id) => Some(id.clone()),
        None => validation_error(service, &mut diagnostics),
    };
    let models = models::emit(service, &mut diagnostics);
    check_patterns(service, &mut diagnostics);
    let errors = validation
        .as_ref()
        .map(|validation| errors::emit(service, validation, &mut diagnostics))
        .unwrap_or_default();
    let api = validation
        .as_ref()
        .map(|validation| api::emit(service, validation, &mut diagnostics))
        .unwrap_or_default();
    let router = router::emit(service, &mut diagnostics);
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    let file = |path: &str, contents: String| File {
        path: path.to_owned(),
        contents,
    };
    Ok(vec![
        file(
            "Cargo.toml",
            cargo_toml(service, options, models.code.contains("::regex::")),
        ),
        file("src/lib.rs", lib_rs(service)),
        file("src/runtime.rs", RUNTIME.replace("\r\n", "\n")),
        file("src/models.rs", models.code),
        file("src/errors.rs", errors),
        file("src/api.rs", api),
        file("src/router.rs", router),
    ])
}

fn validation_error(service: &Service, diagnostics: &mut Diagnostics) -> Option<ShapeId> {
    let candidates: Vec<&ShapeId> = service
        .shapes
        .iter()
        .filter(|(id, shape)| {
            matches!(shape, Shape::Structure(s) if s.error.is_some())
                && service.name_of(id).contains("Validation")
        })
        .map(|(id, _)| id)
        .collect();
    match candidates.as_slice() {
        [only] => Some((*only).clone()),
        _ => {
            diagnostics.push(
                &service.id,
                "name the error a rejected request becomes (--validation-error): the service has no single error named *Validation*",
            );
            None
        }
    }
}

/// Every `@pattern` must compile under the regex crate the server runs,
/// which lacks look-around and backreferences.
fn check_patterns(service: &Service, diagnostics: &mut Diagnostics) {
    let mut members = Vec::new();
    for (id, shape) in &service.shapes {
        match shape {
            Shape::Structure(s) | Shape::Union(s) => {
                members.extend(s.members.iter().map(|m| (id.with_member(&m.name), m)));
            }
            Shape::List(l) => members.push((id.with_member("member"), &l.member)),
            Shape::Map(m) => {
                members.push((id.with_member("key"), &m.key));
                members.push((id.with_member("value"), &m.value));
            }
            _ => {}
        }
    }
    for (id, member) in members {
        if let Some(pattern) = &member.constraints.pattern {
            if let Err(error) = regex::Regex::new(pattern) {
                diagnostics.push(
                    &id,
                    format!("@pattern {pattern:?} does not compile for the Rust server: {error}"),
                );
            }
        }
    }
}

fn lib_rs(service: &Service) -> String {
    format!(
        "{HEADER}//! Server for {} {}, generated by crucible.\n//!\n//! Implement the traits in [`api`] and serve [`router`].\n\n#![allow(clippy::all, unused_imports, unused_variables, dead_code, non_snake_case)]\n\npub mod api;\npub mod errors;\npub mod models;\nmod router;\npub mod runtime;\n\npub use router::router;\npub use runtime::Context;\n",
        service.id, service.version
    )
}

fn cargo_toml(service: &Service, options: &Options, regex: bool) -> String {
    let regex = if regex { "regex = \"1\"\n" } else { "" };
    format!(
        "# Generated by crucible. Do not edit: change the Smithy model and regenerate.\n\n[package]\nname = {name:?}\nversion = {version:?}\nedition = \"2024\"\ndescription = {description:?}\npublish = false\n\n[dependencies]\naxum = \"0.8\"\nchrono = {{ version = \"0.4\", default-features = false, features = [\"std\", \"serde\"] }}\n{regex}serde = {{ version = \"1\", features = [\"derive\"] }}\nserde_json = \"1\"\n",
        name = options.crate_name,
        version = options.crate_version,
        description = format!(
            "Server for {} {}, generated by crucible. Do not edit.",
            service.id, service.version
        ),
    )
}

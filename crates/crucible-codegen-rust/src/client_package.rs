use crucible_codegen_common::guide;
use crucible_ir::Diagnostics;
use crucible_ir::ir::Service;

use crate::{ClientOptions, File, RuntimeDependency, generate_client, names};

const REPOSITORY: &str = "https://github.com/Operation-Leyline/crucible";
const RUNTIME: &str = "crucible-client-runtime-rust";

/// Emit an ordinary Cargo SDK dependency, including its runtime dependency.
/// Consumers use its service client and runtime API without build scripts.
pub fn emit_client_package(
    service: &Service,
    options: &ClientOptions,
) -> Result<Vec<File>, Diagnostics> {
    let mut diagnostics = Diagnostics::default();
    let name = client_package_name(service, options);
    if !valid_name(&name) {
        diagnostics.push(&service.id, format!("invalid Cargo SDK package name {name:?}; use a Rust crate name containing ASCII letters, digits, hyphens or underscores"));
    }
    if semver::Version::parse(&options.package_version).is_err() {
        diagnostics.push(
            &service.id,
            format!(
                "invalid Cargo SDK package version {:?}; use a complete semantic version",
                options.package_version
            ),
        );
    }
    let metadata = &options.metadata;
    for problem in metadata.problems().into_iter().chain(
        crucible_codegen_common::metadata::cargo_keyword_problems(&metadata.keywords),
    ) {
        diagnostics.push(
            &service.id,
            format!("Cargo SDK package metadata: {problem}"),
        );
    }
    if matches!(
        metadata.registry,
        Some(crucible_codegen_common::Registry::Npm { .. })
    ) {
        diagnostics.push(
            &service.id,
            "a Cargo SDK package cannot name an npm registry",
        );
    }
    let dependency = runtime(&options.runtime)
        .map_err(|message| diagnostics.push(&service.id, message))
        .ok();
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    let source = generate_client(service)?;
    let manifest = format!(
        "# Generated by crucible. Change the generation configuration and regenerate.\n[package]\nname = {}\nversion = {}\nedition = \"2024\"\nrust-version = \"1.85\"\ndescription = {}\n{}\n# docs.rs builds the API reference once, for the platform every runtime\n# dependency supports; the crate has no platform-specific API.\n[package.metadata.docs.rs]\nall-features = true\ntargets = [\"x86_64-unknown-linux-gnu\"]\n\n[dependencies]\n{RUNTIME} = {}\n\n[workspace]\n",
        literal(&name),
        literal(&options.package_version),
        literal(
            metadata
                .description
                .as_deref()
                .unwrap_or(&format!("Rust SDK for {}", service.id))
        ),
        package_metadata(metadata),
        dependency.expect("validated runtime")
    );
    let declared = crate::client_api::declared_names(service);
    let exports: Vec<_> = [
        "BigDecimal",
        "BigInteger",
        "Blob",
        "BuildError",
        "CallOptions",
        "CancellationToken",
        "Config",
        "Error",
        "Field",
        "Identity",
        "Interceptor",
        "ResponseMetadata",
        "Retry",
        "ServiceError",
        "Token",
        "UnknownError",
        "UnknownUnion",
    ]
    .into_iter()
    .filter(|name| !declared.contains(*name))
    .collect();
    // Always expose the complete runtime under a namespace. Top-level shortcuts
    // omit names occupied by generated API types so valid model names still work.
    let api = format!(
        "\n/// Shared runtime configuration and transport types for this SDK.\npub use ::crucible_client_runtime_rust as runtime;\npub use ::crucible_client_runtime_rust::{{{}}};\n",
        exports.join(", ")
    );
    // The README, the configured one or else the generated one, is the
    // crate's documentation, as docs.rs and crates.io show it. Its code
    // blocks are prose, not tests a consumer's `cargo test` runs.
    let docs = "#![cfg_attr(not(doctest), doc = include_str!(\"../README.md\"))]\n\n";
    let mut files = vec![
        File {
            path: "Cargo.toml".into(),
            contents: manifest,
        },
        File {
            path: "src/lib.rs".into(),
            contents: format!("{docs}{source}{api}"),
        },
        // `cargo fmt --all` visits path dependencies. Keep generated sources
        // deterministic while allowing consumers to format their own packages.
        File {
            path: ".rustfmt.toml".into(),
            contents: "# Generated by crucible. Format the generator, then regenerate.\ndisable_all_formatting = true\n".into(),
        },
    ];
    let surface = crate::surface(service, options);
    let facts = crate::snippet::guide(service, options);
    files.push(File {
        path: guide::README.into(),
        contents: metadata
            .readme
            .clone()
            .unwrap_or_else(|| guide::readme(service, &surface, &facts)),
    });
    files.push(File {
        path: guide::AGENTS.into(),
        contents: guide::agents(service, &surface, &facts),
    });
    if let Some(license) = &metadata.license_file {
        files.push(File {
            path: "LICENSE".into(),
            contents: license.clone(),
        });
    }
    Ok(files)
}

/// The Cargo package a client package is generated as: the configured name,
/// or the service name in kebab case followed by `-sdk`.
pub fn client_package_name(service: &Service, options: &ClientOptions) -> String {
    options
        .package_name
        .clone()
        .unwrap_or_else(|| format!("{}-sdk", names::snake(service.id.name()).replace('_', "-")))
}

/// `[package]` keys for the common metadata.
fn package_metadata(metadata: &crucible_codegen_common::PackageMetadata) -> String {
    let mut keys = String::new();
    let mut key = |name: &str, value: String| {
        keys.push_str(name);
        keys.push_str(" = ");
        keys.push_str(&value);
        keys.push('\n');
    };
    let list = |values: &[String]| {
        let values: Vec<String> = values.iter().map(|value| literal(value)).collect();
        format!("[{}]", values.join(", "))
    };
    if let Some(license) = &metadata.license {
        key("license", literal(license));
    }
    if metadata.license_file.is_some() {
        key("license-file", literal("LICENSE"));
    }
    if !metadata.authors.is_empty() {
        key("authors", list(&metadata.authors));
    }
    for (name, value) in [
        ("repository", &metadata.repository),
        ("homepage", &metadata.homepage),
        ("documentation", &metadata.documentation),
    ] {
        if let Some(value) = value {
            key(name, literal(value));
        }
    }
    key("readme", literal("README.md"));
    if !metadata.keywords.is_empty() {
        key("keywords", list(&metadata.keywords));
    }
    // A Git channel is never a registry (docs/sdk-packaging.md's table), and
    // a private package is never published from its manifest either.
    if metadata.private || metadata.registry == Some(crucible_codegen_common::Registry::Git) {
        key("publish", "false".into());
    }
    keys
}

fn runtime(dependency: &RuntimeDependency) -> Result<String, String> {
    match dependency {
        RuntimeDependency::Auto => {
            let revision = crate::source_revision().ok_or("this generator has no verified Crucible Git provenance; select an explicit runtime Git repository/revision or a local development runtime path")?;
            Ok(format!(
                "{{ version = {}, git = {}, rev = {} }}",
                literal(env!("CARGO_PKG_VERSION")),
                literal(REPOSITORY),
                literal(revision)
            ))
        }
        RuntimeDependency::Git {
            repository,
            revision,
            version_requirement,
        } => {
            semver::VersionReq::parse(version_requirement).map_err(|error| {
                format!("invalid runtime Git version requirement {version_requirement:?}: {error}")
            })?;
            if repository.is_empty()
                || repository.chars().any(char::is_control)
                || repository.trim() != repository
            {
                return Err("runtime Git repository must be nonempty and contain no control characters or outer whitespace".into());
            }
            let url = url::Url::parse(repository)
                .map_err(|error| format!("invalid runtime Git repository URL: {error}"))?;
            if !matches!(url.scheme(), "https" | "http" | "ssh" | "git" | "file") {
                return Err(
                    "runtime Git repository must use https, http, ssh, git or file URL".into(),
                );
            }
            if revision.is_empty()
                || revision.chars().any(char::is_control)
                || revision.trim() != revision
            {
                return Err("runtime Git revision must be nonempty and contain no control characters or outer whitespace".into());
            }
            Ok(format!(
                "{{ version = {}, git = {}, rev = {} }}",
                literal(version_requirement),
                literal(repository),
                literal(revision)
            ))
        }
        RuntimeDependency::Path(path) => {
            if !path.is_absolute() {
                return Err("local runtime path must be absolute so the generated SDK does not depend on its output location".into());
            }
            let text = path
                .to_str()
                .ok_or("local runtime path must be valid UTF-8")?;
            if text.chars().any(char::is_control) {
                return Err("local runtime path must contain no control characters".into());
            }
            let version = local_runtime_version(path)?;
            Ok(format!(
                "{{ version = {}, path = {} }}",
                literal(&version),
                literal(text)
            ))
        }
    }
}

fn local_runtime_version(path: &std::path::Path) -> Result<String, String> {
    let manifest = path
        .join("Cargo.toml")
        .canonicalize()
        .map_err(|error| format!("cannot locate local runtime Cargo.toml: {error}"))?;
    // Cargo owns workspace inheritance. Metadata without dependency resolution
    // reads the effective package version without fetching or building anything.
    let output =
        std::process::Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
            .args([
                "metadata",
                "--no-deps",
                "--offline",
                "--format-version",
                "1",
                "--manifest-path",
            ])
            .arg(&manifest)
            .output()
            .map_err(|error| format!("cannot read local runtime Cargo metadata: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "cannot read local runtime Cargo metadata: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    let metadata: serde_json::Value = serde_json::from_slice(&output.stdout)
        .map_err(|error| format!("invalid local runtime Cargo metadata: {error}"))?;
    let package = metadata["packages"]
        .as_array()
        .and_then(|packages| {
            packages.iter().find(|package| {
                package["manifest_path"].as_str().is_some_and(|path| {
                    std::path::Path::new(path).canonicalize().ok().as_ref() == Some(&manifest)
                })
            })
        })
        .ok_or("local runtime Cargo metadata does not contain the selected package")?;
    if package["name"].as_str() != Some(RUNTIME) {
        return Err(format!(
            "local runtime path must name the {RUNTIME} Cargo package"
        ));
    }
    let version = package["version"]
        .as_str()
        .ok_or("local runtime Cargo metadata has no package version")?;
    semver::Version::parse(version)
        .map_err(|error| format!("invalid local runtime Cargo package version: {error}"))?;
    Ok(version.into())
}

fn literal(value: &str) -> String {
    serde_json::to_string(value).expect("strings serialize")
}

fn valid_name(name: &str) -> bool {
    name.bytes()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == b'_')
        && name
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
        && name != "_"
        && names::escape_identifier(&name.replace('-', "_")) == name.replace('-', "_")
}
